#pragma once
#ifndef CONSOLE_CLI_MANUAL_COVERAGE_VALIDATION_H
#define CONSOLE_CLI_MANUAL_COVERAGE_VALIDATION_H

// ===========================================================================
// CliManualCoverageValidation -- hecke-extensions slot 18, WP-M (owner ruling
// 2026-10-03): the LaTeX user manual of the command line and the console,
// docs/latex/cli_manual.tex, may not drift from the binary.
//
// The manual's reference tables (verbs, types, settings, the CLI tokens of
// every parser, the campaign spec keys, the usage texts, the validation
// roster) are GENERATED by this TU into docs/latex/cli_manual/*.tex:
//
//     CLI_MANUAL_EMIT=<scratch-dir> ./cohomology_app CliManualCoverageValidation
//
// writes them into <scratch-dir> (which must exist and must lie OUTSIDE the
// source tree, the HECKE_DUMP_TAU rule), and
// docs/latex/tools/gen_cli_manual_tables.sh <binary> copies them into the tree
// (or, with --check, only diffs).  Unset, the validation is read-only and
// checks (fast tier):
//   (1) every committed generated file equals what this binary generates;
//   (2) every registered verb / type / setting / validation and every CLI
//       token of the manual's token table appears in the committed tables;
//   (3) cli_manual.tex \input's every generated file;
//   (4) the token table equals what the parsers' sources compare against
//       (main.cpp, Bench/, Campaign/, Console/Core/ConsoleCli.cpp,
//       HeckeExt/HeckeAtlasCli.cpp, the --backend parser): a flag added to a
//       parser without a manual row fails, and so does a row for a flag no
//       parser reads;
//   (5) the top-level usage text equals Console/scripts/cli_frozen/help.stdout
//       (itself gated by ConsoleCliPreservationValidation);
//   (6) every line of every \excerptfrom{<script>} block of cli_manual.tex
//       occurs in that script, and every \octranscript{<name>} names an
//       existing frozen .expected transcript -- so worked examples are quoted,
//       never invented.
// Files are read through the repository root (OC_SOURCE_DIR, then the
// executable's and the working directory's parents); without a checkout the
// validation prints [SKIP].
// ===========================================================================

#include <cstdint>
#include <string>
#include <vector>

uint32_t CliManualCoverageValidation();

namespace cli_manual {

struct GeneratedFile {
    std::string name;   // file name under docs/latex/cli_manual/
    std::string text;
};

// The generated include files: a pure function of the binary's registries and
// built-in help texts (no environment value, timing or machine property).
std::vector<GeneratedFile> GenerateTables();

} // namespace cli_manual

#endif // CONSOLE_CLI_MANUAL_COVERAGE_VALIDATION_H
