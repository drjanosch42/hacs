std::string TokenTable(const std::string& ctx) {
    std::string o = kHeader;
    const bool spec = (ctx == "spec");
    o += "\\begin{tokentable}{" + std::string(spec ? "Key" : "Token") + "}{" +
         std::string(spec ? "Value / default" : "Arguments") + "}\n";
    for (const TokenRow& r : kTokens) {
        if (ctx != r.ctx) continue;
        std::string cell;
        bool first = true;
        for (const std::string& t : SplitAliases(r.tokens)) {
            if (!first) cell += ", ";
            first = false;
            cell += "\\clitok{" + Tex(t, true) + "}";
            if (!IsSynthetic(t)) cell += IndexEntry(t, CtxWhat(ctx));
        }
        const std::string args = r.args;
        o += cell + " & " + (args.empty() ? std::string("--") : (spec ? Prose(args) : Code(args))) + " & " +
             Prose(r.desc) + " \\\\\n";
    }
    o += "\\end{tokentable}\n";
    return o;
}

