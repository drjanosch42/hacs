std::vector<std::string> SplitAliases(const std::string& s) {
    std::vector<std::string> out;
    std::string cur;
    for (char c : s) {
        if (c == '|') { out.push_back(cur); cur.clear(); }
        else cur += c;
    }
    out.push_back(cur);
    return out;
}

bool IsSynthetic(const std::string& tok) {
    return tok.empty() || tok[0] == '<' || tok == "(none)";
}

