// Escapes plain text for LaTeX.  In `code` mode every '-' becomes "-{}" so
// that no font ever ligates "--" into a dash.
std::string Tex(const std::string& s, bool code = false) {
    std::string o;
    for (char c : s) {
        switch (c) {
            case '\\': o += "\\textbackslash{}"; break;
            case '{': o += "\\{"; break;
            case '}': o += "\\}"; break;
            case '$': o += "\\$"; break;
            case '&': o += "\\&"; break;
            case '#': o += "\\#"; break;
            case '%': o += "\\%"; break;
            case '_': o += "\\_"; break;
            case '^': o += "\\textasciicircum{}"; break;
            case '~': o += "\\textasciitilde{}"; break;
            case '<': o += "\\textless{}"; break;
            case '>': o += "\\textgreater{}"; break;
            case '|': o += "\\textbar{}"; break;
            case '"': o += "\\textquotedbl{}"; break;
            case '\n': o += ' '; break;
            case '-': o += code ? "-{}" : "-"; break;
            default: o += c;
        }
    }
    return o;
}

// Code in running text: breakable after ", " and before "(".
std::string Code(const std::string& s) {
    std::string esc = Tex(s, /*code=*/true);
    std::string o;
    for (std::size_t i = 0; i < esc.size(); ++i) {
        o += esc[i];
        if (esc[i] == ',' && i + 1 < esc.size() && esc[i + 1] == ' ') o += "\\allowbreak{}";
    }
    return "\\texttt{" + o + "}";
}

// Plain text with `code` spans.
std::string Prose(const std::string& s) {
    std::string o;
    std::size_t i = 0;
    while (i < s.size()) {
        const std::size_t open = s.find('`', i);
        if (open == std::string::npos) { o += Tex(s.substr(i)); break; }
        const std::size_t close = s.find('`', open + 1);
        if (close == std::string::npos) { o += Tex(s.substr(i)); break; }
        o += Tex(s.substr(i, open - i));
        o += Code(s.substr(open + 1, close - open - 1));
        i = close + 1;
    }
    return o;
}

// makeindex sort key: leading dashes dropped, the specials quoted.
std::string IndexKey(const std::string& s) {
    std::size_t b = 0;
    while (b < s.size() && s[b] == '-') ++b;
    std::string o;
    for (std::size_t i = b; i < s.size(); ++i) {
        const char c = s[i];
        if (c == '!' || c == '@' || c == '|' || c == '"') o += '"';
        if (c == '\\' || c == '{' || c == '}') continue;
        o += c;
    }
    return o.empty() ? std::string("-") : o;
}

std::string IndexEntry(const std::string& name, const std::string& what) {
    // \index{key@\texttt{escaped} (what)}; the display text escapes '!' / '@' /
    // '|' / '"' for makeindex too.
    std::string disp = Tex(name, true);
    std::string q;
    for (char c : disp) {
        if (c == '!' || c == '@' || c == '|' || c == '"') q += '"';
        q += c;
    }
    std::string w = what;
    if (!w.empty() && w[0] == '-') w = "\\texttt{" + Tex(w, true) + "}";
    return "\\index{" + IndexKey(name) + "@\\texttt{" + q + "}" + (w.empty() ? "" : " (" + w + ")") + "}";
}

std::string Usage(const std::string& text) {
    std::string t = text;
    if (!t.empty() && t.back() != '\n') t += '\n';
    return std::string(kHeader) + "\\begin{clihelp}\n" + t + "\\end{clihelp}\n";
}

template <class F>
std::string CaptureStdout(F f) {
    std::ostringstream buf;
    std::streambuf* old = std::cout.rdbuf(buf.rdbuf());
    try {
        f();
    } catch (...) {
        std::cout.rdbuf(old);
        throw;
    }
    std::cout.rdbuf(old);
    return buf.str();
}

