std::string VerbsTex(const Registry& reg) {
    std::string o = kHeader;
    std::string group;
    bool open = false;
    for (const std::string& name : reg.verb_names()) {
        const VerbEntry* v = reg.find_verb(name);
        if (v == nullptr) continue;
        if (v->group != group) {
            if (open) o += "\\end{verbgroup}\n";
            group = v->group;
            o += "\\begin{verbgroup}{" + Tex(group) + "}\n";
            open = true;
        }
        bool first = true;
        for (const Overload& ov : v->overloads) {
            // (slot-19 NB-2, [P] v3.10 Sec. 18.8) the per-overload read_only tag:
            // `ro` (served by --serve), `rw` (not served), `untagged` (no row
            // in Console/Bindings/ReadOnlyTags.cpp: not served, and a failure
            // of ConsoleReadOnlyTagValidation (B)).
            const serve_tags::TagState tag = serve_tags::LookupTag(*v, ov);
            const char* mark = tag == serve_tags::TagState::ReadOnly      ? "ro"
                               : tag == serve_tags::TagState::NotReadOnly ? "rw"
                                                                          : "untagged";
            o += "\\ocverb{" + Tex(v->name, true) + "}{" + Code(ov.sig.to_string(v->name)) + "}{" + Prose(ov.doc) +
                 "}{" + (first ? IndexEntry(v->name, "verb") : std::string()) + "}{" + mark + "}\n";
            first = false;
        }
    }
    if (open) o += "\\end{verbgroup}\n";
    return o;
}

