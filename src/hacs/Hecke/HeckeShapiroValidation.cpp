// numbers below: they are NOT taken from HeckeInducedLocalSystemSmokeValidation.cpp,
// Stage S5's own smoke test, which this file's author did not read for
// numeric values -- only the PUBLIC headers InducedLocalSystem.h and
// HeckeCosetTables.h were consulted for API signatures).
//
// Contract facts used ([C] = docs/latex/hecke_action.tex):
//   * [C, def:inducedls] / [C, prop:lhcompliant]: L_H = L_{Gamma_0(N)} is a
//     valid SimplexRelation-compliant matrix local system on the SAME
//     (K,R), and EquivariantCohomologyOnK computes
//       H^q(K,R;L_{Gamma_0(N)}) ~= H^q(Gamma_0(N); V)      (Shapiro's lemma)
//     for ell >= 5 (Remark "rmk:orbifold" cited by prop:lhcompliant): the
//     isomorphism with GROUP cohomology of Gamma_0(N) (as opposed to only
//     the coarse-space cohomology of the quotient orbifold) requires
//     ell >= 5, because ell >= 5 is coprime to the orders (2 and 3) of
//     every finite elliptic-point stabilizer of Gamma_0(N) <= SL(2,Z);
//     this kills the torsion correction terms of the orbifold-vs-coarse-
//     space comparison (transfer argument: H^{>0}(finite group; F_ell) = 0
//     when ell does not divide the group's order).
//   * [C, obl:shapiro] itself already states the p=2, n=0 case as an
//     oracle (dim H^0=1, dim H^1=1); this file re-derives that number (and
//     the analogous p=3 number) from the underlying topology/group theory
//     rather than transcribing it, and extends the same derivation to
//     ell=101 and to Gamma_0(3).
//
// --- Case n = 0: V = F_ell, the trivial 1-dimensional representation ---
//
// dim H^0(H; F_ell) = 1 for ANY subgroup H <= SL(2,Z) and any ell: the
// trivial module's H-invariants are all of F_ell (H acts trivially by
// definition of the trivial representation). This needs no genus/cusp
// input at all -- it is unconditional. (It is also, separately, a
// necessary consequence of H being generated by torsion + parabolic
// elements acting trivially on F_ell; but the direct argument above
// suffices.)
//
// dim H^1(Gamma_0(N); F_ell), ell >= 5: by the torsion-killing argument
// above, this equals the singular cohomology H^1 of the COARSE
// topological quotient space Y_0(N) := Gamma_0(N)\H (upper half-plane
// modulo Gamma_0(N), NOT compactified -- the cusps are punctures, not
// points) with F_ell coefficients. Y_0(N) is the compact Riemann surface
// X_0(N) (genus g) with its c(>=1) cusps removed. A compact genus-g
// surface minus c >= 1 points deformation retracts onto a wedge of
// (2g + c - 1) circles: Euler characteristic chi(Y_0(N)) =
// chi(X_0(N)) - c = (2 - 2g) - c; since Y_0(N) is homotopy equivalent to a
// connected graph, b_0 = 1 and chi = b_0 - b_1, giving
//     b_1 = 1 - chi = 1 - (2 - 2g - c) = 2g + c - 1.
// Higher Betti numbers of a graph vanish, so the TOPOLOGICAL expectation
// is dim H^2(Y_0(N); F_ell) = 0 too (this is what "record dim H^2" below
// is checking against, but per the task instructions it is RECORDED, not
// hard-asserted, since a nonzero computed value would be a statement
// about the specific (K,R) model, not directly a Shapiro-lemma failure).
//
// Summary: dim H^0 = 1, dim H^1 = 2g + c - 1, dim H^2 "expected" 0 (recorded).
//
// Classical genus/cusp data of X_0(N) (standard modular-curve invariants,
// e.g. Diamond-Shurman, "A First Course in Modular Forms", Ch. 3 tables,
// or any standard reference -- NOT taken from this codebase):
//     X_0(1) = SL(2,Z)\H-bar: g = 0, c = 1  => dim H^1 = 2*0 + 1 - 1 = 0.
//         (Cross-check only, not asserted by this file: matches oracle O1
//          of the implementation plan, dim H^1(SL(2,Z); F_ell) = 0 for
//          n=0, ell >= 5 -- independent confirmation that the 2g+c-1
//          formula is the right one to use here.)
//     X_0(2): g = 0, c = 2  => dim H^1 = 2*0 + 2 - 1 = 1.
//     X_0(3): g = 0, c = 2  => dim H^1 = 2*0 + 2 - 1 = 1.
// These give the two HARD-ASSERTED targets below: dim H^0 = 1, dim H^1 = 1
// for both L_{Gamma_0(2)} and L_{Gamma_0(3)} at n=0, ell in {5,101} (the
// Gamma_0(3) case per the Q2 ruling of the plan's Sec. 0.1, which upgrades
// it from "record" to "assert").
//
// --- Case n = 2, N = 2, ell = 5 (regression anchor, NOT hard-asserted) --
//
// An independent characteristic-0 count would use the Eichler-Shimura
// isomorphism dim H^1(Gamma_0(2); Sym^2(C)) = 2*dim S_4(Gamma_0(2)) +
// dim Eis_4(Gamma_0(2)) = 2*0 + 2 = 2 (S_4(Gamma_0(2)) = 0 is classical --
// the first nonzero cusp form space for level 2 appears at weight 8; the
// weight-4 Eisenstein space for Gamma_0(2) has dimension = the number of
// cusps = 2, since weight >= 3 Eisenstein series are one-per-cusp for
// trivial character). However, transporting this characteristic-0 count
// to F_5 is NOT safe to hard-assert here without a separate boundedness/
// congruence argument: the level-1 weight-4 Eisenstein series already has
// 5 in the denominator of its Bernoulli-number normalization
// (B_4 = -1/30 = -1/(2*3*5)), i.e. ell = 5 divides the denominator
// relevant to exactly this weight, so ell = 5 is a priori a candidate
// congruence/exceptional prime for this specific (N,k) and a naive
// "same dimension mod ell" transport is not something this validation
// agent can independently certify from first principles. Per the task's
// explicit license ("you may hard-assert whatever you can independently
// justify, else record"), this case is therefore RUN AND RECORDED ONLY:
// all three dimensions are printed as a regression anchor. Only the
// unconditional structural facts (pipeline completes; the dimension
// vector has one entry per dimension of K, i.e. size 3) are hard-asserted.
// =====================================================================

