namespace {

struct ShapiroRunResult {
    bool ok = false; // true iff the whole pipeline (cosets -> L_H -> cohomology) ran without throwing
    std::vector<uint32_t> dims; // get_H_eq_dimensions(), valid only if ok
};

// Runs the full independent pipeline named in the task: HeckeCosetTables(p,1,ell,n)
// -> hecke::MakeInducedLocalSystemGamma0(K, cosets, ell, n) -> EquivariantCohomologyOnK::compute_cohomology().
ShapiroRunResult RunGamma0Case(uint64_t p_hecke, uint32_t n_sym, uint32_t ell) {
    ShapiroRunResult result;
    try {
        const SimplicialComplex K = CreateSL2ZFundamentalDomainTriangulation();
        const hecke::HeckeCosetTables cosets(p_hecke, /*r=*/1, ell, n_sym);
        const LocalSystemSimplicialComplex L_H =
            hecke::MakeInducedLocalSystemGamma0(K, cosets, ell, n_sym);

        EquivariantCohomologyOnK eq_cohom(&L_H);
        eq_cohom.compute_cohomology();

        result.dims = eq_cohom.get_H_eq_dimensions();
        result.ok = true;
    } catch (const std::exception& e) {
        std::cout << "HeckeShapiroValidation: EXCEPTION for p_hecke=" << p_hecke
                   << " n_sym=" << n_sym << " ell=" << ell << ": " << e.what() << std::endl;
    }
    return result;
}

// Case-1/3 pattern: L_{Gamma_0(p_hecke)}, n=0, hard-assert dim H^0 = dim H^1 = 1
// (derivation above), record dim H^2. Returns 1 on failure, 0 on success.
uint32_t CheckN0HardAssertCase(uint64_t p_hecke, uint32_t ell, uint32_t expected_h1,
                                const std::string& x0_label) {
    const ShapiroRunResult r = RunGamma0Case(p_hecke, /*n_sym=*/0, ell);
    if (!r.ok) {
        return 1;
    }
    if (r.dims.size() < 2) {
        std::cout << "HeckeShapiroValidation: FAILED Gamma_0(" << p_hecke << "), n=0, ell=" << ell
                   << ": get_H_eq_dimensions() has size " << r.dims.size()
                   << " (expected >= 2)." << std::endl;
        return 1;
    }

    const uint32_t h0 = r.dims[0];
    const uint32_t h1 = r.dims[1];
    const uint32_t h2 = (r.dims.size() > 2) ? r.dims[2] : 0;

    bool ok = true;
    if (h0 != 1) {
        std::cout << "HeckeShapiroValidation: FAILED Gamma_0(" << p_hecke << "), n=0, ell=" << ell
                   << ": expected dim H^0 = 1 (Shapiro; trivial-module invariants, unconditional), got "
                   << h0 << "." << std::endl;
        ok = false;
    }
    if (h1 != expected_h1) {
        std::cout << "HeckeShapiroValidation: FAILED Gamma_0(" << p_hecke << "), n=0, ell=" << ell
                   << ": expected dim H^1 = " << expected_h1 << " (Shapiro + " << x0_label
                   << ": genus/cusp formula 2g+c-1), got " << h1 << "." << std::endl;
        ok = false;
    }

    std::cout << "HeckeShapiroValidation: Gamma_0(" << p_hecke << "), n=0, ell=" << ell
               << ": dim H^0=" << h0 << " dim H^1=" << h1
               << " dim H^2=" << h2 << " (H^2 recorded, not asserted) -> "
               << (ok ? "OK" : "MISMATCH") << std::endl;

    return ok ? 0u : 1u;
}

} // namespace

uint32_t HeckeShapiroValidation() {
    uint32_t failures = 0;

    // -----------------------------------------------------------------
    // Case 1: L_{Gamma_0(2)}, n=0, ell in {5,101}.
    // Independently derived expectation (see file header): X_0(2) has
    // genus 0, 2 cusps => dim H^1 = 2*0 + 2 - 1 = 1. dim H^0 = 1 always.
    // -----------------------------------------------------------------
    for (uint32_t ell : { 5u, 101u }) {
        failures += CheckN0HardAssertCase(/*p_hecke=*/2, ell, /*expected_h1=*/1u,
                                           "X_0(2) (genus 0, 2 cusps)");
    }

    // -----------------------------------------------------------------
    // Case 2: L_{Gamma_0(2)}, n=2, ell=5. Regression anchor only -- see
    // the file header for why this is NOT independently hard-assertable
    // by this agent (ell=5 divides the weight-4 Bernoulli denominator).
    // Only unconditional structural facts are hard-asserted here:
    // pipeline completion and the shape of the dimension vector.
    // -----------------------------------------------------------------
    {
        const ShapiroRunResult r = RunGamma0Case(/*p_hecke=*/2, /*n_sym=*/2, /*ell=*/5);
        if (!r.ok) {
            ++failures;
        } else if (r.dims.size() != 3) {
            // K is a 2-dimensional simplicial complex (triangles), so
            // get_H_eq_dimensions() must report one dimension per
            // q in {0,1,2} -- this is a structural fact about the fixed
            // 7-vertex model K, independent of any modular-forms count.
            std::cout << "HeckeShapiroValidation: FAILED Gamma_0(2), n=2, ell=5: "
                          "get_H_eq_dimensions() has size " << r.dims.size()
                       << " (expected exactly 3, one per dimension of K)." << std::endl;
            ++failures;
        } else {
            std::cout << "HeckeShapiroValidation: Gamma_0(2), n=2, ell=5 (regression anchor, "
                          "recorded only, not independently asserted): dim H^0="
                       << r.dims[0] << " dim H^1=" << r.dims[1] << " dim H^2=" << r.dims[2]
                       << std::endl;
        }
    }

    // -----------------------------------------------------------------
    // Case 3: L_{Gamma_0(3)}, n=0, ell in {5,101}. Q2 ruling (plan Sec.
    // 0.1): HARD-ASSERT dim H^1 = 1 (not merely record), same derivation
    // as Case 1: X_0(3) has genus 0, 2 cusps => dim H^1 = 2*0+2-1 = 1.
    // -----------------------------------------------------------------
    for (uint32_t ell : { 5u, 101u }) {
        failures += CheckN0HardAssertCase(/*p_hecke=*/3, ell, /*expected_h1=*/1u,
                                           "X_0(3) (genus 0, 2 cusps)");
    }

    std::cout << "HeckeShapiroValidation: " << failures << " failing case(s) out of 5." << std::endl;
    return failures;
}
