// (LIT-42): T°_{Gamma_1(N)} / p for N = l_0 l_1, computed on Gamma_H(N), H = the prime-to-p part of G_N (the family over
// Lambda = Z_p[Delta], Delta the p-Sylow; their Examples 1.2, 1.3 at (p, l_0) = (5, 11), l_1 = 23, 67) and its
// Hecke-intrinsic reducibility ideal J^red (computed from the Frobenius relations T_q = q psi(q) + psi(q)^{-1} <q>).
