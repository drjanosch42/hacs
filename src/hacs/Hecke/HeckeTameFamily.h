//
// WHAT IS BUILT (pipeline-free, value-free with respect to every shipped object).
//  * FpMat and dense F_p linear algebra (p < 2^16: products accumulate in uint64 without intermediate reduction).
//  * Readings on Q = M / Rel (HeckeGammaH.h's QuotientCoords): the matrix of a symbol operator on Q, on a stable
//    subspace W (given by basis columns) -- by the rows `sel` where W has full rank, so a large operator (T_q, q < 200) is
//    applied only to h |Mer_q| dim W entries -- the cuspidal subspace ker(delta), the generalised eigenspaces and the
//    localisation at a list (operator, eigenvalue).
//  * MatAlgebra -- the unital F_p-algebra generated by commuting matrices (span closure), membership, coordinates.
//  * ReducibilityIdeal (V2) -- J_0 = { a in A : a (x) 1 in JC }, JC the ideal of A (x) B generated by the Frobenius
//    relations, B = F_p[X]/(X^{|Delta|} - 1) (psi tame, through Delta) or (x) F_5[u]/(u^6) (psi allowed to ramify at 5:
//    the 5-part of (Z/125)^x, p = 5 only); the variants of the ansatz used as controls.
//  * RunTameCell -- the per-cell driver (the HPWWE cells of the validation; WAKE-3's survey cells go through it).
// ===========================================================================

