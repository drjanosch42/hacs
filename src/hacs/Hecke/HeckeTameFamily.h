// ---- dense matrices over F_p -----------------------------------------------------------------------------------
struct FpMat {
    uint32_t rows = 0, cols = 0;
    std::vector<uint32_t> a;
    FpMat() = default;
    FpMat(uint32_t r, uint32_t c) : rows(r), cols(c), a(static_cast<size_t>(r) * c, 0) {}
    uint32_t at(uint32_t i, uint32_t j) const { return a[static_cast<size_t>(i) * cols + j]; }
    uint32_t& at(uint32_t i, uint32_t j) { return a[static_cast<size_t>(i) * cols + j]; }
};
FpMat Identity(uint32_t n);
FpMat Mul(const FpMat& A, const FpMat& B, uint32_t p);
FpMat Add(const FpMat& A, const FpMat& B, uint32_t p);
FpMat Sub(const FpMat& A, const FpMat& B, uint32_t p);
FpMat Scale(const FpMat& A, uint64_t s, uint32_t p);
FpMat Transpose(const FpMat& A);
FpMat Power(const FpMat& A, uint64_t e, uint32_t p);
bool IsZero(const FpMat& A);
bool Equal(const FpMat& A, const FpMat& B);
// RREF in place (fully reduced); returns the pivot columns ascending.
std::vector<uint32_t> Rref(FpMat& A, uint32_t p);
uint32_t Rank(FpMat A, uint32_t p);
// A basis of { x : A x = 0 } as the columns of a (cols x k) matrix.
FpMat NullSpace(const FpMat& A, uint32_t p);
// Rows of A selected (in the given order).
FpMat SelectRows(const FpMat& A, const std::vector<uint32_t>& rows);
// X with A X = B, A square invertible; throws otherwise.
FpMat SolveSquare(const FpMat& A, const FpMat& B, uint32_t p);
// det(x - A), low -> high.
std::vector<uint32_t> Charpoly(const FpMat& A, uint32_t p);
// The column spans of A and B (column bases) are equal.
bool SameColumnSpan(const FpMat& A, const FpMat& B, uint32_t p);

// ---- readings on the quotient Q ---------------------------------------------------------------------------------
// [X] on Q in the free-column basis (h x h, columns = images of the basis vectors).
FpMat OnQuotient(const level::QuotientCoords& QC, const level::SymbolOperator& X);
// The rows (indices in [0, h)) where the basis W (h x w, full column rank) is invertible: the pivots of W^T.
std::vector<uint32_t> PivotRows(const FpMat& W, uint32_t p);
// R (w x w) with X W = W R for a STABLE subspace W, read only on the rows sel = PivotRows(W): the coordinates of every
// basis vector of M restricted to sel are tabulated once (m (n + 1) x w), then each operator costs h |image| w.
class SubspaceReader {
public:
    SubspaceReader(const level::QuotientCoords& QC, const FpMat& W);
    FpMat read(const level::SymbolOperator& X) const;
    const std::vector<uint32_t>& sel() const { return sel_; }
private:
    const level::QuotientCoords* QC_;
    FpMat W_, Wsel_inv_;
    std::vector<uint32_t> sel_;
    std::vector<uint32_t> selrow_;   // D x w
};
// R with T W = W R from the full matrix T (h x h); `stable` reports T W == W R entrywise.
FpMat RestrictFull(const FpMat& T, const FpMat& W, uint32_t p, bool* stable);
// ker (R - a)^infinity as columns (w x e), by squaring until the rank is stable.
FpMat GenEigenspace(const FpMat& R, uint32_t a, uint32_t p);
// delta on Q (c x h): column f = [cusp(J)] - [cusp(J S)], J the class of free column f (n = 0); `rel_ok` reports delta(Rel) = 0
// on every stored RREF row.
FpMat BoundaryOnQuotient(const level::SparseCokernel& Q, const level::CuspData& C, bool* rel_ok);

// ---- algebras ---------------------------------------------------------------------------------------------------
class MatAlgebra {
public:
    // The unital algebra generated by the square matrices gens (all w x w), by span closure (BFS on products).
    MatAlgebra(const std::vector<FpMat>& gens, uint32_t p);
    uint32_t dim() const { return static_cast<uint32_t>(basis_.size()); }
    uint32_t w() const { return w_; }
    uint32_t p() const { return p_; }
    const std::vector<FpMat>& basis() const { return basis_; }
    bool contains(const FpMat& X) const;
    std::vector<uint32_t> coords(const FpMat& X) const;      // throws unless X is inside
    FpMat from_coords(const std::vector<uint32_t>& c) const;
    // Structure constants: mult()[i][j] = coords(b_i b_j).
    const std::vector<std::vector<std::vector<uint32_t>>>& mult() const;
    // dim A / (the ideal generated by the given elements), and that ideal's span (rows = coordinate vectors, RREF).
    uint32_t quotient_dim(const std::vector<FpMat>& gens, FpMat* ideal_rref = nullptr) const;
    // The least e with m^e = 0 for the maximal ideal m = the span of the nilpotent part (A local), 0 if not local.
    uint32_t radical_nilpotency() const;
private:
    uint32_t w_ = 0, p_ = 0;
    std::vector<FpMat> basis_;
    FpMat flat_;                      // dim x w^2 (rows = flattened basis)
    std::vector<uint32_t> sel_;       // dim positions where flat_ is invertible
    FpMat sel_inv_;                   // (flat_ restricted to sel_)^{-1}
    mutable std::vector<std::vector<std::vector<uint32_t>>> mult_;
};

// ---- V2: the reducibility ideal -----------------------------------------------------------------------------------
enum class ReducibilityAnsatz : uint8_t {
    kStandard = 0,    // T_q = q psi(q) + psi(q)^{-1} <q>            (the pseudorepresentation's reducibility)
    kSwapped = 1,     // T_q = psi(q) + q psi(q)^{-1} <q>            (equivalent: psi -> psi^{-1} <.>)
    kTrivial = 2,     // T_q = q + <q>                               (psi forced trivial: a control)
    kNoDiamond = 3,   // T_q = q psi(q) + psi(q)^{-1}                (determinant without the diamond: a control)
};
const char* AnsatzName(ReducibilityAnsatz a);

struct FrobeniusDatum {
    uint64_t q = 0;
    uint32_t e = 0;                   // the class of q in Delta = g^e
    uint32_t f = 0;                   // wild: q^{76} = 6^f mod 125
    std::vector<uint32_t> Tq;         // coordinates of T_q|V in A
    std::vector<uint32_t> Dq;         // coordinates of <q>|V in A
};

struct ReducibilityResult {
    uint32_t dim_quotient = 0;        // dim A / J_0
    bool surjective = false;          // A -> C onto (1 (x) X, and 1 (x) Y when wild, in A (x) 1 + JC)
    uint32_t relations = 0;
    FpMat J0;                         // RREF rows: coordinate vectors over A's basis
    std::string case_name() const { return dim_quotient == 1 ? "i" : dim_quotient == 2 ? "ii" : "iii"; }
};
// delta_order = |Delta| (the order of g in G_N / H); one = coordinates of the identity.
ReducibilityResult ReducibilityIdeal(const MatAlgebra& A, const std::vector<FrobeniusDatum>& frob, uint32_t delta_order,
                                     bool wild, ReducibilityAnsatz ansatz);

// ---- the per-cell driver -------------------------------------------------------------------------------------------
struct Presentation {
    std::vector<uint32_t> u_base;     // u(D) = u_base(D)^u_power, coefficients low -> high in D = <g>
    uint32_t u_power = 1;
    std::vector<uint32_t> v;          // v(D)
    uint32_t mu = 0;                  // y^2 = mu z^2
};

struct TameCellSpec {
    uint32_t p = 5;
    uint64_t l0 = 11, l1 = 23;
    uint64_t g = 3;                   // the generator of Delta (<g>, z = <g> - 1)
    std::vector<uint64_t> loc_primes{2, 3, 7, 13, 17, 19};   // T_q at 1 + q for q !| pN; U_l at 1 for l | N
    bool full = true;                 // the full m-part is always computed (the cusp m-part is its intersection with ker delta); false skips W-P4b
    bool algebra = true;              // A = <T_g, <g>> on the cusp m-part, membership of T_q (q < members_qmax), <u>
    uint64_t members_qmax = 60, members_umax = 40;
    bool full_algebra = true;         // W-P4b: the algebra of T_q (q in full_algebra_primes), U_l, <g> on the full m-part
    std::vector<uint64_t> full_algebra_primes{2, 3, 7, 13, 17, 19, 29};
    bool v2 = true;                   // the reducibility ideal, Frobenius relations q < v2_qmax
    uint64_t v2_qmax = 200;
    bool wild = true;                 // the wild variant too (p = 5 only)
    bool controls = false;            // the ansatz variants (swapped / trivial / no diamond)
    bool identities = true;           // the operator identities on Q (spec I6) and the inverse-normalisation control (N4)
    const Presentation* pres = nullptr;   // the preprint's presentation (y, mu), or null
    // (WAKE-3, docs/implementation/slot22/WAKE3_spec.md) the survey route for large h: no memo of full matrices (each
    // localisation operator is built dense, used and freed), every further operator read on the subspace only
    // (SubspaceReader), A = the algebra of T_g, <g>, every Frobenius T_q (q < v2_qmax), T_p, U_l (l | N) and <u>
    // (u < members_umax) -- so A is T°/p up to the finite-q caveat whether or not <T_g, <g>> generates it (dimA_TgD).
    // The identities on Q, the presentation, the wild variant and the controls are not computed (pres, wild, controls,
    // identities and full are ignored).
    bool lean = false;
};

struct TameCellReading {
    uint64_t N = 0;
    std::string H;
    uint32_t m = 0, h = 0, c = 0, nu2 = 0, nu3 = 0;
    int64_t twelve_g = 0;
    bool genus_ok = false, rel_boundary_ok = false;
    uint32_t boundary_rank = 0;
    uint32_t cusp_m = 0, full_m = 0;
    uint32_t rel_escapes = 0;                 // summed over every operator built
    uint32_t dimA = 0;
    uint32_t dimA_TgD = 0;                    // lean: dim <T_g, <g>> on V (members_inside = (dimA_TgD == dimA))
    uint64_t qc_nnz = 0;                      // lean: QuotientCoords entries (the rule-19 sparse term)
    bool members_inside = false;              // every T_q (q < members_qmax, q prime) and <u> (u < members_umax) in A
    bool diamonds_power = false;              // <q> = <g>^{e_q} on V for every Frobenius q
    uint32_t full_alg_dim = 0;
    uint32_t radical_nilpotency = 0;
    bool t5_unipotent = false;                // T_p - 1 nilpotent on V (ordinary)
    uint32_t nonordinary_dim = 0;             // dim of the generalised T_p = 0 eigenspace in V (N5)
    // presentation
    bool pres_done = false, z5 = false, rel = false;
    uint32_t pres_rank = 0;
    uint32_t dim_y = 0, dim_ypz = 0, dim_ymz = 0;
    bool shifted_z5 = false, shifted_rel = false;   // N3 with z' = <g'> - 1, g' = 2
    // V2
    ReducibilityResult red, red_wild;
    bool J_is_y = false, J_is_ypz = false, J_is_ymz = false, wild_same = false;
    std::map<std::string, ReducibilityResult> variants;
    std::map<std::string, bool> variant_same;  // the variant's ideal equals the standard one
    std::map<std::string, bool> identities;   // name -> holds (the N4 entry is expected to FAIL)
    bool v2_done() const { return red.relations > 0; }
    double seconds = 0, peak_rss_mib = 0;
    std::vector<std::string> notes;
};

