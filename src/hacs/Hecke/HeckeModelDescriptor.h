#pragma once
#ifndef HECKE_MODEL_DESCRIPTOR_H
#define HECKE_MODEL_DESCRIPTOR_H

// ===========================================================================
// matrix-engine Phase 6 -- the model descriptor (plan item 7.18 / Q8).
//
// WHY. Until Phase 6 the Hecke pipeline pinned its base complex with a
// LITERAL shape test -- "7 vertices, 11 edges, 5 triangles, dimension 2" --
// written out at four independent sites (HeckeOperatorOnK.cpp,
// HeckeCrossChecks.cpp, HeckeTauTable.cpp, SL2ZTessellationTables.cpp).
// 02-pipeline-consumer-audit.md item 7.18 asks for that literal to become a
// DATUM, so that the engine's block-sparsity planning (and the Phase 6
// campaign driver, which must state the model it swept) is driven by the
// simplex counts N_q and the tau pattern rather than by constants baked into
// an `if`.
//
// WHAT THIS IS NOT. This is deliberately NOT a model abstraction layer: the
// SL(2,Z) 7-vertex model remains the ONLY instance, the relation table is
// still generated by GenerateSL2ZRelationsWithGroupData, and the predicate
// tested at each site is exactly the predicate that was tested before -- the
// change is value-preserving by construction (the golden harness gates it).
// It is the single place where "which model is this?" is written down, so a
// refined model (the -I / odd-n gap, docs/KNOWN_ISSUES.md) can be added as a
// second instance without hunting for literals.
//
// The descriptor carries:
//   * a stable machine-readable `name` (the campaign JSON's "model" field and
//     the shape-signature component of campaign::plan_campaign),
//   * `dimension` and the per-degree simplex counts `simplex_counts`
//     (N_0, ..., N_dim) -- the numbers the block grids are built from,
//   * `relation_source`, the name of the function that is the single source of
//     truth for the local-system relations on this model (documentation and
//     JSON provenance; not called through here).
// ===========================================================================

#include <cstdint>
#include <string>
#include <vector>

class SimplicialComplex;

namespace hecke {

struct SimplicialModelDescriptor {
    std::string name;                       // e.g. "sl2z_7vertex"
    std::string description;                // human-readable one-liner
    uint32_t dimension = 0;                 // top simplex dimension
    std::vector<uint32_t> simplex_counts;   // N_q, q = 0 .. dimension
    std::string relation_source;            // the generator function's name

    // Number of cochain degrees the pipeline reports (q = 0 .. dimension).
    uint32_t num_degrees() const { return dimension + 1; }

    uint32_t num_simplices(uint32_t q) const {
        return q < simplex_counts.size() ? simplex_counts[q] : 0u;
    }

    // "7/11/5" -- the shape as it used to be spelled in the error messages.
    std::string shape_string() const;

    // True iff K has this descriptor's dimension and simplex counts.
    bool matches(const SimplicialComplex& K) const;
};

// The one shipped instance: the fixed 7-vertex triangulation of SL(2,Z)\H
// produced by CreateSL2ZFundamentalDomainTriangulation() (7 vertices,
// 11 edges, 5 triangles).
const SimplicialModelDescriptor& SL2Z7VertexModel();

// Descriptor lookup by name; nullptr if unknown. ("sl2z_7vertex" is the only
// registered name today; the campaign spec's `model =` key goes through here
// so an unknown model is a spec error rather than a silent default.)
const SimplicialModelDescriptor* FindModelDescriptor(const std::string& name);

// Asserts that K is the model `d` describes. Throws std::runtime_error whose
// message begins with `who` (the calling class) on any mismatch, and on a
// null K. This is the replacement for the four literal 7/11/5 tests.
void RequireModel(const SimplicialModelDescriptor& d, const SimplicialComplex* K,
                  const char* who);

} // namespace hecke

#endif // HECKE_MODEL_DESCRIPTOR_H
