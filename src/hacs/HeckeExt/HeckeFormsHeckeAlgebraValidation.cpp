void ArmN() {
    std::cout << "-- (N) precision control\n";
    const CuspSpace S = BuildCuspSpace(144, 7, 12 * 5 + 1);   // enough for p <= 5 only
    bool threw = false;
    try {
        (void)HeckeOnCusp(S, 7);
    } catch (const std::exception&) {
        threw = true;
    }
    Check(threw, "negative control -- T_7 beyond the q-expansion precision throws");
    bool ok = true;
    try {
        (void)HeckeOnCusp(S, 5);
    } catch (const std::exception&) {
        ok = false;
    }
    Check(ok, "T_5 within the precision computes");
}


