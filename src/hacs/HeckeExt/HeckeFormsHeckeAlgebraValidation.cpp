struct FormsSide {
    bool ran = false;
    uint32_t dim = 0, T_dim = 0, T_embdim = 0, T_loewy = 0, T_socle = 0;
    bool T_gor = false, T_local = false;
    std::vector<uint32_t> T_hilbert;
    bool drv_gen = false;     // the driver's primes generate T_m / ell
    uint32_t joint = 0, Tc = 0;
    bool quotient = false, equal = false;
};

FormsSide CompareForms(const CuspSpace& X, const std::vector<uint64_t>& P, const std::vector<ExtMatrix>& T,
                       const std::vector<uint64_t>& sp, const std::vector<uint32_t>& sys, const LocalAlgebra& L,
                       uint32_t ell) {
    FormsSide o;
    const FormsBlock B = LocaliseAtSystem(X, P, T, sp, sys);
    o.ran = true;
    o.dim = B.dim;
    if (B.dim == 0) return o;
    o.T_dim = B.A.dim_A;
    o.T_embdim = B.A.dim_tangent;
    o.T_hilbert = B.A.hilbert;
    o.T_loewy = B.A.nilpotency_index;
    o.T_socle = B.A.dim_socle;
    o.T_gor = B.A.gorenstein;
    o.T_local = B.A.local;
    std::vector<ExtMatrix> tT, joint;
    for (size_t j = 0; j < L.primes.size(); ++j) {
        const size_t idx = static_cast<size_t>(std::find(P.begin(), P.end(), L.primes[j]) - P.begin());
        tT.push_back(B.t[idx]);
        joint.push_back(BlockDiag(B.t[idx], L.t[j]));
    }
    o.Tc = ComputeAlgebraInvariants(tT, ell).dim_A;
    o.joint = ComputeAlgebraInvariants(joint, ell).dim_A;
    o.drv_gen = o.Tc == B.A.dim_A;
    o.quotient = o.joint == o.Tc;
    o.equal = o.quotient && o.drv_gen && L.dim_A == B.A.dim_A;
    return o;
}

