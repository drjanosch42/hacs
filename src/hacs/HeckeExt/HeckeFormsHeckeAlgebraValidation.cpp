        // block T(X)_m has dimension dim X_m (X = S_k, M_k), i.e. T / ell -> End(X_m) is injective, X_m = T_m^dual.
        if (fs.dim != 0 && S_gen) Check(fs.T_dim == fs.dim, tag + ": dim T(S_k)_m == dim S_k(F_ell)_m (faithful, Theorem A(3))");
        if (fm.dim != 0 && M_gen) Check(fm.T_dim == fm.dim, tag + ": dim T(M_k)_m == dim M_k(F_ell)_m (faithful, Theorem A(3))");
        // (slot-12 WP-14, F9; slot-15 WP-20 torsion guard; audit repair, WP-4 referee ruling on WP-19 question 5)
        // Eichler-Shimura, corrected: on an H^1 row D = dim T(S_k)_m + dim T(M_k)_m + h, h = dim H^0(Gamma; M_n)_lambda
        // (WP-19 Theorem B).  The corrected identity is GATED on every H^1 row; h = 0 is F9 proper.
