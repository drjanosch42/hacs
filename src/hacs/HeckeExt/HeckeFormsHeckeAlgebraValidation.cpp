void ArmD() {
    std::cout << "-- (D) duality and Sturm sufficiency\n";
    for (uint32_t k : {36u, 84u, 144u}) {
        const uint32_t ell = 7;
        const uint32_t d0 = k / 12;
        const CuspSpace S = BuildCuspSpace(k, ell, std::max(ResidualPrecision(d0, 31), d0 * d0 + 2));
        Check(ResidualDepth(S, 31) >= 2 * S.d, tag0(k) + ": the residual of T_31 f_j is checked on >= d coefficients beyond a_1 .. a_d");
        const std::string tag = "S_" + std::to_string(k) + "(F_7)";
        const std::vector<ExtMatrix> Tn = SturmRangeOperators(S);
        Check(SpanDim(Tn, ell) == S.d, tag + ": dim span{T_1 .. T_d} == d (T / ell faithful, duality)");
        // (slot-12 WP-11, A6) the Sturm set is the primes <= k/12 (the Sturm bound
        // of S_k(SL_2(Z))); p <= 7 is a separate, separately labelled check.
        const std::vector<uint64_t> sturm = PrimesUpTo(d0);
        const std::vector<uint64_t> small = PrimesUpTo(std::max(d0, 7u));
        const std::vector<uint64_t> all = PrimesUpTo(31);
        const AlgebraInvariants As = ComputeAlgebraInvariants(HeckeList(S, sturm), ell);
        const AlgebraInvariants A7 = ComputeAlgebraInvariants(HeckeList(S, small), ell);
        const AlgebraInvariants Aa = ComputeAlgebraInvariants(HeckeList(S, all), ell);
        Check(As.dim_A == S.d, tag + ": F_7[T_p : p <= k/12 (Sturm)] has dimension d");
        Check(A7.dim_A == S.d, tag + ": F_7[T_p : p <= max(k/12, 7)] has dimension d");
        Check(Aa.dim_A == As.dim_A, tag + ": primes <= 31 add nothing (Sturm sufficiency)");
        Check(As.dim_rad == Aa.dim_rad && As.components == Aa.components,
              tag + ": same radical and component count with primes <= 31");
        std::cout << "    " << tag << ": d=" << S.d << " dim T/7=" << As.dim_A << " components=" << As.components
                  << " dim rad=" << As.dim_rad << "\n";
    }
}

