void ArmQ() {
    std::cout << "-- (Q) the q-expansion substrate\n";
    const int64_t tau[] = {1, -24, 252, -1472, 4830, -6048, -16744, 84480, -113643, -115920};
    const QSeries D = hecke_ext::forms::DeltaSeries(7, 12);
    for (int n = 1; n <= 10; ++n)
        Check(D[n] == static_cast<uint32_t>(((tau[n - 1] % 7) + 7) % 7), "tau(" + std::to_string(n) + ") mod 7");
    Check(D[0] == 0, "Delta has no constant term");
    const int64_t tau_p[] = {-24, 252, 4830, -16744, 534612};   // p = 2, 3, 5, 7, 11
    const uint32_t ps[] = {2, 3, 5, 7, 11};
    for (uint32_t ell : {7u, 11u, 13u}) {
        const CuspSpace S = BuildCuspSpace(12, ell, ResidualPrecision(1, 11));
        Check(S.d == 1, "dim S_12 = 1");
        for (int i = 0; i < 5; ++i) {
            const ExtMatrix T = HeckeOnCusp(S, ps[i]);
            const uint32_t want = static_cast<uint32_t>(((tau_p[i] % static_cast<int64_t>(ell)) + ell) % ell);
            Check(T.data[0][0] == want, "T_" + std::to_string(ps[i]) + " on S_12 = tau(p) mod " + std::to_string(ell));
        }
    }
    for (uint32_t k : {84u, 144u}) {
        const CuspSpace S = BuildCuspSpace(k, 7, ResidualPrecision(k / 12, 11));
        const std::vector<uint64_t> P = PrimesUpTo(11);
        const std::vector<ExtMatrix> T = HeckeList(S, P);
        for (size_t a = 0; a < T.size(); ++a)
            for (size_t b = a + 1; b < T.size(); ++b)
                Check(T[a] * T[b] == T[b] * T[a], "S_" + std::to_string(k) + ": T_" + std::to_string(P[a]) + " T_"
                                                      + std::to_string(P[b]) + " commute");
    }
}

