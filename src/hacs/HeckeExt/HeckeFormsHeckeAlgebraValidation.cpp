struct CellExpect {
    uint32_t n;
    uint32_t ell;
    // The referee's forms-side datum for the cell's largest non-reduced ideal.
    uint32_t dim_T;
    uint32_t embdim_T;
    std::vector<uint32_t> hilbert_T;
    uint32_t loewy_T;
    uint32_t socle_T;
    bool     gorenstein_T;
    // The census's A for that ideal.
    uint32_t dim_A;
    std::vector<uint32_t> hilbert_A;
};

struct ArmRResult {
    bool have_142_block = false;
    FormsBlock block_142;
    uint32_t lambda2_142 = 0;
};

void ArmRC(ArmRResult& out) {
    std::cout << "-- (R) the referee datum and (C) A a quotient of T_m / ell\n";
    const std::vector<CellExpect> cells = {
        {34, 7, 2, 1, {1, 1}, 2, 1, true, 2, {1, 1}},
        {82, 7, 4, 3, {1, 3}, 2, 3, false, 3, {1, 2}},
        {142, 7, 6, 3, {1, 3, 2}, 3, 3, false, 4, {1, 3}},
    };
    for (const CellExpect& e : cells) {
        const std::string cell = "(" + std::to_string(e.n) + ", " + std::to_string(e.ell) + ")";
        ExtDriverOptions o;
        o.run_commutant = false;
        o.run_sturm = false;
        HeckeExtDriver drv(e.n, e.ell, o);
        drv.run();
        const HeckeExtRecord& rec = drv.record();

        const uint32_t k = e.n + 2;
        const std::vector<uint64_t> P = PrimesUpTo(31);
        uint64_t pmax = 31;
        const CuspSpace S = BuildCuspSpace(k, e.ell, ResidualPrecision(k / 12, static_cast<uint32_t>(pmax)));
        Check(ResidualDepth(S, static_cast<uint32_t>(pmax)) >= 2 * S.d,
              cell + ": the residual of T_31 f_j is checked on >= d coefficients beyond a_1 .. a_d (A6)");
        const std::vector<ExtMatrix> T = HeckeList(S, P);

        int best = -1;
        uint32_t best_dim = 0;
        uint32_t compared = 0;
        for (uint32_t i = 0; i < rec.ideals.size(); ++i) {
            if (OwnGroup(rec.ideals[i]) != "H1") continue;
            const LocalAlgebra& L = drv.local_algebra(i);
            if (!L.ok || L.f != 1 || L.nu < 2) continue;
            const std::string tag = cell + " ideal " + std::to_string(i);
            // The system over the driver's primes != ell.
            std::vector<uint64_t> sp;
            std::vector<uint32_t> sys;
            // The quotient test runs on ALL the driver's primes (U_ell included:
            // it is T_ell on the forms side, a_n -> a_{n ell} mod ell).
            const std::vector<ExtMatrix> tA = L.t;
            const std::vector<uint64_t> qp = L.primes;
            bool rational = true;
            for (size_t j = 0; j < L.primes.size(); ++j) {
                if (L.primes[j] == e.ell) continue;
                const int64_t lam = RationalEigenvalue(L.t[j]);
                if (lam < 0) rational = false;
                sp.push_back(L.primes[j]);
                sys.push_back(static_cast<uint32_t>(lam < 0 ? 0 : lam));
            }
            Check(rational, tag + ": an F_ell-rational system (f = 1)");
            bool in_P = true;
            for (uint64_t p : qp) in_P = in_P && std::find(P.begin(), P.end(), p) != P.end();
            Check(in_P, tag + ": the driver's primes are <= 31");
            if (!rational || !in_P) continue;
            const FormsBlock B = LocaliseAtSystem(S, P, T, sp, sys);
            ++compared;
            std::ostringstream line;
            line << "FORMS_ALGEBRA n=" << e.n << " ell=" << e.ell << " k=" << k << " ideal=" << i
                 << " dim_S=" << S.d << " precision=" << S.precision << " generators=" << Vec64(P)
                 << " system_primes=" << Vec64(sp) << " system=" << Vec(sys) << " dim_Vm=" << B.dim;
            if (B.dim > 0) {
                line << " T_dim=" << B.A.dim_A << " T_local=" << B.A.local << " T_embdim=" << B.A.dim_tangent
                     << " T_hilbert=" << Vec(B.A.hilbert) << " T_loewy=" << B.A.nilpotency_index
                     << " T_socle=" << B.A.dim_socle << " T_gorenstein=" << B.A.gorenstein;
            }
            line << " A_D=" << L.D << " A_dim=" << L.dim_A << " A_embdim=" << L.embdim << " A_hilbert=" << Vec(L.hilbert)
                 << " A_primes=" << Vec64(L.primes);
            // (C) the quotient test on ALL the driver's primes (U_ell = T_ell).
            if (B.dim > 0) {
                std::vector<ExtMatrix> tT, joint, tT0, tA0;
                for (size_t j = 0; j < qp.size(); ++j) {
                    const size_t idx = static_cast<size_t>(std::find(P.begin(), P.end(), qp[j]) - P.begin());
                    tT.push_back(B.t[idx]);
                    if (qp[j] != e.ell) {
                        tT0.push_back(B.t[idx]);
                        tA0.push_back(tA[j]);
                    }
                }
                for (size_t j = 0; j < qp.size(); ++j) joint.push_back(BlockDiag(tT[j], tA[j]));
                // Reported, not gated: the same algebras without ell.
                line << " T_no_ell_dim=" << ComputeAlgebraInvariants(tT0, e.ell).dim_A
                     << " A_no_ell_dim=" << ComputeAlgebraInvariants(tA0, e.ell).dim_A;
                const AlgebraInvariants Tc = ComputeAlgebraInvariants(tT, e.ell);
                const AlgebraInvariants Ac = ComputeAlgebraInvariants(tA, e.ell);
                const AlgebraInvariants J = ComputeAlgebraInvariants(joint, e.ell);
                const bool quotient = J.dim_A == Tc.dim_A;
                line << " Tc_dim=" << Tc.dim_A << " Ac_dim=" << Ac.dim_A << " joint_dim=" << J.dim_A
                     << " quotient=" << (quotient ? "yes" : "no");
                Check(B.A.local, tag + ": T_m / ell local at the system");
                Check(Tc.dim_A == B.A.dim_A, tag + ": the driver's primes generate T_m / ell");
                Check(Ac.dim_A == L.dim_A, tag + ": the driver's primes generate A");
                Check(quotient, tag + ": T_p -> t_p extends to a surjection T_m / ell -> A");
                Check(L.dim_A <= B.A.dim_A, tag + ": length A <= length T_m / ell");
                bool bounded = L.hilbert.size() <= B.A.hilbert.size();
                for (size_t h = 0; bounded && h < L.hilbert.size(); ++h) bounded = L.hilbert[h] <= B.A.hilbert[h];
                Check(bounded, tag + ": A's Hilbert function bounded by T_m / ell's");
                // (N) a perturbed t_2 is not a quotient.
                if (!qp.empty() && qp[0] == 2 && L.D > 0) {
                    std::vector<ExtMatrix> bad = joint;
                    bad[0] = BlockDiag(tT[0], Shift(tA[0], e.ell - 1));   // t_2 + 1
                    const AlgebraInvariants Jb = ComputeAlgebraInvariants(bad, e.ell);
                    Check(Jb.dim_A > Tc.dim_A, tag + ": negative control -- t_2 + 1 is not a quotient");
                }
                // (N) the system shifted at p = 2 carries no cusp form.
                std::vector<uint32_t> sys_bad = sys;
                if (!sys_bad.empty()) {
                    sys_bad[0] = (sys_bad[0] + 1) % e.ell;
                    const FormsBlock Bb = LocaliseAtSystem(S, P, T, sp, sys_bad);
                    // (slot-12 WP-11, A5) asserted as stated: no form carries the shifted system.
                    Check(Bb.dim == 0, tag + ": negative control -- the system shifted at p = 2 carries no form (dim 0)");
                }
            }
            std::cout << line.str() << "\n";
            if (B.dim > best_dim) {
                best_dim = B.dim;
                best = static_cast<int>(i);
            }
            if (e.n == 142 && B.dim == e.dim_T) {
                out.have_142_block = true;
                out.block_142 = B;
                out.lambda2_142 = sys.empty() ? 0 : sys[0];
            }
        }
        Check(compared >= 1, cell + ": at least one non-reduced local H^1 ideal compared");
        if (best < 0) continue;
        // The referee's values on the cell's largest block.
        const LocalAlgebra& L = drv.local_algebra(static_cast<uint32_t>(best));
        std::vector<uint64_t> sp;
        std::vector<uint32_t> sys;
        for (size_t j = 0; j < L.primes.size(); ++j) {
            if (L.primes[j] == e.ell) continue;
            sp.push_back(L.primes[j]);
            sys.push_back(static_cast<uint32_t>(RationalEigenvalue(L.t[j])));
        }
        const FormsBlock B = LocaliseAtSystem(S, P, T, sp, sys);
        const std::string tag = cell + " (referee)";
        Check(B.dim == e.dim_T, tag + ": dim V_m == " + std::to_string(e.dim_T) + " (got " + std::to_string(B.dim) + ")");
        Check(B.A.dim_A == e.dim_T, tag + ": dim T_m / ell == " + std::to_string(e.dim_T));
        Check(B.A.dim_tangent == e.embdim_T, tag + ": embdim T_m / ell == " + std::to_string(e.embdim_T)
                                                 + " (got " + std::to_string(B.A.dim_tangent) + ")");
        Check(B.A.hilbert == e.hilbert_T, tag + ": Hilbert T_m / ell == " + Vec(e.hilbert_T) + " (got "
                                              + Vec(B.A.hilbert) + ")");
        Check(B.A.nilpotency_index == e.loewy_T, tag + ": Loewy length T_m / ell == " + std::to_string(e.loewy_T));
        Check(B.A.dim_socle == e.socle_T, tag + ": socle T_m / ell == " + std::to_string(e.socle_T));
        Check(B.A.gorenstein == e.gorenstein_T, tag + ": Gorenstein flag of T_m / ell");
        Check(L.dim_A == e.dim_A, tag + ": the census's length A == " + std::to_string(e.dim_A));
        Check(L.hilbert == e.hilbert_A, tag + ": the census's Hilbert A == " + Vec(e.hilbert_A));
        if (e.n == 82) Check(L.embdim != B.A.dim_tangent, tag + ": A is a PROPER quotient (embdim 2 vs 3)");
        if (e.n == 142)
            Check(L.dim_A == B.A.hilbert[0] + B.A.hilbert[1], tag + ": length A == length T_m / (7, m^2)");
        if (e.n == 34) Check(L.dim_A == B.A.dim_A, tag + ": A == T_m / ell at the agreeing control");
    }

    // (N) generators: F_7[T_2] alone on the (142, 7) block is a proper subalgebra.
    Check(out.have_142_block, "(142, 7): the length-6 block found");
    if (out.have_142_block) {
        const FormsBlock& B = out.block_142;
        const ExtMatrix N2 = Shift(B.t[0], out.lambda2_142);
        const std::vector<uint32_t> jt = NilpotentJordanType(N2);
        Check(jt == std::vector<uint32_t>({3, 2, 1}), "(142, 7): T_2 - lambda_2 has Jordan type (3,2,1) (got "
                                                          + Vec(jt) + ")");
        const AlgebraInvariants A2 = ComputeAlgebraInvariants({B.t[0]}, 7);
        Check(A2.dim_A == 3 && A2.dim_A < B.A.dim_A, "(142, 7): negative control -- F_7[T_2] is a proper subalgebra (dim 3)");
        std::cout << "    (142, 7): lambda_2=" << out.lambda2_142 << " Jordan(T_2 - lambda_2)=" << Vec(jt)
                  << " dim F_7[T_2]=" << A2.dim_A << "\n";
    }
}

