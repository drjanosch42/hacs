using Row = std::map<std::string, std::string>;

std::vector<Row> ReadCensus(const std::string& path) {
    std::ifstream in(path);
    ENGINE_CHECK_MSG(in.good(), ("forms census: cannot open " + path).c_str());
    std::vector<Row> rows;
    std::vector<std::string> header;
    std::string line;
    auto split = [](const std::string& s) {
        std::vector<std::string> out;
        std::string cur;
        for (char c : s) {
            if (c == '\t') {
                out.push_back(cur);
                cur.clear();
            } else if (c != '\r') {
                cur.push_back(c);
            }
        }
        out.push_back(cur);
        return out;
    };
    uint64_t lineno = 0;   // (slot-16 WP-3) the physical TSV line, for refusals by line number
    while (std::getline(in, line)) {
        ++lineno;
        if (line.empty() || line[0] == '#') continue;
        if (header.empty()) {
            header = split(line);
            continue;
        }
        const std::vector<std::string> f = split(line);
        ENGINE_CHECK_MSG(f.size() == header.size(), "forms census: a row of the wrong width");
        Row r;
        for (size_t i = 0; i < f.size(); ++i) r[header[i]] = f[i];
        r["#line"] = std::to_string(lineno);
        rows.push_back(std::move(r));
    }
    return rows;
}

