// "" when the row may be used; else the refusal reason.  *mode = system | witness, *fallback = why a
// row fell back to the witness join (empty when it did not).
std::string TJoinRow(uint32_t n, uint32_t ell, uint32_t id, const Row& r, const LocalAlgebra& L, const std::vector<uint32_t>& drv_wp,
                     bool with_u, uint32_t budget_mb, std::string* mode, std::string* fallback) {
    if (r.count("module_D") && r.at("module_D") != "not_computed" && std::to_string(L.D) != r.at("module_D"))
        return "driver_D_" + std::to_string(L.D) + "_not_module_D_" + r.at("module_D");
    if (census::ParseUIntList(r.at("witness_poly")) != drv_wp) return "driver_witness_poly_differs";
    const std::string rp = r.count("record_path") ? r.at("record_path") : std::string();
    if (!g_tjoin.records.count(rp)) {
        census::RecordSystems none;
        none.why = "no_record_path";
        g_tjoin.records[rp] = rp.empty() ? none : census::ReadRecordSystems(rp, g_tjoin.roots.roots);
    }
    const census::RecordSystems& rs = g_tjoin.records[rp];
    const std::string u = census::CheckUEllOperator(rs, ell, with_u, budget_mb);
    if (!u.empty()) return u;
    if (rs.ok) {
        if (rs.n != n || rs.ell != ell) return "record_cell_mismatch";
        const auto it = rs.ideals.find(id);
        if (it == rs.ideals.end()) return "record_has_no_ideal_" + std::to_string(id);
        if (it->second.witness_poly != drv_wp) return "record_witness_poly_differs";
        if (it->second.split_ok && it->second.r == 1) {
            std::vector<uint32_t> a;
            for (const ExtMatrix& t : L.t) {
                const int64_t lam = RationalEigenvalue(t);
                a.push_back(lam < 0 ? UINT32_MAX : static_cast<uint32_t>(lam));
            }
            const std::string w = census::CompareSystem(it->second, L.primes, a);
            if (!w.empty()) return w;
            *mode = "system";
            return std::string();
        }
        *fallback = "record_split_unusable";
    } else {
        *fallback = rs.why.empty() ? std::string("record_unusable") : rs.why;
    }
    *mode = "witness";
    return std::string();
}

