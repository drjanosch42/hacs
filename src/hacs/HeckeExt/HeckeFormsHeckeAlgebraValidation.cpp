// (slot-15 WP-20, F9 torsion guard; WP-19 Theorem B(4), [C] prop:heckeH0) h = dim
// H^0(Gamma; M_n)_lambda, the torsion term of D = s + m + h: zero when ell is a driver
// prime with lambda_ell != 0, else the number of Dickson monomials L^a D^b with
// a(ell+1) + b(ell^2-ell) = n whose T_p-eigenvalue (1+p) p^a matches lambda_p at
// every driver prime p != ell.  Pipeline-free.
uint64_t DicksonH0Lambda(uint32_t n, uint32_t ell, const std::vector<uint64_t>& sp, const std::vector<uint32_t>& sys) {
    for (size_t j = 0; j < sp.size(); ++j)
        if (sp[j] == ell && sys[j] != 0) return 0;
    uint64_t h = 0;
    const uint64_t wl = static_cast<uint64_t>(ell) + 1, wd = static_cast<uint64_t>(ell) * ell - ell;
    for (uint64_t a = 0; a * wl <= n; ++a) {
        if ((n - a * wl) % wd != 0) continue;
        bool match = true;
        for (size_t j = 0; j < sp.size() && match; ++j) {
            if (sp[j] == ell) continue;
            uint64_t pa = 1;
            for (uint64_t e = 0; e < a; ++e) pa = pa * (sp[j] % ell) % ell;
            match = ((1 + sp[j]) % ell) * pa % ell == sys[j];
        }
        if (match) ++h;
    }
    return h;
}

// One census cell of arm (T): the driver run, the forms side on S_k and M_k, one
// FORMS_CENSUS line per row (slot-12 WP-14: factored out of ArmT so that
// HeckeBoundaryFinalityValidation's arm (I) gates the F9 identity on a subset).
// (slot-16 WP-3) The cell's u_ell: the source set's (census::CensusUEllBudgetMb -- ext_u691 8192, the np /
// npx cluster sets 16384, ext_first / ext_census_l7l11 the default), as the records ran it.  Before, only
// ext_u691 was honoured, so the np rows re-ran at the default and lost U_ell on 230 cells (slot-15 WP-15).
// *known = false when a row's set is not in the table; *mixed = true when the rows disagree.
uint32_t CellUEllBudgetMb(const std::vector<const Row*>& rows_of_cell, bool* known, bool* mixed) {
    *known = true;
    *mixed = false;
    uint32_t b = 0;
    for (size_t i = 0; i < rows_of_cell.size(); ++i) {
        bool k = true;
        const uint32_t bi = census::CensusUEllBudgetMb(rows_of_cell[i]->at("source_set"), &k);
        *known = *known && k;
        if (i > 0 && bi != b) *mixed = true;
        b = bi;
    }
    return b;
}

