// (slot-12 FIN) the driver's emitted (d0) / (d1) against the independent
// computation on a default subset of the heuristic census rows: every
// heuristic row of edition 1 at (26, 5), (126, 5) (both X_1 and X_4),
// (50, 7) and (122, 11) (the representatives 37, 43 streamed); the full
// census -- ell = 13 included -- is arm (H).
void ArmDriverRoutes() {
    std::cout << "-- (R) the driver's finality routes (d0) / (d1) vs the independent computation\n";
    const std::vector<Row> rows = ReadCensus(Edition1Path());
    const std::vector<std::pair<uint32_t, uint32_t>> want = {{26, 5}, {126, 5}, {50, 7}, {122, 11}};
    std::map<std::pair<uint32_t, uint32_t>, std::vector<std::pair<uint32_t, const Row*>>> cells;
    for (const Row& r : rows) {
        if (r.at("final_reason") != "sturm_heuristic") continue;
        const std::pair<uint32_t, uint32_t> c(static_cast<uint32_t>(std::stoul(r.at("n"))),
                                              static_cast<uint32_t>(std::stoul(r.at("ell"))));
        if (std::find(want.begin(), want.end(), c) == want.end()) continue;
        cells[c].push_back({static_cast<uint32_t>(std::stoul(r.at("ideal_id"))), &r});
    }
    Check(cells.size() == want.size(), "(R) every chosen cell carries a heuristic census row");
    FinalityOutcome out;
    std::vector<FinalityIdeal> per;
    for (const auto& cv : cells) FinalityCell(cv.first.first, cv.first.second, cv.second, out, true, &per);
    uint32_t agree = 0, d0 = 0, d1 = 0, fin = 0;
    for (const FinalityIdeal& f : per) {
        agree += f.driver_agrees;
        fin += f.driver_final;
        (f.driver_certificate == "dickson" ? d0 : d1) += (f.driver_certificate == "dickson" ||
                                                           f.driver_certificate == "boundary");
    }
    std::cout << "FIN_ROUTES_SUMMARY rows=" << per.size() << " agree=" << agree << " final=" << fin
              << " dickson=" << d0 << " boundary=" << d1 << "\n";
    Check(agree == per.size() && fin == per.size(), "(R) the driver discharges every chosen row, agreeing");
    Check(d0 > 0 && d1 > 0, "(R) both routes are exercised");

    // (audit G1) (d1)'s stream cap: every census cell (ell <= 13, even n <= 200) is within
    // it at the default u_ell budget; (n, 691) and (n, 10007) are not; a synthetic route
    // over the cap refuses without computing a single representative.
    {
        const uint32_t B = hecke::UEllSetting().budget_mb;
        double worst = 0.0;
        uint32_t census_cells = 0, within = 0;
        for (uint32_t ell : {5u, 7u, 11u, 13u})
            for (uint32_t n = 2; n <= 200; n += 2) {
                ++census_cells;
                within += BoundaryStreamWithinBudget(n, ell, B);
                worst = std::max(worst, BoundaryStreamCostMb(n, ell));
            }
        Check(within == census_cells, "(R) G1: every census-range cell (ell <= 13, n <= 200) is within the cap");
        Check(!BoundaryStreamWithinBudget(10, 691, B) && !BoundaryStreamWithinBudget(2, 691, B),
              "(R) G1: (2, 691) and (10, 691) are over the cap");
        Check(!BoundaryStreamWithinBudget(2, 10007, B) && !BoundaryStreamWithinBudget(18, 10007, B),
              "(R) G1: (2, 10007) and (18, 10007) are over the cap");
        ExtMatrix V(1, 1, 691), r1(1, 1, 691), coords(1, 1, 691);
        V.data[0][0] = 1;
        r1.data[0][0] = 1;
        coords.data[0][0] = 1;
        uint32_t calls = 0;
        const BoundaryFinalityCertificate c = BoundaryRoute(
                10, 691, true, B, V, r1, std::vector<ExtMatrix>{V}, coords,
                [&](uint64_t) -> ExtMatrix { ++calls; return V; });
        Check(c.outcome == "not_run:budget" && calls == 0 && c.verify() == 0,
              "(R) G1: a synthetic (10, 691) injective block -> not_run:budget, no representative streamed, verifies");
        BoundaryFinalityCertificate bad = c;
        bad.outcome = "passed";
        Check(bad.verify() != 0, "(R) G1: a (10, 691) certificate claiming passed over the cap is refused");
        std::cout << "FIN_STREAM_CAP budget_mb=" << B << " factor=" << kBoundaryStreamBudgetFactor
                  << " census_cells_within=" << within << "/" << census_cells << " census_worst_mb=" << worst
                  << " cost_10_691_mb=" << BoundaryStreamCostMb(10, 691)
                  << " cost_18_10007_mb=" << BoundaryStreamCostMb(18, 10007) << "\n";
    }

    // verify()'s clauses 30 / 31 on tampered copies of a real record ((126, 5): an H0 ideal
    // passed by (d0), H1 ideals passed by (d1)), and the driver's (d1) certificate object.
    {
        HeckeExtDriver drv(126, 5);
        drv.run();
        const HeckeExtRecord& rec = drv.record();
        Check(rec.verify() == 0, "(R) the (126, 5) record verifies");
        int i0 = -1, i1 = -1;
        for (size_t i = 0; i < rec.ideals.size(); ++i) {
            if (rec.ideals[i].certificate_routes.d0 == "passed" && i0 < 0) i0 = static_cast<int>(i);
            if (rec.ideals[i].certificate_routes.d1 == "passed" && i1 < 0) i1 = static_cast<int>(i);
        }
        Check(i0 >= 0 && i1 >= 0, "(R) (126, 5) carries a (d0)- and a (d1)-passed ideal");
        if (i0 >= 0 && i1 >= 0) {
            const BoundaryFinalityCertificate* bc = drv.boundary_certificate(static_cast<uint32_t>(i1));
            Check(bc != nullptr && bc->verify() == 0 && bc->rank_r1 == rec.ideals[i1].dim,
                  "(R) the (d1) certificate object is present, verifies, and r^1 is injective");
            if (bc) {
                BoundaryFinalityCertificate bad = *bc;
                bad.outcome = "failed:11";
                Check(bad.verify() == 4, "(R) a (d1) certificate claiming failed:11 is refused (code 4)");
            }
            auto code = [&](const std::function<void(HeckeExtRecord&)>& f) {
                HeckeExtRecord t = rec;
                f(t);
                return t.verify();
            };
            Check(code([&](HeckeExtRecord& t) { t.ideals[i1].certificate_routes.d1 = "bogus"; }) == 30,
                  "(R) verify() 30: a (d1) value outside the closed list");
            Check(code([&](HeckeExtRecord& t) { t.ideals[i1].boundary_reps = {2, 3}; }) == 30,
                  "(R) verify() 30: boundary_reps != R(ell)");
            Check(code([&](HeckeExtRecord& t) {
                      IdealRecord& id = t.ideals[i1];
                      id.certificate_routes.d1 = "not_run:budget";
                      id.final_inputs.boundary_passed = false;
                      id.boundary_reps.clear();
                      id.certificate = "sturm(B')";
                      id.final = hecke_ext::is_final(id.final_inputs, t.settings);
                  }) == 30,
                  "(R) verify() 30: not_run:budget claimed on a cell within the cap");
            Check(code([&](HeckeExtRecord& t) { t.ideals[i1].certificate = "sturm(B')"; }) == 30,
                  "(R) verify() 30: a passed (d1) must name the certificate boundary");
            Check(code([&](HeckeExtRecord& t) {
                      std::swap(t.ideals[i0].certificate_routes.d0, t.ideals[i0].certificate_routes.d1);
                  }) == 30,
                  "(R) verify() 30: (d1) on an H0 ideal");
            Check(code([&](HeckeExtRecord& t) {
                      IdealRecord& id = t.ideals[i0];
                      for (size_t j = 0; j < id.operator_primes.size(); ++j)
                          if (id.operator_primes[j] == 2) id.t_p[j].data[0][0] = (id.t_p[j].data[0][0] + 1) % 5;
                  }) == 31,
                  "(R) verify() 31: a (d0) that does not re-derive from the stored t_p");
            // (slot-13 WP-7, hecke_ext/v5) every (d1)-passed ideal's boundary_data IS the
            // in-process certificate's data: r1 = r^1 V, t = the t_p|_V it tested.
            uint32_t d1_passed = 0, data_equal = 0;
            for (size_t i = 0; i < rec.ideals.size(); ++i) {
                const IdealRecord& id = rec.ideals[i];
                if (id.certificate_routes.d1 != "passed") {
                    Check(!id.boundary_data.present, "(R) v5: no boundary_data off a (d1)-passed ideal");
                    continue;
                }
                ++d1_passed;
                const BoundaryFinalityCertificate* c = drv.boundary_certificate(static_cast<uint32_t>(i));
                if (!c) continue;
                const ExtMatrix r1V = c->r1 * c->V;
                bool eq = id.boundary_data.present && id.boundary_data.rank_r1 == c->rank_r1 &&
                          id.boundary_data.r1.rows == r1V.rows && id.boundary_data.r1.data == r1V.data &&
                          id.boundary_data.t.size() == c->reps_restricted.size();
                for (size_t k = 0; eq && k < c->reps_restricted.size(); ++k)
                    eq = id.boundary_data.t[k].data == c->reps_restricted[k].data;
                data_equal += eq;
            }
            Check(d1_passed > 0 && data_equal == d1_passed,
                  "(R) v5: every (d1)-passed ideal of (126, 5) carries the certificate object's own data");
            std::cout << "FIN_RECORD_DATA cell=(126,5) d1_passed=" << d1_passed << " data_equal=" << data_equal
                      << " D=" << rec.ideals[i1].dim << " reps=" << rec.ideals[i1].boundary_reps.size()
                      << " json_bytes=" << hecke_ext::BuildHeckeExtReportJson(rec).size() << "\n";
        }
    }

    // (slot-13 WP-7) BoundaryDataRederive's clauses on synthetic data (ell = 5, D = 2,
    // A_S = F_5 I generated by t_2 = 3 I and t_5 = 0): scalar restrictions pass; a
    // commuting non-scalar t_p is outside A_S (clause 7, H2); a rank-1 r^1|_V is not
    // injective (clause 4, H1); a wrong rank_r1 (3); an entry >= ell (2); a t_2 that is
    // not the stored t_2 (5); a non-commuting t_p (6); a missing class (1).
    {
        const uint32_t l = 5;
        auto scal = [&](uint32_t a) { ExtMatrix M(2, 2, l); M.data[0][0] = M.data[1][1] = a; return M; };
        const std::vector<uint64_t> S = {2, 5};
        const std::vector<ExtMatrix> gen = {scal(3), scal(0)};
        const std::vector<uint64_t> R = BoundaryRepresentatives(l);   // {11, 2, 3, 19}
        ExtMatrix r1(3, 2, l);
        r1.data[0][0] = 1; r1.data[2][1] = 4;
        std::vector<ExtMatrix> t = {scal(2), scal(3), scal(4), scal(0)};
        Check(R == std::vector<uint64_t>({11, 2, 3, 19}), "(R) v5 synthetic: R(5) = {11, 2, 3, 19}");
        Check(BoundaryDataRederive(l, S, gen, R, 2, r1, t) == 0, "(R) v5 synthetic: scalar t_p -> re-derives (0)");
        std::vector<ExtMatrix> tj = t;
        tj[2].data[0][1] = 1;   // t_3 = [[4,1],[0,4]] commutes with scalars, is not in F_5 I
        Check(BoundaryDataRederive(l, S, gen, R, 2, r1, tj) == 7, "(R) v5 synthetic: a Jordan t_3 outside A_S -> 7 (H2)");
        ExtMatrix r1low(3, 2, l);
        r1low.data[0][0] = 1; r1low.data[0][1] = 1;
        Check(BoundaryDataRederive(l, S, gen, R, 1, r1low, t) == 4, "(R) v5 synthetic: rank(r1) = 1 < D -> 4 (H1)");
        Check(BoundaryDataRederive(l, S, gen, R, 1, r1, t) == 3, "(R) v5 synthetic: rank_r1 misstated -> 3");
        std::vector<ExtMatrix> tb = t;
        tb[0].data[0][0] = 5;
        Check(BoundaryDataRederive(l, S, gen, R, 2, r1, tb) == 2, "(R) v5 synthetic: an entry >= ell -> 2");
        std::vector<ExtMatrix> ts = t;
        ts[1] = scal(1);        // t_2 in R(5) and in S must be the stored 3 I
        Check(BoundaryDataRederive(l, S, gen, R, 2, r1, ts) == 5, "(R) v5 synthetic: t_2 != the stored t_2 -> 5");
        std::vector<ExtMatrix> gj = {tj[2], scal(0)};   // A_S = F_5[J]; t_19 = E_21 does not commute
        std::vector<ExtMatrix> tn = {scal(2), tj[2], scal(4), scal(0)};
        tn[3].data[1][0] = 1;
        Check(BoundaryDataRederive(l, S, gj, R, 2, r1, tn) == 6, "(R) v5 synthetic: a non-commuting t_19 -> 6");
        std::vector<ExtMatrix> tm = t;
        tm.pop_back();
        Check(BoundaryDataRederive(l, S, gen, R, 2, r1, tm) == 1, "(R) v5 synthetic: a class missing -> 1");
    }

    // (slot-13 WP-7; FIN audit G5) a synthetic failed:<class> for (d0): at ell = 5 the
    // degree n = 60 carries the Dickson classes {0, 2} (a = 0 (D^3) and a = 10 (L^10));
    // with S \ {ell} = {11} (11 = 1 mod 5, no primitive root) or {19} (19 = -1 mod 5)
    // the eigenvalue (1 + q) q^a is 2 resp. 0 on both classes -- inseparable, so the
    // route must fail naming class 2; with q = 2 (a primitive root) it separates.
    {
        auto scal = [&](uint32_t a) { ExtMatrix M(2, 2, 5); M.data[0][0] = M.data[1][1] = a; return M; };
        Check(DicksonClassesPresent(60, 5) == std::vector<uint32_t>({0, 2}), "(R) G5: classes present at (60, 5) = {0, 2}");
        const std::string f11 = DicksonRoute(60, 5, {5, 11}, {scal(1), scal(2)});
        const std::string f19 = DicksonRoute(60, 5, {5, 19}, {scal(1), scal(0)});
        const std::string p2 = DicksonRoute(60, 5, {2, 5}, {scal(3), scal(1)});
        Check(f11 == "failed:2" && IsDicksonRouteValue(f11), "(R) G5: S_0 \\ {5} = {11} -> failed:2");
        Check(f19 == "failed:2", "(R) G5: S_0 \\ {5} = {19} -> failed:2");
        Check(p2 == "passed", "(R) G5: S_0 \\ {5} = {2} (primitive root) separates -> passed");
        std::cout << "FIN_G5 d0(60,5;{5,11})=" << f11 << " d0(60,5;{5,19})=" << f19 << " d0(60,5;{2,5})=" << p2 << "\n";
    }
    std::cout << "FIN_RECORD_SIDE rows=" << g_record_side_rows << " passed=" << g_record_side_passed << "\n";
}

void ArmHeuristicAll() {
    if (!EnvOn("HECKE_BOUNDARY_FINALITY_ALL")) {
        std::cout << "-- (H) all heuristic rows: [SKIP] (HECKE_BOUNDARY_FINALITY_ALL=1 runs it)\n";
        return;
    }
    const std::string path = CensusPath();
    std::cout << "-- (H) every sturm_heuristic row at ell in {5, 7, 11, 13} of " << path << "\n";
    const std::vector<Row> rows = ReadCensus(path);
    std::map<std::pair<uint32_t, uint32_t>, std::vector<std::pair<uint32_t, const Row*>>> cells;
    uint32_t heuristic = 0, other_nonfinal = 0;
    for (const Row& r : rows) {
        if (r.at("final") != "true" && r.at("final_reason") != "sturm_heuristic") ++other_nonfinal;
        if (r.at("final_reason") != "sturm_heuristic") continue;
        const std::string& e = r.at("ell");
        if (e != "5" && e != "7" && e != "11" && e != "13") continue;
        ++heuristic;
        cells[{static_cast<uint32_t>(std::stoul(r.at("n"))), static_cast<uint32_t>(std::stoul(e))}].push_back(
            {static_cast<uint32_t>(std::stoul(r.at("ideal_id"))), &r});
    }
    std::cout << "    heuristic rows: " << heuristic << " over " << cells.size()
              << " cells; other non-final rows: " << other_nonfinal << "\n";
    FinalityOutcome out;
    std::vector<FinalityIdeal> per;
    std::map<uint32_t, std::pair<uint32_t, uint32_t>> by_ell;   // ell -> (rows, certified)
    for (const auto& cv : cells) FinalityCell(cv.first.first, cv.first.second, cv.second, out, true, &per);
    uint32_t driver_agree = 0, driver_final = 0;
    for (const FinalityIdeal& f : per) {
        ++by_ell[f.ell].first;
        by_ell[f.ell].second += f.certified;
        driver_agree += f.driver_agrees;
        driver_final += f.driver_final;
    }
    std::cout << "FIN_ROUTES_ALL rows=" << per.size() << " driver_agree=" << driver_agree
              << " driver_final=" << driver_final << "\n";
    std::cout << "BOUNDARY_FINALITY_SUMMARY rows=" << out.ideals << " injective=" << out.injective
              << " boundary_law_held=" << out.law_held << " certified=" << out.certified
              << " all_q_le_31_in_A_S=" << out.all_pool;
    for (const auto& e : by_ell) std::cout << " ell" << e.first << "=" << e.second.second << "/" << e.second.first;
    std::cout << " other_nonfinal=" << other_nonfinal << "\n";
    // (slot-14 WP-2, plan item 5) cells=0 here is a LEGITIMATE outcome on a
    // census edition where S12-FIN made every heuristic row final (edition 2)
    // -- it is not itself a defect (unlike arm (F) above, this arm has no
    // default-cell fallback to compare against, so there is nothing to SKIP
    // instead of); the EFFECTIVE line makes that reading mechanical rather
    // than requiring the "heuristic rows: 0 over 0 cells" prose to be read by
    // hand ([C4] Sec.1, "boundary_final_all ... vacuous (known)").
    std::cout << "EFFECTIVE HeckeBoundaryFinalityValidation arm=H cells=" << cells.size() << "\n";
    Check(out.ideals == heuristic, "(H) every heuristic row reached");
}

