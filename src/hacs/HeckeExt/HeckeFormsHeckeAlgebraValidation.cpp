    std::cout << "FORMS_CENSUS_JOIN_SUMMARY arm=I rows=" << g_tjoin.rows << " " << TJoinText() << "\n";
    Check(g_tjoin.rows >= 5 && g_tjoin.system == g_tjoin.rows && g_tjoin.fallback == 0 && g_tjoin.refused == 0,
          "(I) every row joins its tracked edition-1 record by eigen-system (module_D, witness_poly, U_ell, split system)");
