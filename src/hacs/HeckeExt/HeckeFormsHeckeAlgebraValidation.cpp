std::string Vec(const std::vector<uint32_t>& v) {
    std::ostringstream s;
    s << "(";
    for (size_t i = 0; i < v.size(); ++i) s << (i ? "," : "") << v[i];
    s << ")";
    return s.str();
}
std::string Vec64(const std::vector<uint64_t>& v) {
    std::ostringstream s;
    s << "{";
    for (size_t i = 0; i < v.size(); ++i) s << (i ? "," : "") << v[i];
    s << "}";
    return s.str();
}

// (slot-12 WP-11, A6) a q-expansion precision N at which HeckeOnCusp's residual
// a_n(T_p f_j) - sum_i c_i a_n(f_i) is checked on n <= M = (N-1)/p >= 2 d for every
// p <= p_max, i.e. on >= d coefficients beyond the a_1 .. a_d the coordinates are
// read from (at N = d p_max + 2, M = d at p_max: nothing was checked there).
uint32_t ResidualPrecision(uint32_t d, uint32_t p_max) { return 2 * d * p_max + 2; }
uint32_t ResidualDepth(const CuspSpace& S, uint32_t p) { return (S.precision - 1) / p; }
std::string tag0(uint32_t k) { return "S_" + std::to_string(k) + "(F_7)"; }

std::vector<uint64_t> PrimesUpTo(uint32_t b) {
    std::vector<uint64_t> out;
    for (uint32_t p = 2; p <= b; ++p) {
        bool pr = true;
        for (uint32_t q = 2; q * q <= p; ++q)
            if (p % q == 0) pr = false;
        if (pr) out.push_back(p);
    }
    return out;
}

std::vector<ExtMatrix> HeckeList(const CuspSpace& S, const std::vector<uint64_t>& primes) {
    std::vector<ExtMatrix> T;
    for (uint64_t p : primes) T.push_back(HeckeOnCusp(S, static_cast<uint32_t>(p)));
    return T;
}

uint32_t SpanDim(const std::vector<ExtMatrix>& mats, uint32_t ell) {
    if (mats.empty()) return 0;
    const uint32_t d = mats[0].rows;
    ExtMatrix M(static_cast<uint32_t>(mats.size()), d * d, ell);
    for (size_t k = 0; k < mats.size(); ++k)
        for (uint32_t i = 0; i < d; ++i)
            for (uint32_t j = 0; j < d; ++j) M.data[k][i * d + j] = mats[k].data[i][j];
    return hecke::RankOf(M);
}

ExtMatrix BlockDiag(const ExtMatrix& a, const ExtMatrix& b) {
    ExtMatrix c(a.rows + b.rows, a.cols + b.cols, a.p);
    for (uint32_t i = 0; i < a.rows; ++i)
        for (uint32_t j = 0; j < a.cols; ++j) c.data[i][j] = a.data[i][j];
    for (uint32_t i = 0; i < b.rows; ++i)
        for (uint32_t j = 0; j < b.cols; ++j) c.data[a.rows + i][a.cols + j] = b.data[i][j];
    return c;
}

ExtMatrix Shift(const ExtMatrix& a, uint32_t lambda) {
    ExtMatrix c = a;
    for (uint32_t i = 0; i < a.rows; ++i) c.data[i][i] = (c.data[i][i] + a.p - lambda % a.p) % a.p;
    return c;
}

std::string OwnGroup(const IdealRecord& id) {
    for (const IdealGroupMatch& g : id.groups)
        if (g.own) return g.group;
    return std::string();
}

