bool IsPrime64(uint64_t q) {
    if (q < 2) return false;
    for (uint64_t d = 2; d * d <= q; ++d)
        if (q % d == 0) return false;
    return true;
}

// The pool primes != ell plus the least prime of each class of (Z/ell)^x the pool misses.
std::vector<uint64_t> PoolWithClassReps(uint32_t ell) {
    std::vector<uint64_t> P = AnemicPool(ell);
    for (uint32_t cls = 1; cls < ell; ++cls) {
        if (LeastPrimeInClass(ell, cls, P) != 0) continue;
        for (uint64_t q = cls;; q += ell)
            if (IsPrime64(q)) {
                P.push_back(q);
                break;
            }
    }
    std::sort(P.begin(), P.end());
    return P;
}

// c1 rho_n(diag(a1, d1)) + c2 rho_n(diag(a2, d2)), rho_n = ComputeSymmetricPowerMatrixFM.
FlatMatrix FibreComb(uint32_t n, uint32_t ell, uint32_t c1, uint32_t a1, uint32_t d1, uint32_t c2, uint32_t a2,
                     uint32_t d2) {
    const FlatMatrix R1 = ComputeSymmetricPowerMatrixFM(FlatMatrix(2, 2, ell, std::vector<uint32_t>{a1, 0, 0, d1}), n);
    const FlatMatrix R2 = ComputeSymmetricPowerMatrixFM(FlatMatrix(2, 2, ell, std::vector<uint32_t>{a2, 0, 0, d2}), n);
    const uint32_t d = n + 1;
    std::vector<uint32_t> v(static_cast<size_t>(d) * d, 0);
    for (uint32_t i = 0; i < d; ++i)
        for (uint32_t j = 0; j < d; ++j)
            v[static_cast<size_t>(i) * d + j] = static_cast<uint32_t>(
                (static_cast<uint64_t>(c1) * R1.get_entry(i, j) + static_cast<uint64_t>(c2) * R2.get_entry(i, j)) % ell);
    return FlatMatrix(d, d, ell, v);
}

struct LemmaBTally {
    uint32_t cells = 0, operators = 0, class_pairs = 0, diag_ok = 0, formula_ok = 0, commute_ok = 0, pairs = 0;
    uint32_t mult0_ok = 0, mult0 = 0, mult1_ok = 0, mult1 = 0;
};

void ArmLemmaB(LemmaBTally& T) {
    std::cout << "-- (L) Lemma B' on the boundary operators A^bd(T_p) (F3)\n";
    const SimplicialComplex K = CreateSL2ZFundamentalDomainTriangulation();
    const hecke::SL2ZTessellationTables model(K);
    const SimplicialComplex Kbd = CreateSL2ZBoundaryPathTriangulation();
    struct Grid {
        uint32_t ell, n_max;
    };
    for (const Grid& G : {Grid{5, 40}, Grid{7, 40}, Grid{11, 34}, Grid{13, 30}}) {
        const uint32_t ell = G.ell;
        const std::vector<uint64_t> P = PoolWithClassReps(ell);
        for (uint32_t n = 2; n <= G.n_max; n += 2) {
            const std::string cell = "(" + std::to_string(n) + ", " + std::to_string(ell) + ")";
            LocalSystemSimplicialComplexT<uint32_t> lssc(Kbd, GenerateSL2ZBoundaryRelationsElt<uint32_t>(Kbd, n, ell),
                                                         n + 1, ell);
            EquivariantCohomologyOnKT<uint32_t> coh(&lssc);
            coh.compute_cohomology();
            ++T.cells;
            std::map<uint64_t, std::vector<ExtMatrix>> A;   // p -> {A^bd_0, A^bd_1}
            for (uint64_t p : P) {
                hecke::HeckeCosetTablesT<uint32_t> cos(p, 1, ell, n);
                hecke::HeckeBoundaryTauTableT<uint32_t> tb(K, model, cos);
                hecke::HeckeBoundaryOperatorT<uint32_t> op(&coh, &cos, &tb);
                op.compute();
                const uint32_t pb = static_cast<uint32_t>(p % ell);
                for (uint32_t q : {0u, 1u}) {
                    const ExtMatrix Aq = op.A(q);
                    A[p].push_back(Aq);
                    ++T.operators;
                    const std::string tag = cell + " p=" + std::to_string(p) + " q=" + std::to_string(q);
                    const uint32_t d = Aq.rows;
                    // (b) diagonalisable over F_ell; the eigenvalue multiset.
                    std::vector<uint32_t> mult(ell, 0);
                    uint32_t tot = 0;
                    for (uint32_t lam = 0; lam < ell; ++lam) {
                        mult[lam] = d - hecke::RankOf(Shift(Aq, lam));
                        tot += mult[lam];
                    }
                    const bool diag = tot == d;
                    T.diag_ok += diag;
                    Check(diag, tag + ": A^bd(T_p) diagonalisable over F_ell (Lemma B'(2))");
                    // (d) the multiset {chi_b(p)}.
                    std::vector<uint32_t> want(ell, 0);
                    for (uint32_t b = 0; b <= n / ell; ++b)
                        ++want[hecke::HeckeBoundaryOperatorT<uint32_t>::chi(ell, p, n, b)];
                    const bool ms = d == n / ell + 1 && want == mult;
                    if (q == 0) {
                        ++T.mult0;
                        T.mult0_ok += ms;
                        Check(ms, tag + ": eigenvalue multiset {chi_b(p)} on H^0 (prop:bdrychar(1))");
                    } else {
                        ++T.mult1;
                        T.mult1_ok += ms;
                        if (!ms) std::cout << "    RECORDED " << tag << ": H^1 multiset != {chi_b(p)} (cl:chi(2))\n";
                    }
                    // (e) Lemma B'(0) / (1): the fibre formula with pb = p mod ell.
                    const FlatMatrix F = q == 0 ? FibreComb(n, ell, 1, 1, pb, pb, pb, 1)
                                                : FibreComb(n, ell, pb, 1, pb, 1, pb, 1);
                    bool descends = false;
                    const ExtMatrix M = op.matrix_on_H_from_fiber_operator(q, F, descends);
                    const bool fok = descends && SameMat(M, Aq);
                    T.formula_ok += fok;
                    Check(fok, tag + ": A^bd(T_p) = the Lemma B'(" + std::to_string(q) + ") fibre formula at p mod ell");
                }
            }
            // (a) dependence on p mod ell only; (c) commutation.
            for (size_t i = 0; i < P.size(); ++i)
                for (size_t j = i + 1; j < P.size(); ++j)
                    for (uint32_t q : {0u, 1u}) {
                        const ExtMatrix& X = A[P[i]][q];
                        const ExtMatrix& Y = A[P[j]][q];
                        const std::string tag = cell + " q=" + std::to_string(q) + " p=" + std::to_string(P[i]) +
                                                ", p'=" + std::to_string(P[j]);
                        if (P[i] % ell == P[j] % ell) {
                            ++T.class_pairs;
                            Check(SameMat(X, Y), tag + ": A^bd(T_p) = A^bd(T_p') for p = p' mod ell (Lemma B'(2))");
                        }
                        ++T.pairs;
                        const bool com = SameMat(X * Y, Y * X);
                        T.commute_ok += com;
                        Check(com, tag + ": A^bd(T_p) A^bd(T_p') = A^bd(T_p') A^bd(T_p)");
                    }
        }
    }
    std::cout << "LEMMA_B cells=" << T.cells << " operators=" << T.operators << " diagonalisable=" << T.diag_ok
              << " fibre_formula=" << T.formula_ok << " same_class_pairs=" << T.class_pairs
              << " commuting_pairs=" << T.commute_ok << "/" << T.pairs << " multiset_H0=" << T.mult0_ok << "/"
              << T.mult0 << " multiset_H1=" << T.mult1_ok << "/" << T.mult1 << " (H^1 recorded, cl:chi(2))\n";
}

