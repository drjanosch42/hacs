std::string StatusName(IdentityStatus s) {
    switch (s) {
        case IdentityStatus::kNotApplicable: return "not_applicable";
        case IdentityStatus::kPassed: return "passed";
        case IdentityStatus::kFailed: return "failed";
    }
    return "?";
}

bool SquareNonEmpty(const MatrixT<uint32_t>& M) {
    return M.rows > 0 && M.rows == M.cols;
}

bool SameShape(const MatrixT<uint32_t>& A, const MatrixT<uint32_t>& B) {
    return A.rows == B.rows && A.cols == B.cols;
}

// ---- identity class 7: plain exact linear algebra over F_ell -------------
// (slot 6, WP-3).  Self-contained on purpose: the certificate re-derives,
// it never calls the production elimination that produced its inputs.
using Dense = std::vector<std::vector<uint64_t>>;   // row-major, entries < ell
using Vec = std::vector<uint64_t>;

Dense DenseOf(const MatrixT<uint32_t>& M) {
    Dense D(M.rows, Vec(M.cols, 0));
    for (uint32_t r = 0; r < M.rows; ++r)
        for (uint32_t c = 0; c < M.cols; ++c) D[r][c] = M.data[r][c];
    return D;
}

Dense DMul(const Dense& A, const Dense& B, uint64_t ell) {
    const size_t R = A.size(), K = B.size(), C = K ? B[0].size() : 0;
    Dense P(R, Vec(C, 0));
    for (size_t i = 0; i < R; ++i)
        for (size_t k = 0; k < K; ++k) {
            const uint64_t a = A[i][k];
            if (a == 0) continue;
            for (size_t j = 0; j < C; ++j) P[i][j] = (P[i][j] + a * B[k][j]) % ell;
        }
    return P;
}

Dense DIdentity(size_t d) {
    Dense I(d, Vec(d, 0));
    for (size_t i = 0; i < d; ++i) I[i][i] = 1;
    return I;
}

uint64_t InvMod(uint64_t a, uint64_t ell) { return engine::scalar::invmod_fermat<uint64_t>(a, ell); }   // ell prime: a^(ell-2)

// Row-reduces `rows` (each of length `len`) in place to reduced echelon form;
// returns the pivot columns.
std::vector<size_t> Rref(Dense& rows, size_t len, uint64_t ell) {
    std::vector<size_t> piv;
    size_t r = 0;
    for (size_t c = 0; c < len && r < rows.size(); ++c) {
        size_t s = r;
        while (s < rows.size() && rows[s][c] == 0) ++s;
        if (s == rows.size()) continue;
        std::swap(rows[r], rows[s]);
        const uint64_t inv = InvMod(rows[r][c], ell);
        for (size_t j = 0; j < len; ++j) rows[r][j] = rows[r][j] * inv % ell;
        for (size_t i = 0; i < rows.size(); ++i) {
            if (i == r || rows[i][c] == 0) continue;
            const uint64_t f = rows[i][c];
            for (size_t j = 0; j < len; ++j) rows[i][j] = (rows[i][j] + (ell - f) * rows[r][j]) % ell;
        }
        piv.push_back(c);
        ++r;
    }
    rows.resize(r);
    return piv;
}

// A basis of the span of `vecs` (each of length `len`).
std::vector<Vec> SpanBasis(std::vector<Vec> vecs, size_t len, uint64_t ell) {
    Rref(vecs, len, ell);
    return vecs;
}

// A basis of { x : M x = 0 }, M given as rows of length `len`.
std::vector<Vec> NullSpace(Dense M, size_t len, uint64_t ell) {
    const std::vector<size_t> piv = Rref(M, len, ell);
    std::vector<char> is_piv(len, 0);
    for (size_t c : piv) is_piv[c] = 1;
    std::vector<Vec> out;
    for (size_t f = 0; f < len; ++f) {
        if (is_piv[f]) continue;
        Vec x(len, 0);
        x[f] = 1;
        for (size_t i = 0; i < piv.size(); ++i) x[piv[i]] = (ell - M[i][f]) % ell;
        out.push_back(x);
    }
    return out;
}

Vec Apply(const Dense& A, const Vec& v, uint64_t ell) {
    Vec w(A.size(), 0);
    for (size_t i = 0; i < A.size(); ++i)
        for (size_t j = 0; j < v.size(); ++j) w[i] = (w[i] + A[i][j] * v[j]) % ell;
    return w;
}

Vec Flatten(const Dense& A) {
    Vec v;
    for (const Vec& r : A) v.insert(v.end(), r.begin(), r.end());
    return v;
}

// The Jacobson radical of the (commutative) F_ell-algebra generated by the
// d x d matrices `gens`, as a list of spanning matrices: the kernel of the
// F_ell-linear Frobenius x -> x^(ell^e), ell^e >= d, on the algebra.
std::vector<Dense> JacobsonRadical(const std::vector<Dense>& gens, size_t d, uint64_t ell) {
    // The algebra: BFS over words, keeping a linearly independent family.
    std::vector<Dense> basis{ DIdentity(d) };
    std::vector<Vec> echelon = SpanBasis({ Flatten(basis[0]) }, d * d, ell);
    for (size_t k = 0; k < basis.size(); ++k)
        for (const Dense& X : gens) {
            Dense cand = DMul(X, basis[k], ell);
            std::vector<Vec> trial = echelon;
            trial.push_back(Flatten(cand));
            trial = SpanBasis(trial, d * d, ell);
            if (trial.size() > echelon.size()) { echelon = trial; basis.push_back(cand); }
        }
    uint64_t q = ell;
    while (q < d) q *= ell;
    // Frobenius images, as columns of a (d*d) x dim A matrix.
    const size_t m = basis.size();
    Dense F(d * d, Vec(m, 0));
    for (size_t i = 0; i < m; ++i) {
        Dense r = DIdentity(d), b = basis[i];
        for (uint64_t e = q; e; e >>= 1) {
            if (e & 1u) r = DMul(r, b, ell);
            if (e > 1) b = DMul(b, b, ell);
        }
        const Vec fv = Flatten(r);
        for (size_t t = 0; t < d * d; ++t) F[t][i] = fv[t];
    }
    std::vector<Dense> J;
    for (const Vec& c : NullSpace(F, m, ell)) {
        Dense x(d, Vec(d, 0));
        for (size_t i = 0; i < m; ++i) {
            if (c[i] == 0) continue;
            for (size_t r = 0; r < d; ++r)
                for (size_t s = 0; s < d; ++s) x[r][s] = (x[r][s] + c[i] * basis[i][r][s]) % ell;
        }
        J.push_back(x);
    }
    return J;
}

// --- identity 6 helpers (slot 6, WP-9) --------------------------------------

using Orbit = std::vector<std::vector<std::vector<uint32_t>>>;
using ClassKey = std::pair<uint32_t, Orbit>;          // (r, sorted orbit)
using SignedMultiset = std::map<ClassKey, int64_t>;

uint32_t PowSmall(uint64_t base, uint64_t e, uint32_t m) { return engine::scalar::powmod<uint32_t>(static_cast<uint32_t>(base % m), e, m); }

// theta^j on one class: every coordinate a_q multiplied by the scalar q^j,
// entrywise on the coefficient vectors; then the orbit sorted.
ClassKey TwistedKey(const ResidueCharacterClass& c, const std::vector<uint64_t>& S, uint32_t j,
                    uint32_t ell) {
    ENGINE_CHECK_MSG(!(c.orbit.size() != c.r || c.r == 0),
        "identity 6: a class whose orbit is not r conjugates");
    Orbit o = c.orbit;
    for (auto& v : o) {
        ENGINE_CHECK_MSG(!(v.size() != S.size()),
            "identity 6: a conjugate not index-aligned with the primes");
        for (size_t i = 0; i < v.size(); ++i) {
            ENGINE_CHECK_MSG(!(v[i].size() != c.r),
                "identity 6: a field element of the wrong width");
            const uint64_t s = PowSmall(S[i], j, ell);
            for (uint32_t& x : v[i]) x = static_cast<uint32_t>((s * x) % ell);
        }
    }
    std::sort(o.begin(), o.end());
    return ClassKey(c.r, o);
}

void AddMultiset(SignedMultiset& acc, const ResidueCharacterMultiset& ms,
                 const std::vector<uint64_t>& S, uint32_t j, uint32_t ell, int64_t sign) {
    for (const ResidueCharacterClass& c : ms) {
        acc[TwistedKey(c, S, j, ell)] += sign * static_cast<int64_t>(c.multiplicity);
    }
}

void CheckResidueInputs(const IdentityCertificate& c) {
    ENGINE_CHECK_MSG(!(c.ell < 5), "identity 6: ell < 5");
    ENGINE_CHECK_MSG(!(c.n % 2 != 0), "identity 6: odd n");
    ENGINE_CHECK_MSG(!(c.residue_cell.size() != 3), "identity 6: residue_cell needs q=0,1,2");
    ENGINE_CHECK_MSG(!(c.residue_weights.size() != c.ell),
        "identity 6: residue_weights needs one entry per m < ell");
    for (uint32_t m = 0; m < c.ell; m += 2)
        ENGINE_CHECK_MSG(!(c.residue_weights[m].size() != 3),
            "identity 6: an even weight cell without three degrees");
    ENGINE_CHECK_MSG(!(c.residue_primes.empty()), "identity 6: no primes");
    for (uint64_t q : c.residue_primes)
        ENGINE_CHECK_MSG(!(q % c.ell == 0), "identity 6: a prime divisible by ell");
}

std::vector<ResidueDifference> ToList(const SignedMultiset& m) {
    std::vector<ResidueDifference> out;
    for (const auto& kv : m) {
        if (kv.second == 0) continue;
        ResidueDifference d;
        d.cls.r = kv.first.first;
        d.cls.orbit = kv.first.second;
        d.delta = kv.second;
        out.push_back(std::move(d));
    }
    return out;
}

SignedMultiset RhsMultiset(const IdentityCertificate& c, GloverConvention conv) {
    SignedMultiset acc;
    for (const IdentityGloverFactor& f : IdentityGloverFactors(c.n, c.ell, conv)) {
        const std::vector<ResidueCharacterMultiset>& w = c.residue_weights.at(f.sym);
        ENGINE_CHECK_MSG(!(w.size() != 3),
            "identity 6: a Glover factor's weight cell was not supplied");
        for (uint32_t q = 0; q < 3; ++q) {
            // sum_i theta^{j_i} ( [H^1] - [H^0] + [H^2] )(M_{n_i}); the cell's
            // own + [H^0(M_n)] - [H^2(M_n)] is added below.
            const int64_t sign = (q == 0) ? -1 : 1;
            for (uint32_t k = 0; k < f.multiplicity; ++k)
                AddMultiset(acc, w[q], c.residue_primes, f.det_twist, c.ell, sign);
        }
    }
    // + [H^0(M_n)] - [H^2(M_n)]
    AddMultiset(acc, c.residue_cell[0], c.residue_primes, 0, c.ell, 1);
    AddMultiset(acc, c.residue_cell[2], c.residue_primes, 0, c.ell, -1);
    return acc;
}

