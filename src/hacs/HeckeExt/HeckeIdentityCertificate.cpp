std::vector<IdentityGloverFactor> IdentityGloverFactors(uint32_t n, uint32_t ell,
                                                        GloverConvention conv) {
    ENGINE_CHECK_MSG(!(ell < 3 || ell % 2 == 0),
        "IdentityGloverFactors: ell must be an odd prime >= 3");
    const uint32_t m = ell - 1u;
    // [E] cl:glover(4): JH(n) = {(n,0)} for 0 <= n <= ell-1, and for n >= ell
    // {(r,0), (ell-1-r, n)} u (JH(n-ell-1) (x) det), r = n mod (ell-1).
    std::map<std::pair<uint32_t, uint32_t>, uint32_t> raw;
    uint32_t twist = 0;          // the accumulated (x) det of the recursion
    int64_t cur = n;
    while (cur >= 0) {
        const uint32_t c = static_cast<uint32_t>(cur);
        if (c <= ell - 1u) {
            ++raw[{c, twist % m}];
            break;
        }
        const uint32_t r = c % m;
        ++raw[{r, twist % m}];
        ++raw[{ell - 1u - r, static_cast<uint32_t>((static_cast<uint64_t>(c) + twist) % m)}];
        cur -= static_cast<int64_t>(ell) + 1;
        ++twist;
    }
    std::map<std::pair<uint32_t, uint32_t>, uint32_t> shifted;
    for (const auto& kv : raw) {
        uint32_t j = kv.first.second;
        if (conv == GloverConvention::kContragredient)
            j = static_cast<uint32_t>((static_cast<uint64_t>(j) + m - (n % m)) % m);
        shifted[{kv.first.first, j}] += kv.second;
    }
    std::vector<IdentityGloverFactor> out;
    for (const auto& kv : shifted) out.push_back({kv.first.first, kv.first.second, kv.second});
    return out;
}

std::vector<ResidueDifference> IdentityResidueRhs(const IdentityCertificate& c,
                                                  GloverConvention conv) {
    CheckResidueInputs(c);
    return ToList(RhsMultiset(c, conv));
}

std::vector<ResidueDifference> IdentityResidueDifference(const IdentityCertificate& c,
                                                         GloverConvention conv) {
    CheckResidueInputs(c);
    SignedMultiset acc = RhsMultiset(c, conv);
    AddMultiset(acc, c.residue_cell[1], c.residue_primes, 0, c.ell, -1);
    return ToList(acc);
}

uint32_t IdentityCertificate::verify() {
    uint32_t first_failure = 0;

    // Eichler-Shimura's own hypothesis ([C, thm:relations] background) and
    // d_2=0's: n > 0, even, ell >= 5. [X Sec.1.3] "Applicability": elsewhere
    // both are `kNotApplicable`, never `kPassed`.
    const bool applicable_es_d2 = (n > 0) && (n % 2 == 0) && (ell >= 5);

    // --- Identity 1: dim H^1 = dim M_{n+2} + dim S_{n+2} + dim H^0. -------
    if (applicable_es_d2) {
        const uint32_t k = n + 2;
        const uint32_t expected = DimModularForms(k) + DimCuspForms(k) + dim_H0;
        const bool ok = (expected == dim_H1);
        eichler_shimura.status = ok ? IdentityStatus::kPassed : IdentityStatus::kFailed;
        std::ostringstream d;
        d << "dim H^1=" << dim_H1 << " vs dim M_" << k << "+dim S_" << k
          << "+dim H^0=" << DimModularForms(k) << "+" << DimCuspForms(k) << "+" << dim_H0
          << "=" << expected;
        eichler_shimura.detail = d.str();
        if (!ok && first_failure == 0) first_failure = 1;
    } else {
        eichler_shimura.status = IdentityStatus::kNotApplicable;
        eichler_shimura.detail = "n=0, odd n, or ell<5";
    }

    // --- Identity 2: [A_p, A_p'] = 0. --------------------------------------
    if (SquareNonEmpty(A_p) && SameShape(A_p, A_p_prime) && SquareNonEmpty(A_p_prime)) {
        const MatrixT<uint32_t> lhs = A_p * A_p_prime;
        const MatrixT<uint32_t> rhs = A_p_prime * A_p;
        const bool ok = (lhs == rhs);
        commutation.status = ok ? IdentityStatus::kPassed : IdentityStatus::kFailed;
        commutation.detail = ok ? "[A_p,A_p']=0" : "[A_p,A_p']!=0";
        if (!ok && first_failure == 0) first_failure = 2;
    } else {
        commutation.status = IdentityStatus::kNotApplicable;
        commutation.detail = "empty or mismatched operator matrices";
    }

    // --- Identity 3: dim H^2 = 0. -------------------------------------------
    if (applicable_es_d2) {
        const bool ok = (dim_H2 == 0);
        d2_vanishes.status = ok ? IdentityStatus::kPassed : IdentityStatus::kFailed;
        d2_vanishes.detail = "dim H^2=" + std::to_string(dim_H2);
        if (!ok && first_failure == 0) first_failure = 3;
    } else {
        d2_vanishes.status = IdentityStatus::kNotApplicable;
        d2_vanishes.detail = "n=0, odd n, or ell<5";
    }

    // --- Identity 4: A_{p^2} = A_p^2 - p^{n+1} mod ell * I. -----------------
    // Gated on ell >= 5, same as Eichler-Shimura / d_2=0: [C, thm:relations]'s
    // recursion is contract-backed only under 6 in R^x (HeckeOperatorFamily.h
    // header, "MULTIPLICATION ORDER"); at ell in {2,3} it is RECORDED, not
    // asserted (plan amendment A-F1), and HeckeOperatorFamilySmokeValidation
    // itself only claims T_p_pow(p,2) == T_p_pow_direct(p,2) "for all ell>=5".
    // `A_p2` here is expected to be the INDEPENDENT double-coset construction
    // (HeckeOperatorFamily::T_p_pow_direct(p,2)), not the recursion's own
    // output -- otherwise this identity would be tautological.
    if (SquareNonEmpty(A_p) && SameShape(A_p, A_p2) && ell >= 5) {
        const uint32_t p_mod = static_cast<uint32_t>(p % ell);
        const uint32_t scalar = engine::ModCtx<uint32_t>(ell).pow(p_mod, n + 1);
        const MatrixT<uint32_t> identity(A_p.rows, ell); // MatrixT(rows, p) == identity
        const MatrixT<uint32_t> rhs = A_p * A_p - identity * scalar;
        const bool ok = (A_p2 == rhs);
        p2_recursion.status = ok ? IdentityStatus::kPassed : IdentityStatus::kFailed;
        std::ostringstream d;
        d << "p=" << p << " scalar=p^{n+1}=" << scalar
          << (ok ? " A_{p^2}=A_p^2-scalar*I" : " A_{p^2}!=A_p^2-scalar*I");
        p2_recursion.detail = d.str();
        if (!ok && first_failure == 0) first_failure = 4;
    } else {
        p2_recursion.status = IdentityStatus::kNotApplicable;
        p2_recursion.detail = "empty operator matrix";
    }

    // --- Identity 5: A_n(T_p) L_* = p . L_* A_m(T_p) (slot 5, WP-8). -------
    //
    // [E Sec.5.1] item 6's `L.` half / [E, cl:Tlnil].  The scalar is p^1: the
    // cochain operator is a sum of terms each carrying exactly one
    // coefficient matrix of determinant p, and rho_n(A) L = det(A) L rho_m(A)
    // pulls out one det per term.  See HeckeIdentityCertificate.h.
    //
    // Applicability: ell >= 3 (at ell = 2, m = n - 3 is odd whenever n is
    // even, and H^*(K, R; Sym^odd) = 0 on this model -- the -I / odd-n gap),
    // n >= ell + 1, n_source == n - ell - 1, and shapes that agree.
    {
        const bool shapes_ok =
            SquareNonEmpty(A_p) && SquareNonEmpty(A_p_source) &&
            L_star.rows == A_p.rows && L_star.cols == A_p_source.rows &&
            L_star.rows == dim_H1 && L_star.rows > 0 && L_star.cols > 0;
        const bool applicable_dickson =
            (ell >= 3) && (n >= ell + 1) && (n_source == n - ell - 1) && shapes_ok;
        if (applicable_dickson) {
            const uint32_t p_mod = static_cast<uint32_t>(p % ell);
            const MatrixT<uint32_t> lhs = A_p * L_star;
            const MatrixT<uint32_t> rhs = (L_star * A_p_source) * p_mod;
            const bool ok = (lhs == rhs);
            dickson_multiplication.status =
                ok ? IdentityStatus::kPassed : IdentityStatus::kFailed;
            std::ostringstream d;
            d << "m=" << n_source << " dim H^1(M_m)=" << L_star.cols
              << " p=" << p << " twist=p^1=" << p_mod
              << (ok ? " A_n L_*=p L_* A_m" : " A_n L_* != p L_* A_m");
            dickson_multiplication.detail = d.str();
            if (!ok && first_failure == 0) first_failure = 5;
        } else {
            dickson_multiplication.status = IdentityStatus::kNotApplicable;
            dickson_multiplication.detail =
                (ell < 3)                  ? "ell<3"
                : (n < ell + 1)            ? "n<ell+1 (no Dickson class)"
                : (n_source != n - ell - 1) ? "n_source != n-ell-1"
                                            : "L_* not supplied, empty, or mismatched";
        }
    }

    // --- Identity 6: the residue atlas (slot 6, WP-9). --------------------
    //
    // [E Sec.5.1] item 6's atlas half, under [E] cl:glover's STANDARD-module
    // convention (or, as the negative control, the contragredient one).  See
    // HeckeIdentityCertificate.h for the Grothendieck-group form asserted.
    {
        bool well_formed = false;
        std::string why;
        if (residue_cell.empty()) {
            why = "residue data not supplied";
        } else if (ell < 5 || n % 2 != 0) {
            why = "ell<5 or odd n";
        } else {
            try {
                CheckResidueInputs(*this);
                well_formed = true;
            } catch (const std::logic_error& e) {
                why = e.what();
            }
        }
        if (well_formed) {
            const std::vector<ResidueDifference> diff =
                IdentityResidueDifference(*this, residue_convention);
            const bool ok = diff.empty();
            residue_atlas.status = ok ? IdentityStatus::kPassed : IdentityStatus::kFailed;
            std::ostringstream d;
            uint64_t lhs = 0;
            for (const ResidueCharacterClass& k : residue_cell[1]) lhs += k.multiplicity;
            d << "convention="
              << (residue_convention == GloverConvention::kStandard ? "standard" : "contragredient")
              << " factors=" << IdentityGloverFactors(n, ell, residue_convention).size()
              << " H1_classes=" << residue_cell[1].size() << " H1_mult=" << lhs
              << (ok ? " [H^1] = sum theta^j + H^0-corrections"
                     : " MISMATCH on " + std::to_string(diff.size()) + " class(es)");
            residue_atlas.detail = d.str();
            if (!ok && first_failure == 0) first_failure = 6;
        } else {
            residue_atlas.status = IdentityStatus::kNotApplicable;
            residue_atlas.detail = why;
        }
    }

    // --- Identity 7: rad^i(W) = (soc^i V)^perp (slot 6, WP-3). -----------
    //
    // [E Sec.5.1] item 5 / [C, cl:pd](3).  See HeckeIdentityCertificate.h.
    // Code 6 is reserved for WP-9's atlas identity and never returned here.
    {
        pd_socle_dims.clear();
        pd_radical_dims.clear();
        const uint32_t dV = pd_pairing.rows, dW = pd_pairing.cols;
        bool shapes_ok = !pd_ops_V.empty() && pd_ops_V.size() == pd_ops_W.size() && dV > 0 && dW > 0;
        for (size_t k = 0; shapes_ok && k < pd_ops_V.size(); ++k)
            shapes_ok = pd_ops_V[k].rows == dV && pd_ops_V[k].cols == dV && pd_ops_W[k].rows == dW &&
                        pd_ops_W[k].cols == dW;
        const bool applicable = (ell >= 5) && (n % 2 == 0) && shapes_ok;
        if (!applicable) {
            socle_loewy_pd.status = IdentityStatus::kNotApplicable;
            socle_loewy_pd.detail = (ell < 5) ? "ell<5" : (n % 2 != 0) ? "odd n" : "operators / pairing not supplied or mismatched";
        } else {
            const uint64_t L = ell;
            const Dense G = DenseOf(pd_pairing);
            std::ostringstream d;
            bool ok = true;
            // (a) perfectness.
            Dense Gc = G;
            const size_t rk = Rref(Gc, dW, L).size();
            if (dV != dW || rk != dV) {
                ok = false;
                d << "pairing not perfect (" << dV << "x" << dW << ", rank " << rk << ")";
            } else {
                std::vector<Dense> gV, gW;
                for (const auto& A : pd_ops_V) gV.push_back(DenseOf(A));
                for (const auto& A : pd_ops_W) gW.push_back(DenseOf(A));
                const std::vector<Dense> JV = JacobsonRadical(gV, dV, L);
                const std::vector<Dense> JW = JacobsonRadical(gW, dW, L);
                // soc^0 V = 0, rad^0 W = W.
                std::vector<Vec> S;                       // basis of soc^i V
                std::vector<Vec> R;                       // basis of rad^i W
                for (uint32_t j = 0; j < dW; ++j) { Vec e(dW, 0); e[j] = 1; R.push_back(e); }
                for (uint32_t i = 0; i <= dV + 1 && ok; ++i) {
                    pd_socle_dims.push_back(static_cast<uint32_t>(S.size()));
                    pd_radical_dims.push_back(static_cast<uint32_t>(R.size()));
                    // (soc^i V)^perp = { w : s^T G w = 0 for s in S }.
                    Dense SG;
                    for (const Vec& s : S) {
                        Vec row(dW, 0);
                        for (uint32_t a = 0; a < dV; ++a)
                            if (s[a])
                                for (uint32_t b = 0; b < dW; ++b) row[b] = (row[b] + s[a] * G[a][b]) % L;
                        SG.push_back(row);
                    }
                    const std::vector<Vec> perp = NullSpace(SG, dW, L);
                    std::vector<Vec> both = R;
                    both.insert(both.end(), perp.begin(), perp.end());
                    const size_t r_both = SpanBasis(both, dW, L).size();
                    if (!(perp.size() == R.size() && r_both == R.size())) {
                        ok = false;
                        d << "i=" << i << ": dim rad^i W=" << R.size() << " vs dim (soc^i V)^perp=" << perp.size();
                        break;
                    }
                    if (S.size() == dV) break;   // soc^i V = V, so rad^i W = 0 has just been checked
                    // soc^{i+1} V = { v : j v in soc^i V for every j in J_V }.
                    // Rows y spanning the annihilator of span(S) (all of F^dV when S = 0).
                    const std::vector<Vec> annS = NullSpace(Dense(S.begin(), S.end()), dV, L);
                    Dense stack;
                    for (const Dense& j : JV)
                        for (const Vec& y : annS) {
                            Vec row(dV, 0);   // y^T j
                            for (uint32_t a = 0; a < dV; ++a)
                                if (y[a])
                                    for (uint32_t b = 0; b < dV; ++b) row[b] = (row[b] + y[a] * j[a][b]) % L;
                            stack.push_back(row);
                        }
                    const std::vector<Vec> Snext = NullSpace(stack, dV, L);   // all of V when stack is empty
                    // rad^{i+1} W = span { j r : j in J_W, r in rad^i W }.
                    std::vector<Vec> Rnext;
                    for (const Dense& j : JW)
                        for (const Vec& r : R) Rnext.push_back(Apply(j, r, L));
                    Rnext = SpanBasis(Rnext, dW, L);
                    if (Snext.size() == S.size() && S.size() != dV) {
                        ok = false;
                        d << "i=" << i << ": the socle series of V stalls at " << S.size() << " < " << dV;
                        break;
                    }
                    S = SpanBasis(Snext, dV, L);
                    R = Rnext;
                }
                if (ok) {
                    d << "dim=" << dV << " socle dims";
                    for (uint32_t x : pd_socle_dims) d << " " << x;
                    d << " | radical dims";
                    for (uint32_t x : pd_radical_dims) d << " " << x;
                    d << " | rad^i(W) = (soc^i V)^perp";
                }
            }
            socle_loewy_pd.status = ok ? IdentityStatus::kPassed : IdentityStatus::kFailed;
            socle_loewy_pd.detail = d.str();
            if (!ok && first_failure == 0) first_failure = 7;
        }
    }

    return first_failure;
}

std::string IdentityCertificate::to_string_offset(uint32_t offset) const {
    const std::string ind(offset, ' ');
    std::ostringstream oss;
    oss << ind << "IdentityCertificate (E0a subset, n=" << n << ", ell=" << ell << ")\n";
    oss << ind << "  eichler_shimura: " << StatusName(eichler_shimura.status)
        << " (" << eichler_shimura.detail << ")\n";
    oss << ind << "  commutation:     " << StatusName(commutation.status)
        << " (" << commutation.detail << ")\n";
    oss << ind << "  d2_vanishes:     " << StatusName(d2_vanishes.status)
        << " (" << d2_vanishes.detail << ")\n";
    oss << ind << "  p2_recursion:    " << StatusName(p2_recursion.status)
        << " (" << p2_recursion.detail << ")\n";
    oss << ind << "  dickson_mult:    " << StatusName(dickson_multiplication.status)
        << " (" << dickson_multiplication.detail << ")\n";
    oss << ind << "  residue_atlas:   " << StatusName(residue_atlas.status)
        << " (" << residue_atlas.detail << ")\n";
    oss << ind << "  socle_loewy_pd:  " << StatusName(socle_loewy_pd.status)
        << " (" << socle_loewy_pd.detail << ")\n";
    return oss.str();
}

