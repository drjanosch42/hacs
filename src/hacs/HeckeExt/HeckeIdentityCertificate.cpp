uint32_t DimModularForms(uint32_t k) {
    if (k < 4 || k % 2 != 0) return 0;
    return (k % 12 == 2) ? (k / 12) : (k / 12 + 1);
}

uint32_t DimCuspForms(uint32_t k) {
    const uint32_t mk = DimModularForms(k);
    return (mk == 0) ? 0 : mk - 1;
}

