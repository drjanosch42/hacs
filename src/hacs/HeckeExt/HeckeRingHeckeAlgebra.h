// ===========================================================================
// (hecke-extensions slot 14, WP-6) THE Z/ell^K HECKE-ALGEBRA ROUTE: route R1 of
// docs/implementation/slot14/WP-M1_loewy_note.md ([M1] Sec. 6) as tree code.
// It replaces the Python drivers docs/implementation/slot14/wpm1/{ringalg,
// localize,cell_loewy}.py for production use; they stay as its oracle.
//
// Not binding mathematics.  [M1]'s Proposition 1 (saturation) is the reason the
// route reads what it reads; it is a NOTE, not a [C] statement (the report of
// WP-6 records it as a contract proposal).  The inputs are the shipped objects:
//   * H^1(Gamma; Sym^n Z/ell^K) = (+)_i Z/ell^{a_i} and T_p on it by the shipped
//     module route (hida::RunModuleCell, HeckeOperatorOnKT's H_matrix_module) --
//     for ell >= 5 this is Lambda / ell^K, Lambda = H^1(Gamma; Sym^n Z_ell), since
//     H^2 has no ell-torsion ([C, cl:bockstein]); Lambda's torsion is of Dickson
//     type ([C, prop:heckeH0], [C, rmk:dickson]) and its exponent e_max is read
//     BEFORE the run by the torsion pre-pass ([C, prop:torsionprepass]);
//   * the elimination is the shipped Howell / Smith layer (engine::elim::howell,
//     length, cyclic_decomposition, cyclic_coordinates over ModCtx<uint64_t>::
//     prime_power); no new elimination.
//
// What one cell computes, per F_ell-rational joint system m = (a_p)_{p in S} of
// the T_p (S = {2, 3, 5, 7, ell} by default) on H^1(F_ell) = M_K / ell:
//
//  (i)   e_m, the joint idempotent: per p the F_ell idempotent polynomial E_{p,a}
//        (E = 1 mod (x - a)^mult, E = 0 mod the cofactor of chi_p mod ell),
//        E(T_p) over Z/ell^K (Paterson-Stockmeyer), the product over p, then the
//        Newton lift e <- 3e^2 - 2e^3; e^2 = e and e T_p = T_p e are checked
//        exactly (ENGINE_CHECK).
//  (ii)  the block B_K = e_m M_K as (+)_s Z/ell^{b_s} by the cyclic-summand rule
//        (engine::elim::cyclic_decomposition of the columns of e_m, embedded
//        g_i -> ell^{K - a_i}), and T_p restricted to it (cyclic_coordinates;
//        every restricted column re-verified).  TORSION BLOCKS ARE INCLUDED:
//        at K_cls = max(2, e_max + 1) the summands of order < ell^{K_cls} are
//        the torsion of Lambda_m (exponents `torsion`), the others its free part
//        (rank `free_rank` = f).
//  (iii) A_K := the Z_ell-algebra generated by the T_p in End(B_K) (a subgroup of
//        End(B_K) inside (Z/ell^K)^{D^2}, D = #summands, by Howell forms), its
//        length, and the Hilbert function of A_K (x) F_ell at m = (ell, T_p - a_p);
//        A_1 := the same on B_K / ell = H^1(F_ell)_m (the census algebra A).
//  (iv)  on a torsion block, THE FREE PART separately: with t = max torsion
//        exponent, ell^t B_K = (Lambda_m / tors) / ell^{K - t} Hecke-equivariantly
//        (multiplication by ell^t on Lambda has kernel exactly the torsion), so the
//        image of T on the free quotient at level K' = K - t is A_K / A_K[ell^t]
//        ~= ell^t A_K; its length and Hilbert function are read on ell^t-scaled
//        generators (no kernel computation).
//
// Stopping rule (per block): the free rank of T_m is rank_T = ceil(f / 2) (over
// Q_ell the block is M_{k,m} (+) S_{k,m}, at most one Eisenstein line).  A free
// block is `stable` at the first K with dim A_K / ell == rank_T ([M1] Prop. 1(3):
// A_K / ell is then T_m / ell); a torsion block's FREE PART is stable at the first
// K with dim == rank_T (`torsion_free_stable`), and a pure-torsion block (f = 0)
// at K = K_cls, where B_K = Lambda_m exactly (`torsion_stable`).  The full algebra
// of a torsion block with f > 0 is reported at the same K without a certificate
// (the Z_ell-torsion of T_m is not bounded a priori).  eps_K = K rank - length
// ([M1] Sec. 2, <= delta).
//
// (slot 15, WP-5) THE CERTIFIED VERDICT.  Since [C] v1.15.0 the stopping rule is
// a theorem: [C, prop:saturation](3) (P15), [C, prop:satdefect] (P17),
// [C, lem:heckerankone], [C, lem:freepart] and [C, cor:stablecert] -- in the
// form of the referee's repair B1 (docs/implementation/slot15/
// WP-4_referee.md Sec. 2.3): the block e_m M is the block of a maximal ideal m'
// of T' = Z_ell[T_p : p in S] (the joint F_ell-rational system of S), which may
// be a SUM of several blocks of the full algebra T^L; the rank formula
// rank e T^L = ceil(f / 2), f = rank(e L'), holds for every idempotent e of
// T^L (at level 1 at most one Eisenstein system lies in any block), so
// dim A'_K / ell <= rank T'_{m'} <= ceil(f / 2) for the T'-block, and equality
// certifies A'_K / ell ~= T'_{m'} / ell (Hilbert function and Loewy length
// included) at this and every larger K.  (audit M3) The Hilbert function
// PRINTED is the route's reading of A'_K / ell (the certificate checks its sum and
// h_0 = 1); the certificate is of the isomorphism, which carries it.  It certifies T'_{m'} / ell, NOT
// T^L_m / ell: the generation certificate of [C, cor:stablecert](2) is a
// separate check this route does not run.  CertifyStable re-derives the
// inputs in exact Z/ell^K arithmetic and throws (ENGINE_CHECK) on any
// mismatch -- it never downgrades silently; LoewyBlock::stable_cert records
// the tri-state `certified` | `reading` | `none`.
//
// (slot 15, WP-5) THE DIGIT ROUTE.  ell^K >= 2^64: the module run is
// hecke::ladic_cell::RunCell (the (C2) digit route of [E] sec:ring, its level
// driver and canonicalisation, engine::ladic) at exactly the working precision
// K, and the algebra reading runs on engine::ladic's Ring / howell /
// cyclic_decomposition -- the same Sec. 13.5 - 13.6 objects, no new
// elimination.  An OpModule then carries its operators as base-ell digits
// (OpModule::dop); every reading is basis-free, so the two routes give the
// same LOEWY_RING lines wherever both apply (HeckeRingLoewyValidation (C3)).
//
// Pipeline side only, console-free; writes nothing, emits no record and no golden
// object.  Lines: LOEWY_RING (one per block, LoewyRingLine).
// ===========================================================================

