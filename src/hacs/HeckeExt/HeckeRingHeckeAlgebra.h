// A finite module N = (+)_s Z/ell^{b_s}, 1 <= b_s, with commuting endomorphisms
// (op[i] of primes[i]; every op has row_exp == exps).
// (slot-15 WP-5) The digit form: digit_K > 0 means the operators live in `dop`
// (and `op` is empty): dop[i] holds op i as rank()^2 entries, row-major, column
// convention (T b_j = sum_i A_ij b_i, entry (i, j) in [0, ell^{b_i})), each
// entry as digit_K base-ell digits, low -> high (digit_K >= max b_s).  The
// digit route produces it for ell^K >= 2^64 (and the oracle route Digit below
// 2^64); every function of this header accepts either form.
struct OpModule {
    uint64_t ell = 0;
    std::vector<uint32_t> exps;
    std::vector<uint64_t> primes;
    std::vector<RingMat> op;
    uint32_t digit_K = 0;
    std::vector<std::vector<uint32_t>> dop;
    // (S25 HZ-LOC audit F3) the word RunModule ran on: "u32" (RunModuleT<uint32_t>), "u64" (RunModuleT<uint64_t>), "digit", "hida";
    // empty for a module not made by RunModule.  A label only: no reading depends on it.
    std::string word;
    uint32_t rank() const { return static_cast<uint32_t>(exps.size()); }
    bool is_digit() const { return digit_K > 0; }
};

// The algebra generated by the ops in End(N), read at the maximal ideal
// m = (ell, T_p - a_p) (system aligned with N.primes, a_p in [0, ell)).
// shift = t > 0 reads A / A[ell^t] ~= ell^t A instead (item (iv)).
struct AlgebraReading {
    uint32_t length = 0;                 // length_{Z_ell}
    uint32_t dim_mod_ell = 0;            // dim_F_ell of (.) / ell
    std::vector<uint32_t> hilbert;       // Hilbert function at m; its size = Loewy length
    uint32_t loewy() const { return static_cast<uint32_t>(hilbert.size()); }
};
AlgebraReading ReadAlgebra(const OpModule& N, const std::vector<uint64_t>& system, uint32_t shift = 0);

// N / ell N with the ops mod ell (every exponent 1).
OpModule ReduceModEll(const OpModule& N);

// The F_ell-rational joint systems of the ops on N / ell N, lexicographic in
// N.primes order, each with the F_ell-dimension of its joint generalised
// eigenspace.  Only residue degree 1 (an irreducible factor of degree > 1 of
// some chi_p mod ell is not a system here).
struct JointSystem {
    std::vector<uint64_t> a;
    uint32_t dim = 0;
};
std::vector<JointSystem> RationalSystems(const OpModule& N);

// e_m on N (exponents <= K, K = max exponent) and the block e_m N as an OpModule.
// A system that does not occur gives an empty block (rank 0).  On a digit
// module, `e` stays empty (the idempotent lives in digit form only) and the
// block is a digit module.
struct Block {
    RingMat e;
    OpModule local;
};
Block Localize(const OpModule& N, const std::vector<uint64_t>& system);

// ---- the module run --------------------------------------------------------------
// H^1(Gamma; Sym^n Z/ell^K) = (+)_i Z/ell^{a_i} with T_p (p in primes, ascending)
// by the shipped module route.  Native: uint32_t elements while ell^K < 2^32,
// uint64_t above; Hida: hida::RunModuleCell (uint64_t throughout) -- the same
// objects, the oracle arm (W).  (slot-15 WP-5) ell^K >= 2^64: the digit route
// (hecke::ladic_cell::RunCell at module_K = K, its per-cell rule and caps; a
// cell it does not execute is its NotImplementedInThisBuild) under Native;
// Hida still refuses there.  Digit: the digit route at EVERY K, the native
// range included (the oracle of HeckeRingLoewyValidation (C3); its only caller).
enum class ModuleRoute { Native, Hida, Digit };
OpModule RunModule(uint32_t n, uint64_t ell, uint32_t K, const std::vector<uint64_t>& primes,
                   ModuleRoute route = ModuleRoute::Native);

// ---- (slot-23 G1) ONE MODULE RUN PER CELL: the levels below it derived ----------------
// [C, lem:precisionreduction] (v1.23.0-pre.3): for ell >= 5, level 1, H^1 and operators from a tau-table
// with every fill over Z at every level (the module route refuses a mod-ell table at every run level,
// RefuseCoefficientRing), M_K ~= M_{K'} / ell^K M_{K'} as Z[X_p]-modules for K <= K' -- so every reading
// the route prints at a level K (the joint systems, the block, A_K and its length / Hilbert function,
// eps^sat_K, the stopping verdict and its certificate, the defect ideal I) is the same read on the
// DERIVED module M_{K'}|K as on a fresh run at K ([C, lem:precisionreduction](3)).
// [C, obl:precisionreuse] is what the code below meets:
//   (i)   scope: native and digit module route only (ModuleRoute::Hida takes the per-K route, by name);
//         every failure of a run above the request (a refusal, an exception, a cap) drops the cell to
//         the per-K route for the levels still unread, the readings already taken kept;
//   (ii)  downward only: a level above the largest run so far (K*) triggers a new run (the restart rule);
//         the run levels are chosen by RunLevelPolicy, which moves no printed value;
//   (iii) the derived module exactly (ReduceToLevel) and its checks (CheckDerivedModule);
//   (v)   the per-K route stays as the oracle and the rollback arm, HECKE_PRECISION_REUSE=0 (read-only:
//         it selects a route, never a value; PrecisionReuseEffectiveLine() is its EFFECTIVE line);
//   (vi)  LoewyCell::K_run / SatCell::K_run keep the levels READ (Lv_read, the per-K route's list), the
//         levels RUN go to the new field Lv_run, and module_seconds counts the runs only;
//   (vii) CertifyStable runs unchanged on the modules read; the run level each was derived from is
//         recorded beside it (LoewyBlock::cert_from_cls / cert_from_K).

// M_{K'}|K of [C, lem:precisionreduction](2): exponents min(a_i, K), row i of every operator reduced mod
// ell^{min(a_i, K)} (OpModule's row-exponent convention).  A digit module keeps the lowest min(a_i, K)
// base-ell digits of row i, reshaped to K digits per entry; with native_out and ell^K < 2^64 it is
// returned in the native form instead (the form the per-K route's ModuleRoute::Native run has there).
// K >= 1.  Lemma (4), never derive upwards: on a native module a K at or above its largest exponent returns
// the module itself (min(a_i, K) = a_i, nothing derived); on a digit module a K above digit_K is refused.
OpModule ReduceToLevel(const OpModule& N, uint32_t K, bool native_out = false);

// [C, obl:precisionreuse](iii) on a module M read at level K: it has D summands, every exponent lies in
// [1, K], the T_p commute on it (CheckLevelModule).  CheckDerivedModule, on M = ReduceToLevel(run, K), adds
// (G1 audit F3) the checks tying M to its run: every entry canonical (row i in [0, ell^{a_i}); on a digit
// module every digit < ell and zero at and above a_i), and ReduceModEll(M) = ReduceModEll(run) entry for
// entry.  CheckRunModule (once per run): the K = 1 reduction of the run equals ReduceModEll entry for entry.
// Each failure throws std::logic_error (ENGINE_CHECK_MSG) whose message names the check: "summands",
// "exponent", "commute", "range", "ReduceModEll".
void CheckLevelModule(const OpModule& M, uint32_t D, uint32_t K);
void CheckDerivedModule(const OpModule& run, const OpModule& derived, uint32_t K);
void CheckRunModule(const OpModule& run);

// The run-level policy ([C, obl:precisionreuse](ii): free, moves no printed value).  Auto: for
// ell <= kEagerEllMax the first run looks ahead to the largest level <= K_need in the SAME word
// (u32 / u64) as the request; above it the first run is at the request (max(2, K_cls)) and each restart
// looks ahead within the word.  The digit range (ell^K >= 2^64) never looks ahead.  AtRequest: every run
// at the request (one run per level read above K*, the most restarts); Lazy: the first run at the request,
// restarts look ahead (Auto's rule above kEagerEllMax, at every ell); SameWord: every run looks ahead within
// the word; Max: every run at K_need, whatever the word (validation arms: the u32 -> u64 crossing).
enum class RunLevelPolicy { Auto, AtRequest, Lazy, SameWord, Max };
// (S23 G2-A, F4 of the G1 audit; G2_plan.md Sec. 1.4) kEagerEllMax = 11, was 13: 0 of 67 ell = 13 cells
// (n <= 200) read K_stab >= 3, so the look-ahead never paid there and cost up to 11 %; at ell = 11, 25 of 114
// do and eager wins by ~12 %.  Value-neutral ([C, obl:precisionreuse](ii): which K'' runs moves only Lv_run).
constexpr uint64_t kEagerEllMax = 11;

