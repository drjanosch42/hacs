// ---- the cell driver ---------------------------------------------------------
struct LoewyOptions {
    uint32_t kmax = 6;                   // the largest precision read, KMAX (the digit route above 2^64)
    std::vector<uint64_t> primes;        // S; empty = {2, 3, 5, 7, ell}
    ModuleRoute route = ModuleRoute::Native;
    bool certify = true;                 // (slot-15 WP-5) run CertifyStable on every stable-family verdict
    // (slot-18 WP-5 (e), WP-8 audit MINOR-4) the caller's torsion pre-pass at (n, ell), if it already ran one
    // ([C, prop:torsionprepass]; the hecke_ring_loewy verb does, for K_cls): used instead of a second run, and handed
    // on to the certificates, so the pre-pass runs ONCE per cell.  Checked to be at (n, ell).  Value-free.
    const hecke::ordinary::TorsionPrepass* prepass = nullptr;
};

struct LoewyStep {
    uint32_t K = 0;
    AlgebraReading full;                 // A_K (x) F_ell on the whole block
    bool has_free = false;               // the free-part reading (iv) was taken
    uint32_t free_level = 0;             // K' = K - t
    AlgebraReading free_part;
};

struct LoewyBlock {
    std::vector<uint64_t> system;        // aligned with LoewyCell::primes
    uint32_t D = 0;                      // dim_F H^1(F_ell)_m (= summands of B_K)
    uint32_t free_rank = 0;              // f
    std::vector<uint32_t> torsion;       // torsion exponents of Lambda_m, descending
    uint32_t rank_T = 0;                 // ceil(f / 2)
    AlgebraReading A1;                   // the census algebra A (on H^1(F_ell)_m)
    std::vector<LoewyStep> history;      // one step per K run (K = 2, 3, ...)
    std::string verdict;                 // reduced_rank1 | stable | not_stable_at_KMAX |
                                         // torsion_stable | torsion_free_stable | torsion_not_stable_at_KMAX
    uint32_t K_stab = 0;                 // the K of the last step (the stable one when stable)
    int64_t eps = 0;                     // K rank - length at K_stab (free part on a torsion block)
    // (slot-15 WP-5) the tri-state of the stopping verdict: "certified" (CertifyStable passed,
    // [C, cor:stablecert]), "reading" (a stable-family verdict, the certificate not run:
    // LoewyOptions::certify = false), "none" (no stable verdict: *_not_stable_at_KMAX).
    std::string stable_cert = "none";
    // (slot-23 G1, [C, obl:precisionreuse](vii)) the run levels the certificate's modules N_cls and N_K were
    // derived from (the level itself when run there; 0: no certificate).  Recorded beside stable_cert, not in it:
    // on a derived module `certified` rests on [C, lem:precisionreduction](1) as well as on [C, cor:stablecert].
    uint32_t cert_from_cls = 0, cert_from_K = 0;
    bool stable_family() const;          // stable | torsion_free_stable | torsion_stable | reduced_rank1
    bool nonreduced_A1() const { return A1.dim_mod_ell > 1; }
    bool cf9_holds() const { return A1.loewy() <= 2; }            // [E] pr:latticesplit (CONJ)
    const AlgebraReading* last_T() const;                          // the T_m / ell reading of the last step
    // The CERTIFIED reading of the last step (slot-14 WP-16, audit S-6): the free part on a
    // torsion block with f > 0 (its full algebra is uncertified, see the header), the full
    // algebra otherwise (a free block; a pure-torsion block, where B_K = Lambda_m).
    const AlgebraReading* certified_T() const;
    const char* cert() const;                                      // "free" | "full" | "torsion"
    bool hidden() const;                                           // A1 = F_ell, the CERTIFIED T_m / ell not
};

// The stopping rule's loud check (slot-14 WP-16, audit S-2): a certified reading with
// dim A_K / ell > rank_T = ceil(f / 2) would refute the rank formula, the free-rank reading
// at K_cls or the module run itself -- throws std::logic_error (ENGINE_CHECK) instead of
// letting the block run on to a silent `not_stable_at_KMAX`.
// (slot-15 WP-5) The bound it checks is [C, cor:stablecert](1)'s dim A'_K / ell <= rank T'_{m'}
// <= ceil(f / 2) for the block of a maximal ideal m' of T' = Z_ell[T_p : p in S] -- the B1-repaired
// [C, lem:heckerankone] (rank e T^L = ceil(rank(e L') / 2) for EVERY idempotent e of T^L), which is
// what makes it valid when the T'-block is a sum of several T^L-blocks.
void CheckWithinRankT(const AlgebraReading& reading, uint32_t rank_T);

// ---- (slot-15 WP-5) the certificate of the stopping verdict --------------------
// [C, cor:stablecert] (B1 form) applied to one block.  Re-derives, in exact Z/ell^K
// arithmetic, from the module runs themselves:
//   (1) the block: e_m by the route's own construction (a polynomial in the T_p, so
//       e in T'), e^2 = e, e T_p = T_p e; the T_p commute on the block; every T_p - a_p
//       is nilpotent on the block mod ell.  Then e = e_{m'}: e in Z[T_p], e^2 = e,
//       e != 0 and T_p - a_p nilpotent on e(N / ell) (audit M1).  That
//       rank_F(e mod ell) equals the joint generalised eigenspace's dimension of
//       RationalSystems is a CONSISTENCY check (both reduce the same projector
//       construction), not an independent verification;
//   (2) f = rank(e L') and the torsion exponents from the SMITH invariant factors
//       of e M at K_cls (a second entry point, not the cyclic decomposition the
//       route read them from); and K_cls separates torsion from free on the whole
//       module: its order-ell^{K_cls} summands number rank H^1 (x) Z_ell = 2 d_k - 1
//       (hecke::ordinary::FreeRankH1), its other summands are the pre-pass torsion
//       ([C, prop:torsionprepass], from rho_n(S), rho_n(T) alone), K_cls > e_max;
//   (3) rank_T = ceil(f / 2) ([C, lem:heckerankone], B1);
//   (4) A'_K by a SECOND construction -- the Z-span of the monomials
//       prod_p T_p^{i_p}, 0 <= i_p < D (Cayley-Hamilton on a D-generated module),
//       not the route's closure iteration -- its length and dim A'_K / ell, on the
//       ell^t-scaled generators for the free part of a torsion block
//       ([C, lem:freepart](2));
//   (5) the criterion dim A'_K / ell == ceil(f / 2) ([C, cor:stablecert](1)); for a
//       pure-torsion block f == 0 and K >= t ([C, lem:freepart](3));
//   (6) eps_K = level * rank_T - length(A'_K), >= 0, equal to the route's eps, and
//       the route's history consistent with [C, prop:satdefect](2): eps^sat is
//       non-decreasing and >= 0 along the recorded levels, dim <= rank_T at each.
// Every re-derived value is compared with the route's claim (the block as read);
// ANY mismatch throws std::logic_error (ENGINE_CHECK_MSG) -- never a downgrade.
// N_cls is the module at K_cls, N_K the module at the claim's level (K_stab; for
// reduced_rank1, N_K = N_cls and the reading is A1 at level 1).
struct StableCertificate {
    std::string label = "cor:stablecert";
    std::string verdict;
    uint32_t level = 0;                  // K (stable), K - t (torsion_free_stable), K_cls (torsion_stable), 1 (reduced_rank1)
    uint32_t f = 0, rank_T = 0, length = 0, dim = 0;
    std::vector<uint32_t> torsion;
    int64_t eps = 0;
    uint32_t monomial_generators = 0;    // the size of the monomial spanning set of (4)
};
StableCertificate CertifyStable(uint32_t n, const OpModule& N_cls, const OpModule& N_K, const LoewyBlock& claim, uint32_t K_cls);
