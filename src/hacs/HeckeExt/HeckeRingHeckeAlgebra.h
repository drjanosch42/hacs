// ---- (S24 SATPERF) the per-cell memo of the whole-module derivations --------------
// docs/implementation/slot24/SATPERF_report.md.  A big sat cell spent ~95 % of its wall re-deriving, PER BLOCK and
// serially, objects that depend on the whole module only: its characteristic polynomials (Berkowitz, O(r^4)), its
// RationalSystems (one Paterson-Stockmeyer evaluation per root), the joint idempotent of a system (up to five times per
// block: the route's Localize, the certificate's Localize and Smith reading at K_cls and again at K), the torsion
// pre-pass.  ModuleDerived holds them for ONE module, computed on first use by exactly the functions the per-block code
// calls (Localize(N, a) == block(a), RationalSystems(N) == systems(), ...), so every value is the same; the module must
// outlive the memo (LevelCache's references do).  Not thread-safe (one cell, one thread; the parallelism is inside the
// End(N) products).
//
// The lever HECKE_SAT_PERF (read-only; unset / "1": on; exactly "0": the route of 4dd1a7e0 -- no memo, the serial u128
// End(N) product; anything else warns and stays on): SatPerfEnabled() / ScopedSatPerf.  While on, (a) the sat cell
// (ComputeSaturationDefectCell) reads its whole-module objects through ModuleDerived and hands its pre-pass to the
// certificate, and (b) every End(N) product (EndCtx::mul) accumulates in uint64_t when r * max A * max B < 2^64 (an
// exact sum, so the same residue) and splits its output rows over engine::elim::parallel_hook() when one is installed
// (the sat cell installs engine::tape::ScopedHostElimHook around its post-module stages; each row is the same exact sum
// whatever the split).  Neither can move a value; HeckeSatPerfValidation (SP) compares the SAT_DEFECT lines on and off
// byte for byte.  The uint64_t accumulation is taken per product on the ACTUAL maxima: for dense full-range entries that is
// roughly q^2 r < 2^64 (q = ell^K), e.g. at r = 429, ell = 103 up to K = 4 and not at K >= 5 (SATPERF audit F3).
// The EFFECTIVE line: the first sat cell prints SatPerfEffectiveLine(false) (the configuration only) when the variable is
// set; SatPerfEffectiveLine(true) adds the process-total counters (memo hits / misses, narrow / wide / split products), read
// after the work (HeckeSatPerfValidation's last line; the cells arm's SAT_DEFECT_TIMES line prints per-cell deltas).
