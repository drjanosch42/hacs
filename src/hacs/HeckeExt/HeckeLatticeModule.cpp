// ---- the module run -------------------------------------------------------------------------------------
LatticeModule RunLatticeModule(uint32_t n, uint64_t ell, uint32_t K, const std::vector<uint64_t>& primes_in) {
    const auto t0 = std::chrono::steady_clock::now();
    ENGINE_CHECK_MSG(n >= 2 && n % 2 == 0, "HeckeLatticeModule: n >= 2 even (odd n vanishes on this model)");
    ENGINE_CHECK_MSG(ell >= 5 && K >= 2, "HeckeLatticeModule: ell >= 5 and K >= 2 (the Z/ell^K module route)");
    std::vector<uint64_t> primes = primes_in;
    std::sort(primes.begin(), primes.end());
    primes.erase(std::unique(primes.begin(), primes.end()), primes.end());
    const uint64_t q = PowU(ell, K);
    const hecke::ScopedCoefficientRing ring(K);
    std::unique_ptr<SimplicialComplex> Kx;
    std::unique_ptr<hecke::SL2ZTessellationTables> model;
    {
        std::lock_guard<std::mutex> lk(hecke::tau_construction_mutex());
        Kx.reset(new SimplicialComplex(CreateSL2ZFundamentalDomainTriangulation()));
        model.reset(new hecke::SL2ZTessellationTables(*Kx));
    }
    const engine::ModCtx<uint64_t> ctx = hecke::CoefficientRingContext<uint64_t>("HeckeLatticeModule", ell, K);
    LocalSystemSimplicialComplexT<uint64_t> lssc(*Kx, hecke::GenerateSL2ZRelationsRing<uint64_t>(*Kx, n, ctx), n + 1, ctx.p);
    EquivariantCohomologyOnKT<uint64_t> coh(&lssc);
    coh.compute_cohomology();
    LatticeModule run;
    run.n = n;
    run.ell = ell;
    run.K = K;
    run.primes = primes;
    run.exps = coh.module_degree(1).dec.exponents;
    const uint32_t r = static_cast<uint32_t>(run.exps.size());
    for (uint64_t p : primes) {
        std::unique_ptr<hecke::HeckeCosetTablesT<uint64_t>> cosets;
        std::unique_ptr<hecke::HeckeTauTableT<uint64_t>> tau;
        {
            std::lock_guard<std::mutex> lk(hecke::tau_construction_mutex());
            cosets.reset(new hecke::HeckeCosetTablesT<uint64_t>(p, 1, ell, n));
            tau.reset(new hecke::HeckeTauTableT<uint64_t>(*Kx, *model, *cosets, ell, n));
        }
        hecke::HeckeOperatorOnKT<uint64_t> opk(&coh, cosets.get(), tau.get());
        opk.compute();
        const engine::DenseBuf<uint64_t>& A = opk.H_matrix_module(1);
        ENGINE_CHECK(A.rows == r && A.cols == r);
        RingMat T;
        T.ell = ell;
        T.row_exp = run.exps;
        for (uint32_t i = 0; i < r; ++i)
            for (uint32_t j = 0; j < r; ++j) T.a.push_back(A.at(i, j));
        run.T.push_back(hecke::ordinary::Canonical(T));
    }
    // iota^* ([C, def:iota](iv)): (iota^* f)(sigma_s) = -eps_s rho_n(iota) f(iota_K sigma_s), rho_n(iota) = diag((-1)^{n-i}).
    const hecke::IotaSimplicialMap im = hecke::BuildIotaSimplicialMapOnModel(*Kx, *model);
    const auto& H = coh.module_degree(1).H;
    const uint32_t dV = n + 1;
    ENGINE_CHECK_MSG(im.num_degrees() >= 2, "HeckeLatticeModule: iota_K has no degree 1");
    const uint32_t N1 = static_cast<uint32_t>(im.image_index[1].size());
    ENGINE_CHECK_MSG(H.rows == N1 * dV && H.cols == r, "HeckeLatticeModule: the module basis is not in flat 1-cochain coordinates");
    engine::DenseBuf<uint64_t> Y(H.rows, r);
    for (uint32_t s = 0; s < N1; ++s) {
        const uint32_t t = im.image_index[1][s];
        const int eps = im.image_sign[1][s];
        for (uint32_t i = 0; i < dV; ++i) {
            const bool rho_minus = ((n - i) % 2u) == 1u;
            const bool neg = (eps > 0) != rho_minus;      // sign = -eps * (-1)^{n-i}
            for (uint32_t j = 0; j < r; ++j) {
                const uint64_t x = H.at(t * dV + i, j) % q;
                Y.at(s * dV + i, j) = neg ? (q - x) % q : x;
            }
        }
    }
    const std::vector<std::vector<uint64_t>> co = coh.H_class_coordinates(1, engine::cview(Y));
    run.iota.ell = ell;
    run.iota.row_exp = run.exps;
    run.iota.a.assign(static_cast<size_t>(r) * r, 0);
    for (uint32_t j = 0; j < r; ++j)
        for (uint32_t i = 0; i < r; ++i) run.iota.a[static_cast<size_t>(i) * r + j] = co[j][i];
    run.iota = hecke::ordinary::Canonical(run.iota);
    ENGINE_CHECK_MSG(hecke::ordinary::Mul(run.iota, run.iota) == hecke::ordinary::Identity(ell, run.exps),
                     "HeckeLatticeModule: iota^* is not an involution on H^1");
    for (const RingMat& T : run.T)
        ENGINE_CHECK_MSG(hecke::ordinary::Mul(run.iota, T) == hecke::ordinary::Mul(T, run.iota),
                         "HeckeLatticeModule: iota^* does not commute with T_p ([C, obl:iota](v))");
    run.seconds = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
    return run;
}

uint32_t RankModEllJoint(const std::vector<FreeMat>& Xs) {
    ENGINE_CHECK(!Xs.empty());
    const uint64_t ell = Xs[0].ell;
    const uint32_t r = Xs[0].r;
    // rows = r, columns = all the X's columns side by side; rank of the column span mod ell
    std::vector<std::vector<uint64_t>> M(r);
    for (const FreeMat& X : Xs) {
        ENGINE_CHECK(X.r == r && X.ell == ell);
        for (uint32_t i = 0; i < r; ++i)
            for (uint32_t j = 0; j < r; ++j) M[i].push_back(X.at(i, j) % ell);
    }
    const uint32_t nc = static_cast<uint32_t>(M.empty() ? 0 : M[0].size());
    uint32_t rank = 0;
    for (uint32_t c = 0; c < nc && rank < r; ++c) {
        uint32_t p = rank;
        while (p < r && M[p][c] == 0) ++p;
        if (p == r) continue;
        std::swap(M[p], M[rank]);
        uint64_t inv = 1;
        {   // Fermat inverse mod the prime ell
            uint64_t b = M[rank][c], e = ell - 2;
            while (e) {
                if (e & 1) inv = MulMod(inv, b, ell);
                b = MulMod(b, b, ell);
                e >>= 1;
            }
        }
        for (uint32_t i = 0; i < r; ++i) {
            if (i == rank || M[i][c] == 0) continue;
            const uint64_t f = MulMod(M[i][c], inv, ell);
            for (uint32_t k = c; k < nc; ++k) M[i][k] = (M[i][k] + ell * ell - MulMod(f, M[rank][k], ell)) % ell;
        }
        ++rank;
    }
    return rank;
}

std::vector<uint32_t> SmithValuations(const FreeMat& X) {
    std::vector<uint32_t> out;
    if (X.r == 0) return out;
    if (X.K == 1) {
        const uint32_t rk = RankModEllJoint({X});
        out.assign(rk, 0);
        out.resize(X.r, 1);
        return out;
    }
    const engine::ModCtx<uint64_t> ctx = engine::ModCtx<uint64_t>::prime_power(X.ell, X.K);
    engine::DenseBuf<uint64_t> I(X.r, X.r), A(X.r, X.r);
    for (uint32_t i = 0; i < X.r; ++i) {
        I.at(i, i) = 1;
        for (uint32_t j = 0; j < X.r; ++j) A.at(i, j) = X.at(i, j);
    }
    // coker X = (colspan I + colspan X) / colspan X = (+)_i Z/ell^{e_i}, e_i >= 1; the other r - #e valuations are 0.
    const std::vector<uint32_t> e = engine::elim::invariant_factors<uint64_t>(ctx, engine::cview(I), engine::cview(A));
    ENGINE_CHECK(e.size() <= X.r);
    out.assign(X.r - e.size(), 0);
    out.insert(out.end(), e.begin(), e.end());
    std::sort(out.begin(), out.end());
    return out;
}

bool FreePart::free() const {
    if (exps.size() != rank) return false;
    for (uint32_t e : exps)
        if (e != (T.empty() ? iota.K : T[0].K)) return false;
    return true;
}

const FreeMat& LatticeBlock::op(const FreePart& part, uint64_t p) const {
    for (size_t i = 0; i < primes.size(); ++i)
        if (primes[i] == p) return part.T.at(i);
    ENGINE_CHECK_MSG(false, "HeckeLatticeModule: T_p was not computed for this p");
    return part.T.at(0);
}

LatticeBlock LocalizeBlock(const LatticeModule& run, const std::vector<uint64_t>& sys_primes, const std::vector<uint64_t>& sys_a) {
    const auto t0 = std::chrono::steady_clock::now();
    ENGINE_CHECK_MSG(sys_primes.size() == sys_a.size() && !sys_primes.empty(), "HeckeLatticeModule: a system is required");
    const uint64_t ell = run.ell;
    const uint32_t K = run.K;
    LatticeBlock B;
    B.n = run.n;
    B.ell = ell;
    B.K = K;
    B.primes = run.primes;
    B.sys_primes = sys_primes;
    B.sys_a = sys_a;
    std::vector<size_t> sys_idx;
    for (uint64_t p : B.sys_primes) {
        const auto it = std::find(B.primes.begin(), B.primes.end(), p);
        ENGINE_CHECK_MSG(it != B.primes.end(), "HeckeLatticeModule: every system prime must be among the computed T_p");
        sys_idx.push_back(static_cast<size_t>(it - B.primes.begin()));
    }
    B.H_exps = run.exps;

    // (i) e_m
    RingMat e = hecke::ordinary::Identity(ell, run.exps);
    for (size_t s = 0; s < sys_idx.size(); ++s) {
        const RingMat& T = run.T[sys_idx[s]];
        uint32_t mult = 0;
        const Poly64 E = IdempotentPoly(CharpolyModEll(ell, T), B.sys_a[s], ell, mult);
        e = hecke::ordinary::Mul(e, EvalPolyRM(E, T));
    }
    for (uint32_t it = 0;; ++it) {
        ENGINE_CHECK_MSG(it < 64, "HeckeLatticeModule: the idempotent's Newton lift did not converge");
        const RingMat e2 = hecke::ordinary::Mul(e, e);
        if (e2 == e) break;
        e = Lin(e2, 3, hecke::ordinary::Mul(e2, e), PowU(ell, K) - 2);
    }
    for (const RingMat& T : run.T)
        ENGINE_CHECK_MSG(hecke::ordinary::Mul(e, T) == hecke::ordinary::Mul(T, e), "HeckeLatticeModule: e_m does not commute with T_p");
    ENGINE_CHECK_MSG(hecke::ordinary::Mul(e, run.iota) == hecke::ordinary::Mul(run.iota, e), "HeckeLatticeModule: e_m does not commute with iota^*");
    B.D = hecke::ordinary::RankModEll(e);

    // (ii) the block, (iii) its sign parts
    const engine::ModCtx<uint64_t> ctx = engine::ModCtx<uint64_t>::prime_power(ell, K);
    B.block = MakePart(ctx, e, run.T, run.iota, K);
    const uint64_t q = PowU(ell, K);
    const uint64_t inv2 = (q + 1) / 2;
    const RingMat Pp = hecke::ordinary::Mul(e, Lin(hecke::ordinary::Identity(ell, run.exps), inv2, run.iota, inv2));
    const RingMat Pm = hecke::ordinary::Mul(e, Lin(hecke::ordinary::Identity(ell, run.exps), inv2, run.iota, q - inv2));
    B.plus = MakePart(ctx, Pp, run.T, run.iota, K);
    B.minus = MakePart(ctx, Pm, run.T, run.iota, K);
    ENGINE_CHECK_MSG(B.plus.iota == Identity(ell, K, B.plus.rank), "HeckeLatticeModule: iota^* != +1 on the plus part");
    ENGINE_CHECK_MSG(B.minus.iota == Scale(Identity(ell, K, B.minus.rank), q - 1), "HeckeLatticeModule: iota^* != -1 on the minus part");
    B.seconds = run.seconds + std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
    return B;
}

LatticeBlock ReduceBlock(const LatticeBlock& B, uint32_t M) {
    ENGINE_CHECK_MSG(M >= 1 && M <= B.K, "HeckeLatticeModule: ReduceBlock needs 1 <= M <= K");
    ENGINE_CHECK_MSG(B.block.free() && B.plus.free() && B.minus.free(), "HeckeLatticeModule: ReduceBlock needs a free block");
    LatticeBlock R = B;
    R.K = M;
    for (FreePart* P : {&R.block, &R.plus, &R.minus}) {
        for (FreeMat& X : P->T) X = ReduceTo(X, M);
        P->iota = ReduceTo(P->iota, M);
        P->exps.assign(P->rank, M);
    }
    return R;
}

std::string JoinU32(const std::vector<uint32_t>& v) {
    std::ostringstream os;
    for (size_t i = 0; i < v.size(); ++i) os << (i ? "," : "") << v[i];
    return os.str();
}

