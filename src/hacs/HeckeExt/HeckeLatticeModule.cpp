uint64_t PowU(uint64_t b, uint32_t e) {
    const uint64_t r = engine::scalar::powfit(b, e);   // 0 when b^e >= 2^64
    ENGINE_CHECK_MSG(r != 0 && r <= (uint64_t(1) << 62), "HeckeLatticeModule: ell^K must stay below 2^62");
    return r;
}

inline uint64_t MulMod(uint64_t a, uint64_t b, uint64_t q) { return engine::scalar::mulmod(a, b, q); }

// ---- matrices on N = (+)_i Z/ell^{a_i} (RingMat, row i mod ell^{a_i}) --------------------------------------
std::vector<uint64_t> RowMods(const RingMat& A) {
    std::vector<uint64_t> m(A.n());
    for (uint32_t i = 0; i < A.n(); ++i) m[i] = PowU(A.ell, A.row_exp[i]);
    return m;
}

RingMat Lin(const RingMat& A, uint64_t ca, const RingMat& B, uint64_t cb) {   // ca A + cb B
    ENGINE_CHECK(A.row_exp == B.row_exp && A.ell == B.ell);
    const std::vector<uint64_t> m = RowMods(A);
    RingMat R = A;
    const uint32_t n = A.n();
    for (uint32_t i = 0; i < n; ++i)
        for (uint32_t j = 0; j < n; ++j) {
            const size_t k = static_cast<size_t>(i) * n + j;
            R.a[k] = (MulMod(A.a[k] % m[i], ca % m[i], m[i]) + MulMod(B.a[k] % m[i], cb % m[i], m[i])) % m[i];
        }
    return R;
}

RingMat AddScalarRM(const RingMat& A, uint64_t c) {
    return Lin(A, 1, hecke::ordinary::Identity(A.ell, A.row_exp), c);
}

// E(T) by Horner (coefficients in [0, ell) lifted).
RingMat EvalPolyRM(const Poly64& E, const RingMat& T) {
    RingMat R = Lin(T, 0, T, 0);
    for (int64_t k = E.degree(); k >= 0; --k) R = AddScalarRM(hecke::ordinary::Mul(R, T), E.coeff(static_cast<uint32_t>(k)));
    return R;
}

// E with E = 1 mod (x - a)^mult, E = 0 mod chi / (x - a)^mult; mult >= 1 checked.
Poly64 IdempotentPoly(const Poly64& chi, uint64_t a, uint64_t ell, uint32_t& mult) {
    const Poly64 lin(ell, {(ell - a % ell) % ell, 1});
    Poly64 g = chi, h = Poly64::one(ell);
    mult = 0;
    for (;;) {
        Poly64 qq(ell), rr(ell);
        Poly64::divrem(g, lin, qq, rr);
        if (!rr.is_zero()) break;
        g = qq;
        h = h * lin;
        ++mult;
    }
    ENGINE_CHECK_MSG(mult >= 1, "HeckeLatticeModule: the system's a_p is not an eigenvalue of T_p mod ell");
    if (g.degree() == 0) return Poly64::one(ell);
    Poly64 u(ell), v(ell);
    const Poly64 d = Poly64::extgcd(h, g, u, v);   // u h + v g = 1
    ENGINE_CHECK(d == Poly64::one(ell));
    return Poly64::mod(v * g, chi);
}

Poly64 CharpolyModEll(uint64_t ell, const RingMat& A) {
    RingMat Abar;
    Abar.ell = ell;
    Abar.row_exp.assign(A.n(), 1);
    Abar.a.resize(A.a.size());
    for (size_t k = 0; k < A.a.size(); ++k) Abar.a[k] = A.a[k] % ell;
    const hida::Poly chi = hida::CharpolyFree(Abar);
    return Poly64(ell, std::vector<uint64_t>(chi.begin(), chi.end()));
}

// N -> (Z/ell^K)^r, g_i -> ell^{K - a_i} g_i: an injective module map.
void EmbedColumn(const RingMat& A, uint32_t K, const std::vector<uint64_t>& col, engine::DenseBuf<uint64_t>& Y, uint32_t c) {
    for (uint32_t i = 0; i < A.n(); ++i) Y.at(i, c) = col[i] * PowU(A.ell, K - A.row_exp[i]);
}

// The submodule generated by the columns `gens` of an operator G on N (given as RingMat columns), as a FreePart
// with the operators `ops` restricted.  The decomposition is of the embedded columns; a restricted column is the
// cyclic_coordinates of the embedded image.
struct Sub {
    engine::elim::CyclicDecomposition<uint64_t> dec;
    std::vector<uint32_t> exps;
};

Sub Decompose(const engine::ModCtx<uint64_t>& ctx, const RingMat& G, uint32_t K) {
    const uint32_t r = G.n();
    engine::DenseBuf<uint64_t> E(r, r), Rl(r, 0);
    for (uint32_t j = 0; j < r; ++j) {
        std::vector<uint64_t> col(r);
        for (uint32_t i = 0; i < r; ++i) col[i] = G.at(i, j);
        EmbedColumn(G, K, col, E, j);
    }
    Sub s;
    s.dec = engine::elim::cyclic_decomposition<uint64_t>(ctx, engine::cview(E), engine::cview(Rl));
    s.exps = s.dec.exponents;
    return s;
}

// X restricted to the decomposed submodule (which must be X-stable): column j = coordinates of X b_j.
FreeMat Restrict(const engine::ModCtx<uint64_t>& ctx, const Sub& s, const RingMat& X, uint32_t K) {
    const uint32_t r = X.n();
    const uint32_t m = s.dec.rows();
    const uint64_t q = PowU(X.ell, K);
    // un-embed b_j, apply X, re-embed
    engine::DenseBuf<uint64_t> Y(r, m);
    for (uint32_t j = 0; j < m; ++j) {
        std::vector<uint64_t> x(r);
        for (uint32_t i = 0; i < r; ++i) {
            const uint64_t sc = PowU(X.ell, K - X.row_exp[i]);
            const uint64_t y = s.dec.basis.at(i, j) % q;
            ENGINE_CHECK_MSG(y % sc == 0, "HeckeLatticeModule: a basis vector is not in the embedded module");
            x[i] = (y / sc) % PowU(X.ell, X.row_exp[i]);
        }
        std::vector<uint64_t> xx(r, 0);
        for (uint32_t i = 0; i < r; ++i) {
            const uint64_t mi = PowU(X.ell, X.row_exp[i]);
            u128 acc = 0;
            for (uint32_t k = 0; k < r; ++k) acc += static_cast<u128>(X.at(i, k) % mi) * (x[k] % mi);
            xx[i] = static_cast<uint64_t>(acc % mi);
        }
        EmbedColumn(X, K, xx, Y, j);
    }
    const std::vector<std::vector<uint64_t>> co = engine::elim::cyclic_coordinates<uint64_t>(ctx, s.dec, engine::cview(Y));
    FreeMat R;
    R.ell = X.ell;
    R.K = K;
    R.r = m;
    R.a.assign(static_cast<size_t>(m) * m, 0);
    for (uint32_t j = 0; j < m; ++j) {
        ENGINE_CHECK(co[j].size() == m);
        for (uint32_t i = 0; i < m; ++i) R.a[static_cast<size_t>(i) * m + j] = co[j][i] % q;
    }
    // re-verify: sum_i R_ij b_i == X b_j (embedded), entrywise mod ell^K
    for (uint32_t j = 0; j < m; ++j)
        for (uint32_t row = 0; row < r; ++row) {
            u128 acc = 0;
            for (uint32_t i = 0; i < m; ++i) acc += static_cast<u128>(R.a[static_cast<size_t>(i) * m + j]) * (s.dec.basis.at(row, i) % q);
            ENGINE_CHECK_MSG(static_cast<uint64_t>(acc % q) == Y.at(row, j) % q,
                             "HeckeLatticeModule: a restricted column does not re-verify (the submodule is not stable)");
        }
    return R;
}

FreePart MakePart(const engine::ModCtx<uint64_t>& ctx, const RingMat& G, const std::vector<RingMat>& T, const RingMat& iota, uint32_t K) {
    const Sub s = Decompose(ctx, G, K);
    FreePart P;
    P.rank = s.dec.rows();
    P.exps = s.exps;
    for (const RingMat& X : T) P.T.push_back(Restrict(ctx, s, X, K));
    P.iota = Restrict(ctx, s, iota, K);
    return P;
}

