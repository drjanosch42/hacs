// ---------------------------------------------------------------------------
// Outcomes and the (pipeline-free half of the) `sturm.unavailable` setting.
// ---------------------------------------------------------------------------

// [X] Sec. 1.3.1 R3.3 item 1: outcome in {found(B'), none_at_cap, in_progress}.
enum class SturmOutcome : uint32_t {
    InProgress = 0,  // constructed but not yet run
    Found      = 1,  // B' exists at or below the cap
    NoneAtCap  = 2   // the closure was still proper when the cap was passed
};
const char* ToString(SturmOutcome outcome);

// [X] Sec. 1.5 `sturm.unavailable`, OQ15 / slot-1 confirmation 6.  The DEFAULT
// is `NonFinal`; `Heuristic` is selectable.  WP-3 owns only the pipeline-free
// half of the semantics -- the map (outcome, mode) -> (final, reason) below.
// The heuristic SWEEP itself (the primes <= cap plus ell tested for membership
// in A_S on the pipeline's own A^{(1)}(T_q)) is E1b's `SturmCertificate`.
enum class SturmUnavailableMode : uint32_t { NonFinal = 0, Heuristic = 1 };
const char* ToString(SturmUnavailableMode mode);

// [X] Sec. 1.3.1 R3.2: `final` is tri-state -- and since slot-4 WP-1 (E2a)
// it is ONE type, hecke_ext::Final, owned by the record layer
// (HeckeExtFinal.h).  These two names survive as ALIASES so that every
// pre-E2a call site (`SturmFinal::Heuristic`, `SturmFinality f; f.value`,
// `ToString(SturmFinal::True)`) compiles and MEANS THE SAME THING; the JSON
// strings are unchanged.
using SturmFinal = Final;

// The Sturm bound's CONTRIBUTION to an ideal's `final`, not the ideal's own
// verdict (that is E2's `HeckeExtRecord::is_final`, which also needs locality
// and the generation certificate).  `True` here means only "the Sturm bound
// does not obstruct finality".
using SturmFinality = Finality;

// ---------------------------------------------------------------------------
// The resumable state ([X] Sec. 1.3.1 R3.3 item 1, verbatim member list).
// ---------------------------------------------------------------------------

struct SturmState {
    uint32_t k        = 0;   // the weight, k = n + 2
    uint32_t ell      = 0;
    uint32_t dim_M_k  = 0;

    // The budget in force and its history.  R3.1 item 4: one entry per
    // run()/resume(), the LAST one is the setting in force.
    uint32_t              cap = 0;
    std::vector<uint32_t> budget_history;

    // Progress: the largest prime processed and the ascending list of all of
    // them.  `primes_done` and `tq_cache` are index-aligned.
    uint32_t              B_reached = 0;
    std::vector<uint32_t> primes_done;

    // The series length L in force; L >= q * dim_M_k for every processed q.
    uint32_t precision = 0;

    // The echelon Miller basis to precision L: dim_M_k rows of L coefficients,
    // with a_m(e_i) = delta_{i,m} for m < dim_M_k.  A deterministic function of
    // (k, ell, L), and stable in L: growing L only appends coefficients.
    std::vector<std::vector<uint32_t>> miller;

    // The T_q cache, one dim_M_k x dim_M_k Miller-basis matrix per entry of
    // `primes_done`.
    std::vector<MatrixT<uint32_t>> tq_cache;

    // The closure basis: the RREF coordinate matrix (closure_dim rows of
    // dim_M_k^2 columns, row-major vec) of the F_ell-algebra generated by
    // {T_q : q <= B_reached}, and its dimension.
    std::vector<std::vector<uint32_t>> closure_basis;
    uint32_t                           closure_dim = 0;

    SturmOutcome outcome = SturmOutcome::InProgress;
    uint32_t     B_prime = 0;  // meaningful iff outcome == Found

    // Entrywise equality.  `ignore_budget_history` is what the resume-invariance
    // property needs: R3.1 item 3 demands the same state entrywise, while
    // R3.1 item 4 demands that every run/resume append its budget, so the two
    // can only be reconciled by excluding the history from the comparison
    // (see docs/implementation/slot1/WP-3_report.md, open point for WP-7).
    bool equals(const SturmState& other, bool ignore_budget_history) const;

    // Fixed key order, no pointers, no hash containers (R3.1 item 1).
    std::string to_json() const;
};

// ---------------------------------------------------------------------------
// The certificate ([X] Sec. 1.3 `SturmBoundCertificate`).
// ---------------------------------------------------------------------------

struct SturmBoundCertificate {
    uint32_t k           = 0;
    uint32_t ell         = 0;
    uint32_t dim_M_k     = 0;
    uint32_t cap         = 0;
    bool     has_B_prime = false;
    uint32_t B_prime     = 0;
    uint32_t closure_dim = 0;

    // The primes actually processed, ascending, index-aligned with `T_q`:
    // every prime <= B' when it exists, every prime <= cap otherwise.
    std::vector<uint32_t> primes;
    std::vector<MatrixT<uint32_t>> T_q;

    // The resumable state (R3.4: the "resumable" object lives in this JSON).
    SturmState state;

    // Where the state goes when its JSON exceeds 64 KiB (R3.1 item 6).  Empty
    // (the default) means "inline it anyway and flag it": only the RECORD layer
    // (E2) knows the record stem, so only it can name the sidecar.
    std::string state_sidecar_stem;

    // 0 on success, else the index of the first failing clause (see the table
    // in the .cpp).  Deterministic, and it re-derives -- it never re-runs a
    // search and never reads `closure_dim` as an input to its own conclusion.
    uint32_t    verify() const;
    static const char* verify_message(uint32_t code);

    std::string to_json() const;
    // The R3.1 "resumable" object on its own.
    std::string resumable_json() const;
};

// ---------------------------------------------------------------------------
// The computation.
// ---------------------------------------------------------------------------

class SturmBound {
public:
    // B(k) = floor(k/12) + 1 ([E] `cl:sturm`).
    static uint32_t weight_bound(uint32_t k);
    // The default cap, 12*B(k) ([E] `def:bprime`, [X] Sec. 1.5, confirmation 6).
    static uint32_t default_cap(uint32_t k);
    // dim M_k for level 1: 0 for odd k and for k == 2; floor(k/12) + 1 unless
    // k == 2 (mod 12), where it is floor(k/12).
    static uint32_t dimension_M_k(uint32_t k);

    // `cap == 0` selects default_cap(k).  Preconditions: k >= 4 and even (so
    // dim M_k >= 1), ell >= 2, cap >= 2.
    SturmBound(uint32_t k, uint32_t ell, uint32_t cap = 0);

    // Runs the ascending prime sweep from scratch under the constructed cap.
    // May be called exactly once; use resume() afterwards.
    SturmOutcome run();

    // Continues from state(), never from scratch (R3.1 item 2).
    //  * a cap below the reached B is REFUSED with a named error;
    //  * on a `Found` state it is a strict no-op -- neither the cap nor the
    //    budget history moves, so the certificate is literally unchanged;
    //  * otherwise the next prime after B_reached is processed, with the
    //    precision grown lazily, until the closure fills or the cap is passed.
    SturmOutcome resume(uint32_t new_cap);

    const SturmState& state() const { return st_; }
    SturmOutcome outcome()    const { return st_.outcome; }
    bool     has_B_prime()    const { return st_.outcome == SturmOutcome::Found; }
    uint32_t B_prime()        const { return has_B_prime() ? st_.B_prime : 0u; }
    uint32_t closure_dim()    const { return st_.closure_dim; }
    uint32_t dim_M_k()        const { return st_.dim_M_k; }
    uint32_t cap()            const { return st_.cap; }
    uint32_t weight()         const { return st_.k; }
    uint32_t ell()            const { return st_.ell; }
    const std::vector<uint32_t>& primes_done() const { return st_.primes_done; }

    // The Miller-basis matrix of T_q; q must be one of primes_done().
    const MatrixT<uint32_t>& T(uint32_t q) const;

    SturmBoundCertificate certificate() const;

private:
    void grow_precision_(uint32_t q);
    void recompute_closure_();
    void advance_();

    SturmState st_;

    // (slot-22 PERF1, P9) A working cache, NOT part of the state: it is not
    // serialised, compared or certified.  closure_span_ is the canonical RREF
    // span of the algebra generated by the first closure_gens_ matrices of
    // st_.tq_cache, extended in place when a generator is added instead of
    // being re-closed from the identity at every prime.  The RREF of a span is
    // unique, so st_.closure_basis is unchanged.
    std::vector<hecke::RrefRowSpan> closure_span_;   // empty, or exactly one
    size_t closure_gens_ = 0;
};

// (outcome, mode) -> the Sturm bound's contribution to `final` ([X] Sec. 1.3.1
// R3.2 / R3.3 item 1's record column).
SturmFinality sturm_finality(const SturmBound& bound, SturmUnavailableMode mode);

// ---------------------------------------------------------------------------
// The q-expansion primitives, exposed so the validation can pin them against
// sigma_3 / sigma_5 / tau and so E1b can reuse them.  Every vector has `L`
// entries, index m holding a_m mod ell.
// ---------------------------------------------------------------------------

// weight must be 4 or 6: E_4 = 1 + 240 sum sigma_3(m) q^m,
// E_6 = 1 - 504 sum sigma_5(m) q^m.
std::vector<uint32_t> EisensteinSeries(uint32_t weight, uint32_t L, uint32_t ell);

// Delta = q prod_{n>=1} (1 - q^n)^24, formed through the pentagonal-number
// product and 24th power -- integral, so no division by 1728 is needed.
std::vector<uint32_t> DeltaSeries(uint32_t L, uint32_t ell);

// The echelon Miller basis of M_k(F_ell) to precision L: the monomials
// E_4^a E_6^b Delta^j, j = 0 .. dim M_k - 1, back-substituted so that
// a_m(e_i) = delta_{i,m} for m < dim M_k.  The monomial coefficient matrix is
// unitriangular over Z, so this needs no pivoting and works for every ell.
std::vector<std::vector<uint32_t>> EchelonMillerBasis(uint32_t k, uint32_t ell, uint32_t L);

// The matrix of T_q on M_k(F_ell) in the echelon Miller basis, from
// a_m(T_q f) = a_{qm}(f) + q^{k-1} a_{m/q}(f).  Requires
// miller[0].size() >= q * (dim M_k - 1) + 1.
MatrixT<uint32_t> HeckeOperatorOnMk(uint32_t q, uint32_t k, uint32_t ell,
                         const std::vector<std::vector<uint32_t>>& miller);

