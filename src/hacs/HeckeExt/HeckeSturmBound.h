// ===========================================================================
// hecke-extensions phase E1s -- the computed Sturm bound B'(k, ell).
//
// WHAT THIS COMPUTES.  [E] = docs/latex/hecke_extensions.tex v1.3.2,
// Definition `def:bprime` and Claim `cl:bprime`:
//
//   For B >= 2 let W_B = Z[T_q : q <= B prime] inside T_Z(M_k).  B'(k, ell) is
//   the LEAST B <= B_max such that the F_ell-ALGEBRA generated in
//   End M_k(F_ell) by the reductions T_q mod ell, q <= B prime, computed on the
//   Miller basis, has dimension dim M_k.  The cap B_max (default 12*B(k) with
//   B(k) = floor(k/12) + 1, [X] Sec. 1.5 `sturm.cap`) and the outcome are both
//   recorded.
//
// B' exists iff ell does not divide [T^sat : T_Z(M_k)] ([E] `cl:bprime`), and
// when it exists every T_q is a Z-polynomial in the T_{q'}, q' <= B' prime,
// plus ell times an element of T_Z(M_k) -- which is what makes the Sturm sweep
// (certificate (c), [E] `cert:sturm`, on the range of [E] `cl:sturmmodl`) a
// proof rather than a heuristic.  The weight is k = n + 2 and the pins below
// are stated in k, not in n.
//
// It is DELIBERATELY PIPELINE-FREE ([X] Sec. 1.1): pure modular-form
// arithmetic on the Miller basis over F_ell.  It constructs no cohomology, no
// coset table and no Hecke operator on H^q; the only thing it shares with the
// rest of the extension layer is `hecke::algebra_closure` in Hecke/SubspaceOps.
// The `check_heckeext_includes.sh` guard asserts exactly that.
//
// NO BIGNUM ([X] Sec. 0.3, Sec. 2.2 Stage 4(c)).  Every q-expansion
// coefficient is reduced mod ell as it is formed: E_4 = 1 + 240 sum sigma_3,
// E_6 = 1 - 504 sum sigma_5, and Delta = q prod (1 - q^n)^24 through the
// pentagonal-number product (so Delta needs no division by 1728 and is correct
// at ell = 2 and ell = 3 as well).
//
// RESUMABLE ([X] Sec. 1.3.1 R3, instance 1; R3.4 is this unit's mandate).
// `SturmState` holds the reached prime B_reached, the precision, the echelon
// Miller basis, the T_q cache and the closure basis; `resume(new_cap)`
// continues from it and never restarts; a cap below B_reached is refused with
// a named error.  Resume-invariance holds because the budget decides only
// WHERE the ascending prime sweep stops: the algebra generated by
// {T_q : q <= B} is a function of (k, ell, B) alone, T_q does not depend on the
// precision beyond L >= q*dim M_k, and the closure basis is the (unique) RREF
// of that algebra.
//
// See Hecke/README.md and docs/implementation/slot1/WP-3_report.md.
// ===========================================================================

