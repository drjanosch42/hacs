// SameMaximalIdeal -- [XA M5] / [X] Sec. 2.2 Stage 2.
// ===========================================================================

EvaluationMatch SameMaximalIdeal(const LocalAlgebra& B,
                                 const std::vector<ExtMatrix>& t_other) {
    if (!B.ok) throw std::invalid_argument("SameMaximalIdeal: B did not certify local");
    if (t_other.size() != B.primes.size()) {
        throw std::invalid_argument("SameMaximalIdeal: operator count mismatch");
    }
    if (t_other.empty()) throw std::invalid_argument("SameMaximalIdeal: empty operator list");
    const uint32_t Dp = t_other[0].rows;
    for (const ExtMatrix& M : t_other) {
        if (M.rows != M.cols || M.rows != Dp) {
            throw std::invalid_argument("SameMaximalIdeal: non-square or ragged operator");
        }
        if (M.p != B.ell) throw std::invalid_argument("SameMaximalIdeal: modulus mismatch");
    }

    EvaluationMatch out;
    // w' = sum_p c_p t_p|_{B'}, with B's OWN witness coefficients.
    ExtMatrix Wp(Dp, Dp, B.ell);
    for (const auto& term : B.locality.witness) {
        const auto it = std::find(B.primes.begin(), B.primes.end(), term.first);
        if (it == B.primes.end()) {
            throw std::invalid_argument("SameMaximalIdeal: the witness names a prime outside S");
        }
        const size_t idx = static_cast<size_t>(it - B.primes.begin());
        Wp = Wp + t_other[idx] * term.second;
    }

    // N' is taken for the TESTED block: nilpotency must be bounded on B'.
    out.N_other = TeichmuellerExponentHere(B.ell, B.f, Dp);

    if (!hecke::IsNilpotent(hecke::EvalPolyAtMatrix(B.witness_poly, Wp), Dp)) {
        out.failure = kEvalWitnessNotNilpotent;
        return out;
    }
    const ExtMatrix w_hat_p = hecke::FrobeniusPower(Wp, B.ell, out.N_other);
    for (size_t j = 0; j < B.primes.size(); ++j) {
        const ExtMatrix n_p = t_other[j] - hecke::EvalPolyAtMatrix(B.character[j], w_hat_p);
        if (!hecke::IsNilpotent(n_p, Dp)) {
            out.failure = kEvalCharacterNotNilpotent;
            out.failing_prime = B.primes[j];
            return out;
        }
    }
    out.same_ideal = true;
    return out;
}

