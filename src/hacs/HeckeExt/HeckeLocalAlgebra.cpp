LocalAlgebra ComputeLocalAlgebra(const hecke::PrimaryBlock& block,
                                 const std::vector<std::pair<uint64_t, ExtMatrix>>& ops_in,
                                 uint32_t ell,
                                 const LocalAlgebraOptions& opts) {
    if (ell < 2) throw std::invalid_argument("ComputeLocalAlgebra: ell must be a prime >= 2");
    if (ops_in.empty()) throw std::invalid_argument("ComputeLocalAlgebra: empty operator family");
    for (const auto& op : ops_in) {
        if (op.second.rows != op.second.cols) {
            throw std::invalid_argument("ComputeLocalAlgebra: non-square operator");
        }
        if (op.second.p != ell) {
            throw std::invalid_argument("ComputeLocalAlgebra: operator modulus != ell");
        }
    }

    // The fixed operator order of [X] Sec. 2.2 Stage 2: ascending prime.
    std::vector<std::pair<uint64_t, ExtMatrix>> ops = ops_in;
    std::stable_sort(ops.begin(), ops.end(),
                     [](const std::pair<uint64_t, ExtMatrix>& a,
                        const std::pair<uint64_t, ExtMatrix>& b) { return a.first < b.first; });
    for (size_t i = 1; i < ops.size(); ++i) {
        if (ops[i].first == ops[i - 1].first) {
            throw std::invalid_argument("ComputeLocalAlgebra: duplicate prime in the family");
        }
    }

    LocalAlgebra out;
    out.ell = ell;
    out.D = block.dim;

    // --- Step 0: the locality certificate.  w_hat and the P_p are CONSUMED
    // from it, never re-derived differently (WP-4 scope).  force_matrix_path
    // is set because the k = 1 analytic shortcut deliberately never forms
    // w_hat ([X] Sec. 3.1, [XA m17]) and Stage 3 needs the matrix. ---------
    if (opts.precomputed_locality != nullptr) {
        // (slot 4, WP-2 / E2b) The fast path: the verdict the decomposition's
        // own refinement loop already proved, adopted rather than re-searched.
        // Every check below still runs.
        out.locality = *opts.precomputed_locality;
    } else {
        hecke::LocalityOptions lopts;
        lopts.max_attempts = opts.max_attempts;
        lopts.force_matrix_path = true;
        out.locality = hecke::CertifyLocality(block, ops, ell, lopts);
    }
    if (!out.locality.local) return out;   // reported, not thrown

    out.f = out.locality.residue_degree;
    out.N = out.locality.w_hat_exponent;
    out.witness_poly = out.locality.witness_poly;
    out.w_hat = out.locality.w_hat;
    ENGINE_CHECK_MSG(out.f >= 1, "ComputeLocalAlgebra: residue degree 0 on a local block");
    ENGINE_CHECK_MSG(out.N == TeichmuellerExponentHere(ell, out.f, out.D),
                     "ComputeLocalAlgebra: the verdict's Teichmueller exponent is not the "
                     "least multiple of f with ell^N >= D");
    ENGINE_CHECK_MSG(out.w_hat.rows == out.D && out.w_hat.cols == out.D,
                     "ComputeLocalAlgebra: CertifyLocality returned no w_hat matrix");
    // pi_w(w_hat) = pi_w(w)^{ell^N} = 0 is an IDENTITY (Frobenius is a ring
    // endomorphism), so its failure is a bug, not a finding ([E] cl:resfield).
    ENGINE_CHECK_MSG(hecke::EvalPolyAtMatrix(out.witness_poly, out.w_hat).is_zero(),
                     "ComputeLocalAlgebra: pi_w(w_hat) != 0");

    const uint32_t D = out.D;

    // --- The restrictions t_p|_V.  Solvability of B X = A_p B IS the
    // invariance certificate ([X] Sec. 1.2: t_p|_V is stored so that every
    // certificate re-verifies from emitted data). -------------------------
    for (const auto& op : ops) {
        out.primes.push_back(op.first);
        out.t.push_back(hecke::SolveColumnsExact(block.basis_columns,
                                                 op.second * block.basis_columns,
                                                 "ComputeLocalAlgebra(restriction)"));
        const auto it = out.locality.character.find(op.first);
        ENGINE_CHECK_MSG(it != out.locality.character.end(),
                         "ComputeLocalAlgebra: the verdict carries no character for a family prime");
        out.character.push_back(it->second);
    }

    // --- Step 1: A_S ([E] alg:stage3(1)). --------------------------------
    out.coords = hecke::algebra_closure(out.t, D, ell, out.dim_A);
    out.basis.reserve(out.dim_A);
    for (uint32_t i = 0; i < out.dim_A; ++i) {
        out.basis.push_back(MatrixOfVec(out.coords.data[i], D, D, ell));
    }

    // --- Step 2: the generators n_p and the ideal m_S ([E] alg:stage3(2)).
    // NO separate pi_w(w) generator: pi_w(w) lies in (n_w) already, and the
    // witness direction n_w = w - w_hat = sum_p c_p n_p is automatic. ------
    for (size_t j = 0; j < out.primes.size(); ++j) {
        ExtMatrix n_p = out.t[j] - hecke::EvalPolyAtMatrix(out.character[j], out.w_hat);
        ENGINE_CHECK_MSG(hecke::IsNilpotent(n_p, D),
                         "ComputeLocalAlgebra: t_p - P_p(w_hat) is not nilpotent on a block "
                         "CertifyLocality accepted");
        out.n.push_back(std::move(n_p));
    }

    {
        const RrefRowSpan m_span = SpanOfProducts(out.basis, out.n, D, ell);
        out.dim_m_S = m_span.dim();
        // A_S / m_S = F_{ell^f}, so the codimension of m_S in A_S is exactly f.
        ENGINE_CHECK_MSG(out.dim_A >= out.dim_m_S && out.dim_A - out.dim_m_S == out.f,
                         "ComputeLocalAlgebra: dim A_S - dim m_S != f "
                         "(A_S/m_S is not the residue field)");
        if (out.dim_m_S != 0) {
            out.m_powers.push_back(UnvecRows(m_span, D, ell));
            out.m_powers_dim.push_back(out.dim_m_S);
        }
    }

    // m_S^{i+1} = m_S^i * m_S = sum_p m_S^i n_p, since m_S = (n_p)_p.  Only
    // the nonzero powers are stored; the loop terminates because the
    // filtration is strictly decreasing until it reaches 0 (m_S is nilpotent,
    // every n_p being nilpotent and the algebra commutative).
    while (!out.m_powers.empty()) {
        const RrefRowSpan next = SpanOfProducts(out.m_powers.back(), out.n, D, ell);
        if (next.dim() == 0) break;
        ENGINE_CHECK_MSG(next.dim() < out.m_powers_dim.back(),
                         "ComputeLocalAlgebra: the m_S-adic filtration did not decrease "
                         "(m_S is not nilpotent)");
        out.m_powers.push_back(UnvecRows(next, D, ell));
        out.m_powers_dim.push_back(next.dim());
    }
    // m_powers holds m_S^1 .. m_S^{nu-1} (all nonzero); m_S^nu = 0.
    out.nu = static_cast<uint32_t>(out.m_powers.size()) + 1u;

    // hilbert[i] = dim(m_S^i / m_S^{i+1}) / f, with m_S^0 = A_S.
    out.hilbert.reserve(out.nu);
    for (uint32_t i = 0; i < out.nu; ++i) {
        const uint32_t dim_i = (i == 0) ? out.dim_A : out.m_powers_dim[i - 1];
        const uint32_t dim_next = (i < out.m_powers_dim.size()) ? out.m_powers_dim[i] : 0u;
        ENGINE_CHECK_MSG(dim_i >= dim_next && ((dim_i - dim_next) % out.f) == 0,
                         "ComputeLocalAlgebra: a Hilbert-function layer is not a multiple of f");
        out.hilbert.push_back((dim_i - dim_next) / out.f);
    }

    // --- soc A_S = Ann_{A_S}(m_S) = { a in A_S : a n_p = 0 for all p }.
    // In the coordinates of `basis` this is the kernel of the (k D^2) x dim_A
    // matrix whose column j stacks vec(b_j n_p) over p. -------------------
    {
        const uint32_t k = static_cast<uint32_t>(out.n.size());
        ExtMatrix sys(k * D * D, out.dim_A, ell);
        for (uint32_t j = 0; j < out.dim_A; ++j) {
            for (uint32_t a = 0; a < k; ++a) {
                const std::vector<uint32_t> v = VecOfMatrix(out.basis[j] * out.n[a]);
                for (uint32_t r = 0; r < D * D; ++r) sys.data[a * D * D + r][j] = v[r];
            }
        }
        const ExtMatrix ker = hecke::KernelAsMatrix(sys);   // dim_A x dim_soc
        out.dim_socle = ker.cols;
        for (uint32_t c = 0; c < ker.cols; ++c) {
            ExtMatrix acc(D, D, ell);
            for (uint32_t j = 0; j < out.dim_A; ++j) {
                if (ker.data[j][c] == 0) continue;
                acc = acc + out.basis[j] * ker.data[j][c];
            }
            out.socle.push_back(std::move(acc));
        }
        out.gorenstein = (out.dim_socle == out.f);
    }

    // --- Step 3: the tangent test OVER K ([E] alg:stage3(3)).  The K-span of
    // a set of n_p-bar in m_S/m_S^2 is the F_ell-span of w_hat^i n_p,
    // 0 <= i < f, worked out modulo m_S^2. --------------------------------
    {
        RrefRowSpan m2(D * D, ell);
        if (out.m_powers.size() >= 2) {
            for (const ExtMatrix& b : out.m_powers[1]) m2.insert(VecOfMatrix(b));
        }
        const uint32_t dim_m2 = m2.dim();
        ENGINE_CHECK_MSG(out.dim_m_S >= dim_m2,
                         "ComputeLocalAlgebra: m_S^2 is not contained in m_S");
        const uint32_t dim_tangent = out.dim_m_S - dim_m2;
        ENGINE_CHECK_MSG((dim_tangent % out.f) == 0,
                         "ComputeLocalAlgebra: dim(m_S/m_S^2) is not a multiple of f");
        out.embdim = dim_tangent / out.f;

        // active[p]: n_p-bar != 0, i.e. n_p is not already in m_S^2.
        out.active.assign(out.n.size(), 0u);
        for (size_t j = 0; j < out.n.size(); ++j) {
            out.active[j] = m2.contains(VecOfMatrix(out.n[j])) ? 0u : 1u;
        }

        // The minimal K-spanning subset, greedy in ASCENDING p (deterministic).
        // The K-span of a set of n_p-bar is the F_ell-span of w_hat^i n_p,
        // 0 <= i < f, which is why the inner loop multiplies by w_hat.
        RrefRowSpan chosen(D * D, ell);
        for (const std::vector<uint32_t>& row : m2.rows()) chosen.insert(row);
        for (size_t j = 0; j < out.n.size(); ++j) {
            if (chosen.dim() == out.dim_m_S) break;
            if (chosen.contains(VecOfMatrix(out.n[j]))) continue;
            out.minimal_active.push_back(out.primes[j]);
            ExtMatrix pw(D, ell);   // identity
            for (uint32_t i = 0; i < out.f; ++i) {
                chosen.insert(VecOfMatrix(pw * out.n[j]));
                if (i + 1 < out.f) pw = pw * out.w_hat;
            }
        }
        // The n_p generate m_S, so their K-span must be all of m_S/m_S^2.
        ENGINE_CHECK_MSG(chosen.dim() == out.dim_m_S,
                         "ComputeLocalAlgebra: the n_p do not K-span m_S/m_S^2");
    }

    // --- Stage 4(a): certificate (a) ([E] cert:cyclic). -------------------
    {
        CyclicityCertificate& c = out.cyclicity;
        c.ell = ell;
        c.D = D;
        c.f = out.f;
        c.primes = out.primes;
        c.t = out.t;
        c.character = out.character;
        c.witness_poly = out.witness_poly;
        c.w_hat = out.w_hat;
        c.a_basis = out.basis;
        c.m_basis = out.m_powers.empty() ? std::vector<ExtMatrix>() : out.m_powers[0];

        const RrefRowSpan mV = RowSpanOfImages(c.m_basis, D, ell);
        c.dim_quotient = D - mV.dim();
        c.cyclic = (c.dim_quotient == out.f);
        c.generator_index = 0;
        if (c.cyclic) {
            uint32_t least = D;
            for (uint32_t j = 0; j < D; ++j) {
                std::vector<uint32_t> e(D, 0u);
                e[j] = 1u;
                if (!mV.contains(e)) { least = j; break; }
            }
            ENGINE_CHECK_MSG(least < D,
                             "ComputeLocalAlgebra: m_S V = V although dim V/m_S V = f > 0");
            c.generator_index = least;
        }
        ENGINE_CHECK_MSG((c.dim_quotient % out.f) == 0,
                         "ComputeLocalAlgebra: dim V/m_S V is not a multiple of f");
        out.min_generators = c.dim_quotient / out.f;
    }

    out.ok = true;
    return out;
}

