std::string LocalAlgebra::to_json() const {
    std::ostringstream os;
    os << "{\"kind\": \"local_algebra\""
       << ", \"local\": " << (ok ? "true" : "false");
    if (!ok) {
        os << ", \"locality_failure\": " << locality.failure
           << ", \"note\": \"" << locality.note << "\"}";
        return os.str();
    }
    os << ", \"ell\": " << ell
       << ", \"D\": " << D
       << ", \"f\": " << f
       << ", \"N\": " << N
       << ", \"primes\": [";
    for (size_t i = 0; i < primes.size(); ++i) { if (i) os << ", "; os << primes[i]; }
    os << "], \"pi_w\": \"" << witness_poly.to_string() << "\""
       << ", \"dim_A_S\": " << dim_A
       << ", \"dim_m_S\": " << dim_m_S
       << ", \"m_powers_dim\": " << JsonDims(m_powers_dim)
       << ", \"nu\": " << nu
       << ", \"hilbert\": " << JsonDims(hilbert)
       << ", \"dim_soc_A_S\": " << dim_socle
       << ", \"gorenstein\": " << (gorenstein ? "true" : "false")
       << ", \"embdim\": " << embdim
       << ", \"min_generators\": " << min_generators
       << ", \"active\": [";
    for (size_t i = 0; i < active.size(); ++i) {
        if (i) os << ", ";
        os << (active[i] ? "true" : "false");
    }
    os << "], \"minimal_active\": [";
    for (size_t i = 0; i < minimal_active.size(); ++i) { if (i) os << ", "; os << minimal_active[i]; }
    os << "], \"certificate_a\": " << cyclicity.to_json() << '}';
    return os.str();
}

