// Least multiple of f with ell^N >= D.  The same recipe CertifyLocality uses
// (HeckeModuleDecomposition.cpp, TeichmuellerExponent) -- [E] `cl:resfield`.
// It is repeated here rather than shared because that copy is file-local to
// the Hecke/ TU and the one-way include rule forbids Hecke/ from reaching into
// HeckeExt/; the two are asserted equal on every computed block (the verdict's
// w_hat_exponent).
uint32_t TeichmuellerExponentHere(uint32_t ell, uint32_t f, uint32_t D) {
    uint32_t t = 0;
    uint64_t acc = 1;
    while (acc < static_cast<uint64_t>(D)) { acc *= static_cast<uint64_t>(ell); ++t; }
    if (f == 0) return t;
    return ((t + f - 1u) / f) * f;
}

// The rows of an RrefRowSpan over F_ell^{D^2} as D x D matrices.
std::vector<ExtMatrix> UnvecRows(const RrefRowSpan& span, uint32_t D, uint32_t ell) {
    std::vector<ExtMatrix> out;
    out.reserve(span.dim());
    for (const std::vector<uint32_t>& row : span.rows()) {
        out.push_back(MatrixOfVec(row, D, D, ell));
    }
    return out;
}

// The F_ell-span of { b * g : b in `left`, g in `right` } inside F_ell^{D^2},
// as a canonical RREF.  This is how an ideal of A_S is formed: `left` is a
// basis of A_S (or of m_S^i) and `right` the generators n_p.
RrefRowSpan SpanOfProducts(const std::vector<ExtMatrix>& left,
                           const std::vector<ExtMatrix>& right,
                           uint32_t D, uint32_t ell) {
    RrefRowSpan span(D * D, ell);
    for (const ExtMatrix& b : left) {
        for (const ExtMatrix& g : right) {
            span.insert(VecOfMatrix(b * g));
        }
    }
    return span;
}

// The column span of [ A_1 | ... | A_r ] as a subspace of F_ell^D, i.e.
// sum_a im(A_a) -- used for m_S V.  Returned as its rank plus an RREF of the
// TRANSPOSED system, so membership of a standard basis vector e_j is one
// reduction.
RrefRowSpan RowSpanOfImages(const std::vector<ExtMatrix>& mats, uint32_t D, uint32_t ell) {
    // im(A) = row span of A^T; collect every column of every A_a as a row.
    RrefRowSpan span(D, ell);
    for (const ExtMatrix& A : mats) {
        for (uint32_t j = 0; j < D; ++j) {
            std::vector<uint32_t> col(D, 0u);
            for (uint32_t i = 0; i < D; ++i) col[i] = A.data[i][j];
            span.insert(std::move(col));
        }
    }
    return span;
}

// rank of [ b_1 v | b_2 v | ... ] for the column vector e_j, i.e. dim A_S v.
uint32_t DimOfModuleGeneratedBy(const std::vector<ExtMatrix>& a_basis,
                                uint32_t j, uint32_t D, uint32_t ell) {
    RrefRowSpan span(D, ell);
    for (const ExtMatrix& b : a_basis) {
        std::vector<uint32_t> v(D, 0u);
        for (uint32_t i = 0; i < D; ++i) v[i] = b.data[i][j];
        span.insert(std::move(v));
    }
    return span.dim();
}

bool SameMatrices(const std::vector<ExtMatrix>& a, const std::vector<ExtMatrix>& b) {
    if (a.size() != b.size()) return false;
    for (size_t i = 0; i < a.size(); ++i) {
        if (a[i].rows != b[i].rows || a[i].cols != b[i].cols || a[i].p != b[i].p) return false;
        if (a[i].data != b[i].data) return false;
    }
    return true;
}

std::string JsonDims(const std::vector<uint32_t>& v) {
    std::ostringstream os;
    os << '[';
    for (size_t i = 0; i < v.size(); ++i) { if (i) os << ", "; os << v[i]; }
    os << ']';
    return os.str();
}

