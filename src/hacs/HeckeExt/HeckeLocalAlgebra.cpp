const char* CyclicityCertificate::verify_message(uint32_t code) {
    switch (code) {
        case 0:  return "ok";
        case 1:  return "malformed: ell, D or f out of range, or f does not divide D";
        case 2:  return "malformed: the prime list is empty or not strictly ascending";
        case 3:  return "malformed: t / character / a_basis / m_basis shape or modulus";
        case 4:  return "pi_w is not monic irreducible of degree f";
        case 5:  return "pi_w(w_hat) != 0 (w_hat is not in the residue field)";
        case 6:  return "some P_p has degree >= f";
        case 7:  return "the stored A_S basis is not the algebra generated by the t_p";
        case 8:  return "some n_p = t_p - P_p(w_hat) is not nilpotent on V";
        case 9:  return "the stored m_S basis is not the ideal (n_p)_p inside A_S";
        case 10: return "the stored dim V/m_S V disagrees with the re-derived rank";
        case 11: return "f does not divide dim V/m_S V, or it is smaller than f";
        case 12: return "the `cyclic` verdict disagrees with dim V/m_S V == f";
        case 13: return "the generator index is not the least standard basis vector outside m_S V";
        case 14: return "A_S v != V for the stored generator (V is not cyclic on that vector)";
        default: return "unknown code";
    }
}

uint32_t CyclicityCertificate::verify() const {
    // --- 1-3: shapes, moduli, ordering. ---------------------------------
    if (ell < 2 || D == 0 || f == 0 || (D % f) != 0) return 1;
    if (primes.empty()) return 2;
    for (size_t i = 1; i < primes.size(); ++i) {
        if (primes[i] <= primes[i - 1]) return 2;
    }
    if (t.size() != primes.size() || character.size() != primes.size()) return 3;
    if (a_basis.empty()) return 3;
    const auto shaped = [&](const ExtMatrix& M) {
        return M.rows == D && M.cols == D && M.p == ell;
    };
    for (const ExtMatrix& M : t)       { if (!shaped(M)) return 3; }
    for (const ExtMatrix& M : a_basis) { if (!shaped(M)) return 3; }
    for (const ExtMatrix& M : m_basis) { if (!shaped(M)) return 3; }
    if (!shaped(w_hat)) return 3;

    // --- 4-6: the coefficient field, re-derived, not read. ---------------
    if (witness_poly.ell != ell) return 4;
    if (witness_poly.degree() != static_cast<int64_t>(f)) return 4;
    if (hecke::CertifyIrreducible(witness_poly) != 0) return 4;
    if (!hecke::EvalPolyAtMatrix(witness_poly, w_hat).is_zero()) return 5;
    for (const FpPoly& P : character) {
        if (P.ell != ell) return 6;
        if (P.degree() >= static_cast<int64_t>(f)) return 6;
    }

    // --- 7: A_S itself.  The closure is RECOMPUTED from the stored t_p and
    // compared ENTRYWISE with the stored basis; the RREF of a span is unique,
    // so this is a bit test and not a span test ([X] Sec. 1.3 R17). --------
    uint32_t dim_A_rederived = 0;
    const ExtMatrix coords_rederived = hecke::algebra_closure(t, D, ell, dim_A_rederived);
    if (dim_A_rederived != static_cast<uint32_t>(a_basis.size())) return 7;
    for (uint32_t i = 0; i < dim_A_rederived; ++i) {
        if (VecOfMatrix(a_basis[i]) != coords_rederived.data[i]) return 7;
    }

    // --- 8: the generators n_p, recomputed and re-tested for nilpotency. --
    std::vector<ExtMatrix> n_rederived;
    n_rederived.reserve(primes.size());
    for (size_t j = 0; j < primes.size(); ++j) {
        ExtMatrix n_p = t[j] - hecke::EvalPolyAtMatrix(character[j], w_hat);
        if (!hecke::IsNilpotent(n_p, D)) return 8;
        n_rederived.push_back(std::move(n_p));
    }

    // --- 9: m_S = (n_p)_p as an ideal of A_S, recomputed and compared. ----
    const RrefRowSpan m_span = SpanOfProducts(a_basis, n_rederived, D, ell);
    if (!SameMatrices(m_basis, UnvecRows(m_span, D, ell))) return 9;

    // --- 10-12: Nakayama's quotient, as a RANK. --------------------------
    const uint32_t dim_mV = RowSpanOfImages(m_basis, D, ell).dim();
    const uint32_t quotient = D - dim_mV;
    if (quotient != dim_quotient) return 10;
    if (quotient < f || (quotient % f) != 0) return 11;
    if (cyclic != (quotient == f)) return 12;
    if (!cyclic) return 0;   // the claim is "not cyclic"; nothing further is asserted

    // --- 13-14: the generator, and A_S v = V. ----------------------------
    const RrefRowSpan mV = RowSpanOfImages(m_basis, D, ell);
    uint32_t least = D;
    for (uint32_t j = 0; j < D; ++j) {
        std::vector<uint32_t> e(D, 0u);
        e[j] = 1u;
        if (!mV.contains(e)) { least = j; break; }
    }
    if (least >= D || least != generator_index) return 13;
    if (DimOfModuleGeneratedBy(a_basis, generator_index, D, ell) != D) return 14;
    return 0;
}

std::string CyclicityCertificate::to_json() const {
    std::ostringstream os;
    os << "{\"kind\": \"cyclicity\""
       << ", \"ell\": " << ell
       << ", \"D\": " << D
       << ", \"f\": " << f
       << ", \"primes\": [";
    for (size_t i = 0; i < primes.size(); ++i) { if (i) os << ", "; os << primes[i]; }
    os << "], \"pi_w\": \"" << witness_poly.to_string() << "\""
       << ", \"character\": [";
    for (size_t i = 0; i < character.size(); ++i) {
        if (i) os << ", ";
        os << '"' << character[i].to_string() << '"';
    }
    os << "], \"dim_A_S\": " << a_basis.size()
       << ", \"dim_m_S\": " << m_basis.size()
       << ", \"dim_quotient\": " << dim_quotient
       << ", \"cyclic\": " << (cyclic ? "true" : "false");
    if (cyclic) os << ", \"generator_index\": " << generator_index;
    os << ", \"verify\": " << verify() << '}';
    return os.str();
}

