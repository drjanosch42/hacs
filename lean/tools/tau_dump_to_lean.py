#!/usr/bin/env python3
"""L16-4: turn the HECKE_DUMP_TAU dump (HeckeTauDumpValidation) into Lean data.

usage: tau_dump_to_lean.py <dump-dir> <out.lean> [--golden <GoldenReference.inc>]

Reads <dump-dir>/tau_p2.txt and <dump-dir>/rho_n*_ell*.txt verbatim (no value is computed
here, only re-typeset) and writes one Lean module with
  GL2.TauChk.Data.tauP2          : TauData
  GL2.TauChk.Data.goldenTauHash  : the golden object tau_table_fnv64_p2_r1 (from the .inc)
  GL2.Exec.Data.rho_n<n>_ell<ell> : List RhoDump
The kernel checks live in GL2/Checkers/TauP2.lean.
"""
import glob
import os
import re
import sys


def mat(xs):
    a, b, c, d = xs
    return f"⟨{a}, {b}, {c}, {d}⟩"


def lean_int(x):
    x = int(x)
    return f"({x})" if x < 0 else str(x)


def parse_tau(path):
    d = {"s": [], "simplices": [], "orbitrep": [], "trs": [], "slots": []}
    cur = None
    with open(path) as f:
        lines = [l.split() for l in f if l.strip() and not l.startswith("#")]
    assert lines[0] == ["TAUDUMP", "1"], lines[0]
    for t in lines[1:]:
        k = t[0]
        if k == "N":
            d["N"] = int(t[1])
        elif k == "m":
            d["m"] = int(t[1])
        elif k == "g":
            d["g"] = t[1:5]
        elif k == "s":
            assert int(t[1]) == len(d["s"]) + 1
            d["s"].append(t[2:6])
        elif k == "simplex":
            d["simplices"].append((int(t[1]), int(t[2]), [int(v) for v in t[3:]]))
        elif k == "orbitrep":
            d["orbitrep"].append(tuple(int(v) for v in t[1:4]))
        elif k == "tr":
            d["trs"].append((int(t[1]), int(t[2]), int(t[3]), t[4:8], [int(v) for v in t[8:11]]))
        elif k == "slot":
            cur = [int(t[1]), int(t[2]), int(t[3]), int(t[4]), []]
            d["slots"].append(cur)
        elif k == "term":
            cur[4].append((int(t[1]), t[2:6], int(t[6])))
        elif k == "regime":
            d["regime"] = t[1]
        elif k == "fnv":
            d["fnv"] = int(t[1])
        elif k == "end":
            pass
        else:
            raise SystemExit(f"unknown line {t}")
    for sl in d["slots"]:
        assert sl[3] == len(sl[4]), sl
    return d


def parse_rho(path):
    n = ell = None
    mats = []
    with open(path) as f:
        lines = [l.split() for l in f if l.strip() and not l.startswith("#")]
    assert lines[0] == ["RHODUMP", "1"], lines[0]
    for t in lines[1:]:
        if t[0] == "n":
            n = int(t[1])
        elif t[0] == "ell":
            ell = int(t[1])
        elif t[0] == "mat":
            mats.append((t[1], [int(v) for v in t[2:6]], []))
        elif t[0] == "row":
            mats[-1][2].append([int(v) for v in t[1:]])
    return n, ell, mats


def golden_hash(inc):
    pat = re.compile(r'\{"n=2 ell=5 ext cone_action", "tau_table_fnv64_p2_r1", \'B\', 1, 1, (0x[0-9a-f]+)ull\}')
    with open(inc) as f:
        for line in f:
            m = pat.search(line)
            if m:
                return m.group(1)
    raise SystemExit("golden tau_table_fnv64_p2_r1 at n=2 ell=5 not found")


def main():
    args = sys.argv[1:]
    golden = None
    if "--golden" in args:
        i = args.index("--golden")
        golden = args[i + 1]
        del args[i:i + 2]
    dump_dir, out = args
    d = parse_tau(os.path.join(dump_dir, "tau_p2.txt"))
    L = []
    L.append("import GL2.Checkers.TauCheck")
    L.append("import GL2.Checkers.RhoExec")
    L.append("")
    L.append("/-! GENERATED by lean/tools/tau_dump_to_lean.py from the HECKE_DUMP_TAU dump of")
    L.append("`HeckeTauDumpValidation` (L16-4). Real C++ output, re-typeset only. Do not edit by hand. -/")
    L.append("")
    L.append("namespace GL2.TauChk.Data")
    L.append("open GL2.TauChk")
    L.append("")
    L.append("/-- The `p = 2`, `ν = 1` τ-table of the golden ext cells' cone action, as dumped. -/")
    L.append("def tauP2 : TauData where")
    L.append(f"  N := {d['N']}")
    L.append(f"  m := {d['m']}")
    L.append(f"  g := {mat([lean_int(x) for x in d['g']])}")
    L.append("  s := [" + ", ".join(mat([lean_int(x) for x in s]) for s in d["s"]) + "]")
    L.append("  simplices := [" + ", ".join(f"({q}, {i}, {vs})" for q, i, vs in d["simplices"]) + "]")
    L.append("  orbitRep := [" + ", ".join(f"({q}, {a}, {b})" for q, a, b in d["orbitrep"]) + "]")
    L.append("  trs := [")
    L.append(",\n".join(f"    ⟨{q}, {a}, {b}, {mat([lean_int(x) for x in g])}, {p}⟩" for q, a, b, g, p in d["trs"]))
    L.append("  ]")
    L.append("  slots := [")
    sl = []
    for i, q, s, _, terms in d["slots"]:
        ts = ", ".join(f"⟨{lean_int(c)}, {mat([lean_int(x) for x in g])}, {sg}⟩" for c, g, sg in terms)
        sl.append(f"    ⟨{i}, {q}, {s}, [{ts}]⟩")
    L.append(",\n".join(sl))
    L.append("  ]")
    L.append(f"  regime := \"{d['regime']}\"")
    L.append(f"  fnv := {d['fnv']}")
    L.append("")
    if golden:
        L.append("/-- The golden object `tau_table_fnv64_p2_r1` (`n=2 ell=5 ext cone_action`, tier B) of")
        L.append("`Orbifold_Cohomology_of_GL2/Golden/GoldenReference.inc`, copied verbatim. -/")
        L.append(f"def goldenTauHash : ℕ := {golden_hash(golden)}")
        L.append("")
    L.append("end GL2.TauChk.Data")
    L.append("")
    L.append("namespace GL2.Exec.Data")
    L.append("open GL2.Exec")
    L.append("")
    for path in sorted(glob.glob(os.path.join(dump_dir, "rho_n*_ell*.txt"))):
        n, ell, mats = parse_rho(path)
        name = f"rho_n{n}_ell{ell}"
        L.append(f"/-- The C++ `ρ_n` matrices at the golden cell `n = {n}`, `ℓ = {ell}`: the p = 2 τ-table's")
        L.append(f"consumer pool and `ComputeSymmetricPowerMatrixFM` on `T, S, ST, TS, s_i, δ_i` ({len(mats)} matrices). -/")
        L.append(f"def {name} : List RhoDump := [")
        ms = []
        for tag, key, rows in mats:
            ms.append(f"    -- {tag}\n    ⟨({key[0]}, {key[1]}, {key[2]}, {key[3]}), {rows}⟩")
        L.append(",\n".join(ms))
        L.append("  ]")
        L.append("")
    L.append("end GL2.Exec.Data")
    with open(out, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"TAU_DUMP_TO_LEAN slots={len(d['slots'])} trs={len(d['trs'])} out={out}")


if __name__ == "__main__":
    main()
