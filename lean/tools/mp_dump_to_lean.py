#!/usr/bin/env python3
"""MP-L1 (slot 22): turn the ORBIFOLD_MP_DUMP dump (OrbifoldMPRulesValidation, MP-1a) into Lean data.

usage: mp_dump_to_lean.py <dump-dir> <out.lean> [--expect-fnv 0x...]

Reads the six TSVs <dump-dir>/mp_{predicates,rz_arrows,rz_orbits,rz_points,rz_sk,rz_top}.tsv verbatim (no value is
computed here, only re-typeset), recomputes the dump's FNV-1a-64 exactly as the C++ emitter does (files in name order,
each contributing its file name and then its body), refuses if it differs from --expect-fnv (the EFFECTIVE line), and
writes one Lean module GL2.MP.RZDump with the raw tables.  The kernel checks (the R_Z descriptor rebuilt from orbits,
points and maximal simplices; its arrows against the dumped arrows; |S_0|, |S_1|; the predicate row) live in
GL2/MP/Models.lean.  Pure: no Lean, no C++.
"""
import os
import sys

FILES = ["mp_predicates.tsv", "mp_rz_arrows.tsv", "mp_rz_orbits.tsv", "mp_rz_points.tsv", "mp_rz_sk.tsv",
         "mp_rz_top.tsv"]
FNV_OFFSET = 0xcbf29ce484222325
FNV_PRIME = 0x100000001b3
TRI = {"M7": 0, "R_Z": 1, "R_Z+": 2, "R_good": 3}


def fnv(h, data):
    for b in data:
        h ^= b
        h = (h * FNV_PRIME) & 0xffffffffffffffff
    return h


def rows(body):
    return [ln.split("\t") for ln in body.splitlines() if ln and not ln.startswith("#")]


def li(x):
    x = int(x)
    return f"({x})" if x < 0 else str(x)


def mat(xs):
    return "⟨" + ", ".join(li(x) for x in xs) + "⟩"


def main(argv):
    if len(argv) < 3:
        raise SystemExit(__doc__)
    d, out = argv[1], argv[2]
    expect = None
    if "--expect-fnv" in argv:
        expect = int(argv[argv.index("--expect-fnv") + 1], 16)
    bodies = {}
    for fn in FILES:
        with open(os.path.join(d, fn), "rb") as f:
            bodies[fn] = f.read()
    h = FNV_OFFSET
    for fn in sorted(FILES):
        h = fnv(h, fn.encode())
        h = fnv(h, bodies[fn])
    if expect is not None and h != expect:
        raise SystemExit("REFUSED: dump fnv 0x%016x != expected 0x%016x" % (h, expect))
    txt = {fn: bodies[fn].decode() for fn in FILES}
    orbits = rows(txt["mp_rz_orbits.tsv"])
    points = rows(txt["mp_rz_points.tsv"])
    top = rows(txt["mp_rz_top.tsv"])
    arrows = rows(txt["mp_rz_arrows.tsv"])
    sk = rows(txt["mp_rz_sk.tsv"])
    preds = rows(txt["mp_predicates.tsv"])
    for i, r in enumerate(orbits):
        assert int(r[0]) == i, "orbits not consecutive"
    for i, r in enumerate(points):
        assert int(r[0]) == i, "point labels not consecutive"
    for i, r in enumerate(top):
        assert int(r[0]) == i, "top simplices not consecutive"
    L = []
    L.append("import GL2.MP.Descriptor")
    L.append("")
    L.append("/-! GENERATED by lean/tools/mp_dump_to_lean.py from the ORBIFOLD_MP_DUMP dump of `OrbifoldMPRulesValidation`")
    L.append("(MP-1a). Real C++ output, re-typeset only. Do not edit by hand.")
    L.append("")
    L.append("Dump FNV-1a-64 (recomputed by the generator as the emitter computes it): `0x%016x`. -/" % h)
    L.append("")
    L.append("namespace GL2.MP.RZDump")
    L.append("open GL2.TauChk GL2.MP")
    L.append("")
    L.append("/-- The dump's FNV-1a-64 (`EFFECTIVE OrbifoldMPRulesValidation arm=dump … fnv=`). -/")
    L.append("def dumpFnv : ℕ := 0x%016x" % h)
    L.append("")
    L.append("/-- `mp_rz_orbits.tsv`: `(label, stabiliser generator, order)` per vertex orbit. -/")
    L.append("def orbits : List (ℕ × M22 × ℕ) := [")
    L.append(",\n".join(f"  ({r[1]}, {mat(r[2:6])}, {r[6]})" for r in orbits) + "]")
    L.append("")
    L.append("/-- `mp_rz_points.tsv`: `(orbit, g, boundary)` per point label (`label = g · ι(orbit)`). -/")
    L.append("def points : List (ℕ × M22 × Bool) := [")
    L.append(",\n".join(f"  ({r[1]}, {mat(r[2:6])}, {'true' if r[6] == '1' else 'false'})" for r in points) + "]")
    L.append("")
    L.append("/-- `mp_rz_top.tsv`: the maximal simplices of the lifted domain (point labels, stored order). -/")
    L.append("def top : List (List ℕ) := [" + ", ".join("[" + ", ".join(r[1:]) + "]" for r in top) + "]")
    L.append("")
    L.append("/-- `mp_rz_arrows.tsv`: `(σ, σ', γ)` with `γ ∈ Ar(σ, σ')`, as the C++ `Arrows` lists them. -/")
    L.append("def arrows : List (ℕ × ℕ × M22) := [")
    L.append(",\n".join(f"  ({r[0]}, {r[1]}, {mat(r[2:6])})" for r in arrows) + "]")
    L.append("")
    L.append("/-- `mp_rz_sk.tsv`: `(k, |S_k| all, |S_k| non-degenerate)`. -/")
    L.append("def sk : List (ℕ × ℕ × ℕ) := [" + ", ".join(f"({r[0]}, {r[1]}, {r[2]})" for r in sk) + "]")
    L.append("")
    L.append("/-- `mp_predicates.tsv`: one `PredRow` per line (triangulation 0 = M7, 1 = R_Z, 2 = R_Z+, 3 = R_good). -/")
    L.append("def predicates : List PredRow := [")
    B = lambda x: "true" if x == "1" else "false"
    L.append(",\n".join(f"  ⟨{TRI[r[0]]}, {r[1]}, {B(r[2])}, {B(r[3])}, {B(r[4])}, {B(r[5])}, {r[6]}, {r[7]}, {r[8]}, {li(r[9])}⟩"
                        for r in preds) + "]")
    L.append("")
    L.append("end GL2.MP.RZDump")
    L.append("")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print("MP_DUMP_TO_LEAN out=%s fnv=0x%016x orbits=%d points=%d top=%d arrows=%d" %
          (out, h, len(orbits), len(points), len(top), len(arrows)))


if __name__ == "__main__":
    main(sys.argv)
