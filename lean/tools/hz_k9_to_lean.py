"""L-K9 data generator (UNTRUSTED): H1's K9 table -> the Mathlib-free Lean data module + a sha256 manifest.

Input:  docs/implementation/slot25/h1/k9_data.tsv (slot-25 H1, HeckeHidaEisLambda K9Line; one row per irregular pair at its first
        weight, every residue below ell^2).
Output: lean/GL2/HeckeZ/Cells/K9Data.lean (the 12 certificates; the kernel re-checks them by `decide +kernel`),
        docs/implementation/slot25/lk9-data/manifest_lk9.tsv (input sha256, per-row fields, the module).

The generator mirrors every check of GL2.HeckeZ.Exec.K9.k9Check and refuses a failing row. Independently of the C++ (but still
untrusted: nothing here enters the kernel), it recomputes B_k/k, G_a(x_k) = -(1 - ell^(k-1)) B_k/k and G_a(x_{k+ell-1}) mod ell^2 from
sympy's exact Bernoulli numbers and compares them with the table (TB-B cross-check); f_k is NOT re-derived here (H1: h1/k9_check.py
re-derives the 547 row, the H1 audit's audh1/math/k9.py all 12).

Usage: hz_k9_to_lean.py <repo-root> [--check]   (--check: regenerate in memory and compare with the committed files)
"""
import hashlib
import sys
from fractions import Fraction
from pathlib import Path

try:
    from sympy import bernoulli
except ImportError:  # pragma: no cover
    bernoulli = None

TSV = "docs/implementation/slot25/h1/k9_data.tsv"
LEAN = "lean/GL2/HeckeZ/Cells/K9Data.lean"
MANIFEST = "docs/implementation/slot25/lk9-data/manifest_lk9.tsv"


def is_prime(n):
    return n >= 2 and all(n % d for d in range(2, int(n ** 0.5) + 1))


def pmul(a, b):
    c = [0] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            c[i + j] += x * y
    return c


def plin(a, g):
    r = [1]
    for _ in range(g):
        r = pmul([-a, 1], r)
    return r


def peval(p, t):
    acc = 0
    for c in reversed(p):
        acc = c + t * acc
    return acc


def v1(ell, z):
    return z % ell == 0 and z % (ell * ell) != 0


def res(q, m):
    """A rational with denominator prime to m, reduced mod m."""
    q = Fraction(q)
    return q.numerator * pow(q.denominator, -1, m) % m


def check_row(r):
    ell, k, flo, e, bk, gk, gnext, lam = r["ell"], r["k"], r["flo"], r["e"], r["bk"], r["gk"], r["gnext"], r["lam"]
    M = ell * ell
    F = flo + [1]
    g = len(flo)
    checks = {
        "guard": is_prime(ell) and ell >= 5 and k >= 3 and k % (ell - 1) != 0 and g >= 1 and k - 1 < 2 ** 12,
        "root": e == (1 + pow(2, k - 1, M)) % M,
        "shape": all((x - y) % ell == 0 for x, y in zip(F, plin(e, g))),
        "val": v1(ell, peval(F, e)),
        "bern": v1(ell, bk),
        "disc": g != 2 or v1(ell, F[1] ** 2 - 4 * F[0]),
        "sign": (gk + bk) % M == 0,
        "lam": (gk - gnext - ell * lam) % M == 0 and lam % ell != 0,
    }
    return checks


def tbb_crosscheck(r):
    if bernoulli is None:
        return "skipped(no sympy)"
    ell, k = r["ell"], r["k"]
    M = ell * ell
    bk = res(Fraction(int(bernoulli(k).p), int(bernoulli(k).q)) / k, M)
    k2 = k + ell - 1
    b2 = res(Fraction(int(bernoulli(k2).p), int(bernoulli(k2).q)) / k2, M)
    gk = -(1 - ell ** (k - 1)) * bk % M
    g2 = -(1 - ell ** (k2 - 1)) * b2 % M
    ok = (bk, gk, g2) == (r["bk"], r["gk"], r["gnext"])
    return "ok" if ok else f"MISMATCH(bk={bk},gk={gk},gnext={g2})"


def read_rows(text):
    rows = []
    for line in text.splitlines():
        if not line or line.startswith("#") or line.startswith("ell\t"):
            continue
        f = line.split("\t")
        coeffs = [int(x) for x in f[3].strip("[]").split(",")]
        if coeffs[-1] != 1 or len(coeffs) != int(f[2]) + 1:
            raise SystemExit(f"REFUSED: row {f[0]} {f[1]}: f_k not monic of degree g")
        rows.append(dict(ell=int(f[0]), k=int(f[1]), flo=coeffs[:-1], e=int(f[4]), bk=int(f[5]), gk=int(f[6]),
                         gnext=int(f[7]), lam=int(f[8]), cpp_checks=f[9]))
    return rows


def lean_module(rows, sha):
    out = ["/-",
           # REUSE-IgnoreStart (the header this tool writes, not this file's licence)
           "SPDX-FileCopyrightText: 2024-2026 Fabian Januszewski",
           "SPDX-License-Identifier: Apache-2.0",
           # REUSE-IgnoreEnd
           "-/",
           "import GL2.HeckeZ.Exec.K9",
           "",
           "/-!",
           "# K9 data: the 12 irregular pairs of slot-25 H1 (generated; do not edit)",
           "",
           "Generated by `lean/tools/hz_k9_to_lean.py` (untrusted) from `docs/implementation/slot25/h1/k9_data.tsv`",
           f"(sha256 `{sha}`; manifest `docs/implementation/slot25/lk9-data/manifest_lk9.tsv`). One certificate per pair at its",
           "first weight: the 11 C2 chain pairs ([U] `prop:u-H11`, g = 1) and (547, 486) ([U] `prop:u-H12`, g = 2).",
           "Mathlib-free: `k9Cells_check` is decided by `decide +kernel`.",
           "-/",
           "",
           "namespace GL2.HeckeZ.Cells.K9Data",
           "",
           "open GL2.HeckeZ.Exec.K9",
           "",
           "/-- The 12 K9 certificates (H1, `k9_data.tsv`). -/",
           "def k9Cells : List K9Cert := ["]
    items = []
    for r in rows:
        items.append(f"  {{ ell := {r['ell']}, k := {r['k']}, flo := [{', '.join(str(x) for x in r['flo'])}], e := {r['e']}, "
                     f"bk := {r['bk']}, gk := {r['gk']}, gnext := {r['gnext']}, lam := {r['lam']} }}")
    out.append(",\n".join(items))
    out += ["]",
            "",
            "/-- There are 12 certificates. -/",
            "theorem k9Cells_length : k9Cells.length = 12 := by decide +kernel",
            "",
            "/-- **Every certificate passes K9** (kernel). -/",
            "theorem k9Cells_check : k9Cells.all k9Check = true := by decide +kernel",
            "",
            "end GL2.HeckeZ.Cells.K9Data",
            ""]
    return "\n".join(out)


def manifest(rows, sha, tbb, out_sha):
    out = ["# L-K9 manifest (generated by lean/tools/hz_k9_to_lean.py; do not edit)",
           f"# input\t{TSV}\tsha256\t{sha}",
           f"# output\t{LEAN}\tsha256\t{out_sha}",
           "# source: slot-25 H1 (HeckeHidaEisLambda K9Line), H1_report.md section 5; module " + LEAN,
           "ell\tk\tg\te\tbk\tgk\tgnext\tlam\tpy_checks\ttbb_sympy\tcpp_checks\tmodule"]
    for r, t in zip(rows, tbb):
        out.append("\t".join(str(x) for x in [r["ell"], r["k"], len(r["flo"]), r["e"], r["bk"], r["gk"], r["gnext"], r["lam"],
                                               "all8", t, r["cpp_checks"], "GL2.HeckeZ.Cells.K9Data"]))
    return "\n".join(out) + "\n"


def main():
    root = Path(sys.argv[1])
    data = (root / TSV).read_bytes()
    sha = hashlib.sha256(data).hexdigest()
    rows = read_rows(data.decode())
    if len(rows) != 12:
        raise SystemExit(f"REFUSED: {len(rows)} rows, expected 12")
    for r in rows:
        bad = [n for n, ok in check_row(r).items() if not ok]
        if bad:
            raise SystemExit(f"REFUSED: ({r['ell']}, {r['k']}) fails {bad}")
    tbb = [tbb_crosscheck(r) for r in rows]
    if any(t.startswith("MISMATCH") for t in tbb):
        raise SystemExit(f"REFUSED: TB-B cross-check {tbb}")
    lean = lean_module(rows, sha)
    man = manifest(rows, sha, tbb, hashlib.sha256(lean.encode()).hexdigest())
    if "--check" in sys.argv:
        same = (root / LEAN).read_text() == lean and (root / MANIFEST).read_text() == man
        print(f"HZ_K9_GEN rows={len(rows)} tbb_ok={tbb.count('ok')} regenerated_identical={'yes' if same else 'NO'}")
        sys.exit(0 if same else 1)
    (root / LEAN).write_text(lean)
    (root / MANIFEST).parent.mkdir(parents=True, exist_ok=True)
    (root / MANIFEST).write_text(man)
    print(f"HZ_K9_GEN rows={len(rows)} tbb_ok={tbb.count('ok')} input_sha256={sha} wrote={LEAN},{MANIFEST}")


if __name__ == "__main__":
    main()
