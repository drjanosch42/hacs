#!/usr/bin/env python3
"""S20 L20-4: turn a HECKE_DUMP_MEREL dump (HeckeLevelNValidation) into Lean data.

usage: merel_dump_to_lean.py <dump-dir> <out.lean>

Reads every <dump-dir>/merel_N<N>_n<n>_p<p>.txt verbatim (no value is computed here, only re-typeset; dst / src are
shifted from the C++'s 1-based indices to 0-based) and writes one Lean module with one
  GL2.M4.Data.merel_N<N>_n<n>_p<p> : MerelDump
per file.  The kernel checks live in GL2/Checkers/MerelN5.lean.

Provenance (slot-20 L20-6, F3-20 MINOR 7): each generated docstring carries dense_fnv64, the FNV-1a-64 of D and then every
dense entry row-major, each fed as one 64-bit little-endian word (ModArithmetic/ModArithmetic/Fnv.h, FnvHasher); the C++
prints the same value on its MEREL_DUMP line, so the committed data can be matched to a C++ run.
"""
import glob
import os
import re
import sys


def lean_int(x):
    x = int(x)
    return f"({x})" if x < 0 else str(x)


def q4(xs):
    return "(" + ", ".join(lean_int(v) for v in xs) + ")"


FNV_OFFSET = 0xcbf29ce484222325
FNV_PRIME = 0x100000001b3


def fnv_u64(h, v):
    for i in range(8):
        h ^= (v >> (8 * i)) & 0xff
        h = (h * FNV_PRIME) & 0xffffffffffffffff
    return h


def dense_fnv64(rows):
    h = fnv_u64(FNV_OFFSET, len(rows))
    for r in rows:
        assert len(r) == len(rows)
        for v in r:
            h = fnv_u64(h, v)
    return h


def parse(path):
    d = {"reps": [], "merel": [], "terms": [], "rows": []}
    with open(path) as f:
        lines = [l.split() for l in f if l.strip()]
    assert lines[0] == ["MERELDUMP", "1"], lines[0]
    assert lines[-1] == ["end"], lines[-1]
    hdr = lines[1]
    kv = dict(zip(hdr[0::2], hdr[1::2]))
    for k in ("N", "n", "p", "q", "m"):
        d[k] = int(kv[k])
    dd = (d["n"] + 1) ** 2
    for t in lines[2:-1]:
        k = t[0]
        if k == "rep":
            assert int(t[1]) == len(d["reps"]) + 1
            d["reps"].append(t[2:6])
        elif k == "eps":
            d["merel"].append(t[1:5])
        elif k == "term":
            assert len(t) == 7 + dd, (path, t)
            d["terms"].append((int(t[1]) - 1, int(t[2]) - 1, t[3:7], [int(v) for v in t[7:]]))
        elif k == "row":
            assert int(t[1]) == len(d["rows"])
            d["rows"].append([int(v) for v in t[2:]])
        else:
            raise SystemExit(f"{path}: unknown line {t}")
    assert len(d["reps"]) == d["m"]
    return d


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    src, out = sys.argv[1], sys.argv[2]
    files = sorted(glob.glob(os.path.join(src, "merel_N*_n*_p*.txt")))
    if not files:
        raise SystemExit(f"no merel_N*_n*_p*.txt in {src}")
    o = ["-- GENERATED by lean/tools/merel_dump_to_lean.py from the HECKE_DUMP_MEREL dump of HeckeLevelNValidation",
         "-- (slot 20, L20-4).  Do not edit.  Checked in GL2/Checkers/MerelN5.lean.",
         "import GL2.Checkers.MerelCheck", "", "namespace GL2.M4.Data", "open GL2.M4", ""]
    for path in files:
        name = re.sub(r"\.txt$", "", os.path.basename(path))
        d = parse(path)
        o.append(f"/-- `{os.path.basename(path)}`: N = {d['N']}, n = {d['n']}, p = {d['p']}, q = {d['q']}, "
                 f"m = {d['m']}, {len(d['terms'])} terms, "
                 f"dense_fnv64 = 0x{dense_fnv64(d['rows']):016x}. -/")
        o.append(f"def {name} : MerelDump where")
        o.append(f"  N := {d['N']}")
        o.append(f"  n := {d['n']}")
        o.append(f"  p := {d['p']}")
        o.append(f"  q := {d['q']}")
        o.append("  reps := [" + ", ".join(q4(r) for r in d["reps"]) + "]")
        o.append("  merel := [" + ", ".join(q4(e) for e in d["merel"]) + "]")
        o.append("  terms := [")
        o.append(",\n".join(f"    ({a}, {b}, {q4(m)}, [{', '.join(map(str, blk))}])"
                            for a, b, m, blk in d["terms"]))
        o.append("  ]")
        o.append("  dense := [")
        o.append(",\n".join("    [" + ", ".join(map(str, r)) + "]" for r in d["rows"]))
        o.append("  ]")
        o.append("")
    o.append("end GL2.M4.Data")
    with open(out, "w") as f:
        f.write("\n".join(o) + "\n")
    print(f"MEREL_TO_LEAN files={len(files)} out={out}")


if __name__ == "__main__":
    main()
