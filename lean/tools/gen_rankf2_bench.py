"""gen_rankf2_bench.py -- LV-0 (slot 22): the kernel benchmarks of `GL2.L23.RankF2` (L23_master_plan.md §4.2(2)).

Writes lean/bench/L23/RankF2{R,A,G}<d>.lean (and RankF2M1000.lean) for d in --dims:

  R<d>  `rankF2 (qrRows d) = k`               a pseudo-random d x d matrix, by decide +kernel
  A<d>  `rankF2 (amalgamCols (d-1)) = k`      [1 + rho_n(S) | 1 + rho_n(U) + rho_n(U)^2] mod 2, n = d - 1
  G<d>  `xorAll (amalgamCols (d-1)) = h`      generation of A<d> only (no elimination)
  M1000 `(toMat 1000 (qrRows 1000)).rank = k` the Mathlib statement via `rank_of_decide` (imports Mathlib)

The expected k / h are computed here, independently of Lean (Python big ints, a separate elimination).
The modules are NOT in the default build target (lakefile lib `L23Bench`, srcDir `bench`).

  --run   additionally time every module: `/usr/bin/time -v lake env lean <file>` under
          `systemd-run --user --scope -p MemoryMax=<cap>`; prints one `LV0_BENCH` line per module and writes a TSV.
"""
import argparse
import os
import re
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
LEAN = os.path.dirname(HERE)
BENCH = os.path.join(LEAN, "bench", "L23")

HEADER = """/-
SPDX-FileCopyrightText: 2024-2026 Fabian Januszewski
SPDX-License-Identifier: Apache-2.0
-/
"""


def qr_rows(d):
    m = 2 ** d - 1
    x = m // 3
    out = []
    for _ in range(d):
        x = (x * x + 12345) % m
        out.append(x)
    return out


def col_u(n, j):
    acc, m = 0, j
    while True:
        acc ^= 1 << (n - m)
        if m == 0:
            return acc
        m = (m - 1) & j


def apply_cols(cols, v):
    acc = 0
    for c in cols:
        if v & 1:
            acc ^= c
        v >>= 1
    return acc


def amalgam_cols(n):
    u = [col_u(n, j) for j in range(n + 1)]
    s = [(1 << j) ^ (1 << (n - j)) for j in range(n + 1)]
    n3 = [(1 << j) ^ u[j] ^ apply_cols(u, u[j]) for j in range(n + 1)]
    return s + n3


def rank_f2(rows):
    """Independent elimination: a dict pivot -> row (top-bit pivots)."""
    piv = {}
    for r in rows:
        while r:
            t = r.bit_length() - 1
            if t in piv:
                r ^= piv[t]
            else:
                piv[t] = r
                break
    return len(piv)


def xor_all(rows):
    acc = 0
    for r in rows:
        acc ^= r
    return acc


def module(imports, body, doc):
    return HEADER + "".join("import %s\n" % i for i in imports) + "\n/-! %s -/\n\nnamespace GL2.L23.RankF2.Bench\n\nopen GL2.L23.RankF2\n\n%s\nend GL2.L23.RankF2.Bench\n" % (doc, body)


def generate(dims):
    os.makedirs(BENCH, exist_ok=True)
    files = []
    for d in dims:
        rows = qr_rows(d)
        k = rank_f2(rows)
        body = "/-- R(%d): the pseudo-random `%d × %d` matrix has rank %d over `F₂`. -/\ntheorem rankR_%d : rankF2 (qrRows %d) = %d := by\n  decide +kernel\n" % (d, d, d, k, d, d, k)
        if d == min(dims):
            body += "\n/-- Negative control: the wrong rank is refuted by the same kernel run. -/\ntheorem rankR_%d_ne : rankF2 (qrRows %d) ≠ %d := by\n  decide +kernel\n" % (d, d, k + 1)
        files.append(("R", d, k, "RankF2R%d" % d, module(["GL2.L23.RankF2Exec"], body,
                      "LV-0 benchmark R(%d), generated by `lean/tools/gen_rankf2_bench.py`; do not edit." % d)))
        n = d - 1
        cols = amalgam_cols(n)
        ka = rank_f2(cols)
        body = "/-- A(%d): `[1 + ρ_%d(S) | 1 + ρ_%d(U) + ρ_%d(U)²]` mod 2 has rank %d. -/\ntheorem rankA_%d : rankF2 (amalgamCols %d) = %d := by\n  decide +kernel\n" % (d, n, n, n, ka, d, n, ka)
        files.append(("A", d, ka, "RankF2A%d" % d, module(["GL2.L23.RankF2Exec"], body,
                      "LV-0 benchmark A(%d), generated by `lean/tools/gen_rankf2_bench.py`; do not edit." % d)))
        h = xor_all(cols)
        body = "/-- G(%d): generation of A(%d) only (the xor of its columns). -/\ntheorem genA_%d : xorAll (amalgamCols %d) = %d := by\n  decide +kernel\n" % (d, d, d, n, h)
        files.append(("G", d, h, "RankF2G%d" % d, module(["GL2.L23.RankF2Exec"], body,
                      "LV-0 benchmark G(%d), generated by `lean/tools/gen_rankf2_bench.py`; do not edit." % d)))
    if 1000 in dims:
        k = rank_f2(qr_rows(1000))
        body = ("/-- M(1000): the Mathlib statement, `Matrix.rank` over `ZMod 2`, from two kernel decisions. -/\n"
                "theorem rankM_1000 : (toMat 1000 (qrRows 1000)).rank = %d :=\n"
                "  rank_of_decide 1000 (qrRows 1000) %d (by decide +kernel) (by decide +kernel)\n" % (k, k))
        files.append(("M", 1000, k, "RankF2M1000", module(["GL2.L23.RankF2"], body,
                      "LV-0 benchmark M(1000) (imports Mathlib), generated by `lean/tools/gen_rankf2_bench.py`; do not edit.")))
    for _, _, _, name, text in files:
        with open(os.path.join(BENCH, name + ".lean"), "w") as f:
            f.write(text)
    return files


def run(files, cap, out_tsv):
    rows = []
    for kind, d, k, name, _ in files:
        path = os.path.join(BENCH, name + ".lean")
        cmd = ["systemd-run", "--user", "--scope", "-q", "-p", "MemoryMax=" + cap,
               "/usr/bin/time", "-v", "lake", "env", "lean", path]
        t0 = time.time()
        p = subprocess.run(cmd, cwd=LEAN, capture_output=True, text=True)
        wall = time.time() - t0
        err = p.stderr
        rss = re.search(r"Maximum resident set size \(kbytes\): (\d+)", err)
        el = re.search(r"Elapsed \(wall clock\) time \(h:mm:ss or m:ss\): (\S+)", err)
        rss_gb = int(rss.group(1)) / 1048576 if rss else float("nan")
        status = "OK" if p.returncode == 0 and "error" not in p.stdout else "FAIL(rc=%d)" % p.returncode
        line = "LV0_BENCH kind=%s d=%d wall_s=%.2f time_v=%s rss_gb=%.3f status=%s" % (
            kind, d, wall, el.group(1) if el else "?", rss_gb, status)
        print(line, flush=True)
        if status != "OK":
            print((p.stdout + err)[-2000:], file=sys.stderr)
        rows.append((kind, d, "%.2f" % wall, "%.3f" % rss_gb, status))
    os.makedirs(os.path.dirname(os.path.abspath(out_tsv)), exist_ok=True)
    with open(out_tsv, "w") as f:
        f.write("kind\td\twall_s\trss_gb\tstatus\n")
        for r in rows:
            f.write("\t".join(map(str, r)) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dims", default="100,250,500,1000,2000")
    ap.add_argument("--run", action="store_true")
    ap.add_argument("--only", default="", help="comma list of module names to run (default: all)")
    ap.add_argument("--cap", default="12G")
    ap.add_argument("--out", default=os.path.join(os.environ.get("XDG_CACHE_HOME") or os.path.expanduser("~/.cache"),
                                                 "hacs", "lv0", "bench.tsv"))
    a = ap.parse_args()
    dims = [int(x) for x in a.dims.split(",")]
    files = generate(dims)
    for kind, d, k, name, _ in files:
        print("LV0_GEN %s d=%d expected=%s" % (name, d, k if kind != "G" else "0x%x" % k))
    if a.run:
        if a.only:
            keep = set(a.only.split(","))
            files = [f for f in files if f[3] in keep]
        run(files, a.cap, a.out)


if __name__ == "__main__":
    main()
