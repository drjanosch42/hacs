#!/usr/bin/env python3
"""L17-4 repair: the rho_n dumps of HeckeTauDumpValidation at many cells -> one kernel-checked Lean module per cell.

usage: rho_grid_to_lean.py <dump-dir> <lean-root>      (<lean-root> = the repository's lean/)

Reads every <dump-dir>/rho_n<n>_ell<ell>.txt (written by HECKE_DUMP_TAU=<dump-dir> with
HECKE_DUMP_TAU_RHO_CELLS="n:ell,...") verbatim -- no value is computed here, only re-typeset -- and writes
  <lean-root>/GL2/Checkers/RhoGrid/N<n>L<ell>.lean   data `GL2.Exec.RhoGrid.rho_n<n>_ell<ell> : List RhoDump`
                                                    and `rho_n<n>_ell<ell>_ok : rhoCheck n ell … = true`
                                                    by `decide +kernel` on rhoCheckFast (= rhoCheck,
                                                    rhoCheckFast_eq; no native_decide)
  <lean-root>/GL2/Checkers/RhoGrid.lean               imports them all; `rho_grid_cells` (rhoCheck_sound at every
                                                    cell) and the negative control `rho_grid_tampered_rejected`
and prints one RHO_GRID_TO_LEAN line.  The [GT] row is orc:rhogrid.
"""
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tau_dump_to_lean import parse_rho  # noqa: E402

CHAINS = 4


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    dump_dir, root = sys.argv[1:]
    outdir = os.path.join(root, "GL2", "Checkers", "RhoGrid")
    os.makedirs(outdir, exist_ok=True)
    cells = []
    for path in glob.glob(os.path.join(dump_dir, "rho_n*_ell*.txt")):
        n, ell, mats = parse_rho(path)
        m = re.search(r"rho_n(\d+)_ell(\d+)\.txt$", path)
        assert m and (int(m.group(1)), int(m.group(2))) == (n, ell), path
        cells.append((n, ell, mats))
    cells.sort(key=lambda c: (c[0], c[1]))
    if not cells:
        raise SystemExit("no rho_n*_ell*.txt in " + dump_dir)
    names = []
    for idx, (n, ell, mats) in enumerate(cells):
        for tag, key, rows in mats:
            assert len(rows) == n + 1 and all(len(r) == n + 1 for r in rows), (n, ell, tag)
        mod = f"N{n}L{ell}"
        name = f"rho_n{n}_ell{ell}"
        # four import chains (cell i imports cell i-4): at most four cell modules elaborate at once under a plain
        # `lake build` (a cell peaks at ≈ 8.5 GB RSS, Mathlib's mmapped oleans included)
        prev = f"GL2.Checkers.RhoGrid.N{cells[idx - CHAINS][0]}L{cells[idx - CHAINS][1]}" if idx >= CHAINS else "GL2.Checkers.RhoFast"
        L = [f"import {prev}", "",
             f"/-! GENERATED by lean/tools/rho_grid_to_lean.py from the HECKE_DUMP_TAU dump of `HeckeTauDumpValidation`",
             "(HECKE_DUMP_TAU_RHO_CELLS, L17-4 repair). Real C++ output, re-typeset only. Do not edit by hand. -/", "",
             "namespace GL2.Exec.RhoGrid", "open GL2.Exec", "",
             "set_option maxRecDepth 100000", "",
             ]
        mnames = []
        for i, (tag, k, rows) in enumerate(mats):
            mn = f"{name}_m{i}"
            mnames.append(mn)
            L += [f"/-- `{tag}` at `n = {n}`, `ℓ = {ell}`. -/",
                  f"def {mn} : RhoDump := ⟨({k[0]}, {k[1]}, {k[2]}, {k[3]}), {rows}⟩", "",
                  f"theorem {mn}_ok : rhoCheckOneFast {n} {ell} {mn} = true := by decide +kernel", ""]
        L += [f"/-- The C++ `ρ_n` matrices at the golden ext cone_action cell `n = {n}`, `ℓ = {ell}`: the `p = 2` τ-table's",
              f"consumer pool and `ComputeSymmetricPowerMatrixFM` on `T, S, ST, TS, s_i, δ_i` ({len(mats)} matrices). -/",
              f"def {name} : List RhoDump := [" + ", ".join(mnames) + "]", "",
              "/-- One `decide +kernel` per matrix (the kernel's cache is per declaration), assembled. -/",
              f"theorem {name}_ok : rhoCheck {n} {ell} {name} = true := by",
              f"  rw [← rhoCheckFast_eq]",
              f"  simp only [rhoCheckFast, {name}, List.all_cons, List.all_nil, Bool.and_true, " +
              ", ".join(f"{mn}_ok" for mn in mnames) + "]", "",
              "end GL2.Exec.RhoGrid", ""]
        with open(os.path.join(outdir, mod + ".lean"), "w") as f:
            f.write("\n".join(L))
        names.append((n, ell, mod, name, len(mats)))
    # the tampered control at the largest cell (largest n, then largest ell)
    n0, ell0, _, t0, _ = names[-1]
    L = ["\n".join(f"import GL2.Checkers.RhoGrid.{mod}" for _, _, mod, _, _ in names), "",
         "/-!",
         "# L17-4 repair: the `ρ_n` oracle at every golden `ext cone_action` cell (kernel-checked)",
         "",
         "[GT] `orc:rhogrid`. GENERATED by `lean/tools/rho_grid_to_lean.py`. Each cell module proves",
         "`rhoCheck n ℓ rho_n<n>_ell<ℓ> = true` by `decide +kernel` on `rhoCheckFast` (`rhoCheckFast_eq`; no `native_decide`, no axiom beyond the",
         "standard three); `rho_grid_cells` applies `rhoCheck_sound`, so every dumped C++ matrix read in `ZMod ℓ` is",
         "`rhoMat n` of its key. There is no golden ρ object: the check is against the definition `rhoMat`",
         "(= `GL2.rhoMat`, `rhoMat_eq`), at the golden harness's 31 points. -/", "",
         "namespace GL2.Exec.RhoGrid", "open GL2.Exec", "",
         "/-- **The differential oracle at every golden ext cone_action cell.** -/",
         "theorem rho_grid_cells :"]
    conj = [f"    (∀ D ∈ {nm}, (Matrix.of fun (t j : Fin {n + 1}) => ((D.entry t j : ℕ) : ZMod {ell})) =\n"
            f"        rhoMat {n} (D.mat (R := ZMod {ell})))" for n, ell, _, nm, _ in names]
    L.append(" ∧\n".join(conj) + " :=")
    L.append("  ⟨" + ",\n   ".join(f"fun D hD => (rhoCheck_sound _ _ _ {nm}_ok D hD).1" for _, _, _, nm, _ in names) + "⟩")
    L += ["",
          f"/-- Negative control at `n = {n0}`, `ℓ = {ell0}`: the first entry of the first matrix moved by one is rejected. -/",
          "theorem rho_grid_tampered_rejected :",
          f"    rhoCheck {n0} {ell0} ({t0}.modifyHead fun D =>",
          f"      {{ D with rows := D.rows.modifyHead fun r => r.modifyHead fun x => (x + 1) % {ell0} }}) = false := by",
          "  rw [← rhoCheckFast_eq]; decide +kernel", "",
          "end GL2.Exec.RhoGrid", ""]
    with open(os.path.join(root, "GL2", "Checkers", "RhoGrid.lean"), "w") as f:
        f.write("\n".join(L))
    print(f"RHO_GRID_TO_LEAN cells={len(names)} mats={sum(c[4] for c in names)} out={outdir}")


if __name__ == "__main__":
    main()
