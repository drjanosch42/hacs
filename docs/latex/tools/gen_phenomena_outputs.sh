# gen_phenomena_outputs.sh -- the drift guard of the phenomena gallery [PG] (docs/latex/phenomena_gallery.tex).
#
#   usage: docs/latex/tools/gen_phenomena_outputs.sh <hacs> [--check]
#
# Runs every snippet of notebook/examples/ that the gallery shows (the list SNIPPETS below, in the
# gallery's order) with `<binary> --script <file>`, under an RSS watchdog (default 4 GiB,
# PG_RSS_CAP_MIB to change it), and
#   * (default)  writes each transcript to docs/latex/phenomena_gallery/<name>.out and the measured
#                wall time / peak RSS to docs/latex/phenomena_gallery/costs.tex (the gallery \input's
#                both, so the document and the files cannot diverge);
#   * --check    writes nothing in the tree: it diffs each fresh transcript against the committed
#                <name>.out and exits 1 on the first difference (costs are measured, never compared).
# Exit: 0 all snippets exit 0 (and, with --check, every transcript is unchanged); 1 otherwise;
# 2 usage. Lines starting with '#~ ' (transcript-excluded annotations) and the thread-count line
# 'EFFECTIVE HECKEZ_LOCAL_PAR ' (host-dependent) are dropped.
set -u
BIN="${1:-}"
MODE="${2:-}"
[ -n "$BIN" ] && [ -x "$BIN" ] || { echo "usage: $0 <hacs> [--check]" >&2; exit 2; }
[ -z "$MODE" ] || [ "$MODE" = "--check" ] || { echo "usage: $0 <hacs> [--check]" >&2; exit 2; }
BIN="$(cd "$(dirname "$BIN")" && pwd)/$(basename "$BIN")"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"          # docs/latex
ROOT="$(cd "$HERE/../.." && pwd)"
EX="$ROOT/notebook/examples"
OUTDIR="$HERE/phenomena_gallery"
CAP_KB=$(( ${PG_RSS_CAP_MIB:-4096} * 1024 ))

SNIPPETS="cohomology_dimensions forms_vs_cohomology_24_7
eisenstein_sign_cone_10_691
ramanujan_10_691 kummer_ribet_30_37 kummer_unit_37_59 visible_congruence_48_7 hidden_congruence_300_23
dihedral_wilton_10_23 multiplicity_two_34_5 dickson_theta_16_7 loewy4_258_37
level_n_old_forms_2_7 nebentypus_7_13
hida_control_13 pow_ordinary_rank_13 hida_tower_13_10 hida_lambda_11_12
descent_torsion_beta descent_congruence_primes ramanujan_691_over_Z nonsplit_torsion_16_2"

TMP="$(mktemp -d "${TMPDIR:-$HOME}/pg_outputs.XXXXXX")" || exit 2
trap 'rm -rf "$TMP"' EXIT
fail=0
COSTS="$TMP/costs.tex"
{
  echo "% GENERATED by docs/latex/tools/gen_phenomena_outputs.sh -- do not edit by hand."
  echo "% binary: $(sha256sum "$BIN" | cut -c1-16)...  host: $(uname -m)  date: $(date -u +%Y-%m-%d)"
} > "$COSTS"

for name in $SNIPPETS; do
  src="$EX/$name.oc"
  [ -f "$src" ] || { echo "MISSING $src"; fail=1; continue; }
  raw="$TMP/$name.raw"
  ( cd "$EX" && exec /usr/bin/time -f "%e %M %x" -o "$TMP/$name.time" "$BIN" --script "$name.oc" ) >"$raw" 2>&1 &
  tp=$!
  killed=0
  while kill -0 "$tp" 2>/dev/null; do
    c=$(pgrep -P "$tp" | head -1)
    if [ -n "$c" ]; then
      r=$(awk '/VmRSS/{print $2}' "/proc/$c/status" 2>/dev/null)
      if [ -n "$r" ] && [ "$r" -gt "$CAP_KB" ]; then kill -9 "$c"; killed=1; fi
    fi
    sleep 0.5
  done
  wait "$tp"
  read -r wall rss code < "$TMP/$name.time" 2>/dev/null || { wall=?; rss=0; code=?; }
  [ "$killed" = 1 ] && code="watchdog"
  grep -v -e '^#~ ' -e '^EFFECTIVE HECKEZ_LOCAL_PAR ' "$raw" > "$TMP/$name.out"
  mib=$(( rss / 1024 ))
  printf 'PG_SNIPPET %-28s exit=%s wall_s=%s peak_rss_mib=%s\n' "$name" "$code" "$wall" "$mib"
  if [ "$code" != "0" ]; then fail=1; tail -5 "$TMP/$name.out"; continue; fi
  printf '\\expandafter\\def\\csname pgcost@%s\\endcsname{%s\\,s, %s\\,MiB}\n' "$name" "$wall" "$mib" >> "$COSTS"
  if [ "$MODE" = "--check" ]; then
    if ! diff -u "$OUTDIR/$name.out" "$TMP/$name.out" > "$TMP/$name.diff"; then
      echo "DRIFT $name:"; head -20 "$TMP/$name.diff"; fail=1
    fi
  else
    cp "$TMP/$name.out" "$OUTDIR/$name.out"
  fi
done

if [ "$MODE" != "--check" ] && [ "$fail" = 0 ]; then cp "$COSTS" "$OUTDIR/costs.tex"; fi
if [ "$fail" = 0 ]; then echo "PG_OUTPUTS mode=${MODE:-emit} snippets=$(echo $SNIPPETS | wc -w) verdict=OK"; else echo "PG_OUTPUTS mode=${MODE:-emit} verdict=FAIL"; fi
exit "$fail"
